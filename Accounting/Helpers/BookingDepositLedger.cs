using Accounting.Data;
using Accounting.Models.Entities;
using Accounting.Models.Enums;
using Microsoft.EntityFrameworkCore;

namespace Accounting.Helpers;

/// <summary>หัว JE หนึ่งใบที่ผูกการจอง (ข้อเท็จจริงจากฐาน)</summary>
public sealed record BookingJournalFact(Guid Id, string EntryNumber, JournalEntryStatus Status, Guid? OriginalEntryId,
    Guid? SourceDocumentId, bool IsAutoGenerated, DateTime EntryDate);

/// <summary>ภาพบัญชีมัดจำของการจองหนึ่งรายการ (tenant แล้ว) — ผลของ <see cref="BookingDepositLedger.LoadAsync"/></summary>
public sealed class BookingDepositSnapshot
{
    public required string Key { get; init; }
    /// <summary>พบร่องรอยการจองนี้ในระบบ (JE ใด ๆ หรือเอกสารใด ๆ รวมใบที่ถูกยกเลิก) — false ⇒ ตัวตัดสินไม่ตัดสิน</summary>
    public required bool TraceFound { get; init; }
    /// <summary>บรรทัดที่อยู่ในสมุด (Posted + Reversed) ของบัญชีมัดจำ/รับล่วงหน้า</summary>
    public required IReadOnlyList<DepositLedgerLine> Lines { get; init; }
    public required IReadOnlyList<BookingJournalFact> Entries { get; init; }
    /// <summary>เลขเอกสารที่ผูกการจองนี้และถูกยกเลิกแล้ว (ใช้ในข้อความเท่านั้น — ตัวตัดสินคือยอดในบัญชี)</summary>
    public required IReadOnlyList<string> VoidedDocumentNumbers { get; init; }
    public required IReadOnlyDictionary<Guid, string> AccountLabels { get; init; }

    public string AccountLabel(Guid id) => AccountLabels.TryGetValue(id, out var l) ? l : "บัญชีมัดจำ";

    /// <summary>JE ชุด <paramref name="roots"/> + ตัวกลับรายการของมันทุกชั้น (ตาม <c>OriginalEntryId</c>)</summary>
    public IReadOnlyCollection<Guid> FamilyOf(IEnumerable<Guid> roots)
    {
        var family = new HashSet<Guid>(roots);
        bool grew = true;
        while (grew)
        {
            grew = false;
            foreach (var e in Entries)
                if (e.OriginalEntryId is Guid o && family.Contains(o) && family.Add(e.Id)) grew = true;
        }
        return family;
    }

    /// <summary>เลข JE ที่ "ตัด" บัญชีนั้นและยังมีผล (Posted · ไม่ใช่ตัวกลับรายการ) นอกชุดที่ยกเลิก — ใช้บอกทางไปต่อ</summary>
    public IReadOnlyList<string> DrawingEntryNumbers(Guid accountId, IReadOnlyCollection<Guid> exclude)
    {
        var posted = Entries.Where(e => e.Status == JournalEntryStatus.Posted && e.OriginalEntryId == null && !exclude.Contains(e.Id))
            .ToDictionary(e => e.Id, e => e.EntryNumber);
        return Lines.Where(l => l.AccountId == accountId && posted.ContainsKey(l.JournalEntryId))
            .GroupBy(l => l.JournalEntryId)
            .Where(g => g.Sum(l => l.Debit - l.Credit) > BookingDepositDrawdown.Tolerance)
            .Select(g => posted[g.Key]).Distinct().OrderBy(n => n).ToList();
    }
}

/// <summary>
/// **ตัวโหลดข้อเท็จจริง "บัญชีมัดจำของการจอง" — ตัวเดียว** ของด่าน <see cref="BookingDepositDrawdown"/> (ทีม S 2026-10-26) ·
/// ผูก JE กับการจองด้วยเลขอ้างอิง/คำอธิบายของ JE · เอกสารต้นทาง (เลขจอง/อ้างอิง/หมายเหตุ) · ตัวกลับรายการของ JE เหล่านั้นทุกชั้น ·
/// นับบรรทัดด้วย <see cref="ReportableJournal.WhereInLedger(IQueryable{JournalEntryLine})"/> (คู่กลับรายการหักล้างกัน) · ทุก query กรอง <c>CompanyId</c>
/// </summary>
public static class BookingDepositLedger
{
    public static async Task<BookingDepositSnapshot> LoadAsync(AccountingDbContext db, Guid companyId, string key, CancellationToken ct = default)
    {
        // 1) เอกสารที่อ้างการจองนี้ (รวมใบที่ยกเลิก — เป็นร่องรอย) · ตรงตัวด้วย ExtractKeys (LIKE กว้างไว้ก่อน)
        var docs = (await db.Documents.AsNoTracking()
                .Where(d => d.CompanyId == companyId
                    && ((d.BookingNumber != null && d.BookingNumber.Contains(key))
                        || (d.Reference != null && d.Reference.Contains(key))
                        || (d.Notes != null && d.Notes.Contains(key))))
                .Select(d => new { d.Id, d.DocumentNumber, d.Status, d.BookingNumber, d.Reference, d.Notes })
                .Take(500)
                .ToListAsync(ct))
            .Where(d => BookingDepositDrawdown.Mentions(key, d.BookingNumber, d.Reference, d.Notes))
            .ToList();
        var docIds = docs.Select(d => d.Id).ToList();

        // 2) JE ที่อ้างการจองนี้ตรง ๆ หรือมาจากเอกสารข้อ 1
        var direct = (await db.JournalEntries.AsNoTracking()
                .Where(j => j.CompanyId == companyId && !j.IsDeleted
                    && ((j.Reference != null && j.Reference.Contains(key))
                        || (j.Description != null && j.Description.Contains(key))
                        || (j.SourceDocumentId != null && docIds.Contains(j.SourceDocumentId.Value))))
                .Select(j => new { j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate, j.Reference, j.Description })
                .Take(2000)
                .ToListAsync(ct))
            .Where(j => (j.SourceDocumentId is Guid s && docIds.Contains(s))
                || BookingDepositDrawdown.Mentions(key, j.Reference, j.Description))
            .Select(j => new BookingJournalFact(j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate))
            .ToList();

        // 3) ตัวกลับรายการ (ลูกทุกชั้น) + ใบต้นของตัวกลับที่อ้างการจอง — คู่กลับรายการต้องอยู่ครบจึงหักล้างกันถูก
        var entries = direct.ToDictionary(e => e.Id);
        var frontier = entries.Keys.ToList();
        for (var depth = 0; depth < 10 && frontier.Count > 0; depth++)
        {
            var kids = await db.JournalEntries.AsNoTracking()
                .Where(j => j.CompanyId == companyId && !j.IsDeleted && j.OriginalEntryId != null && frontier.Contains(j.OriginalEntryId.Value))
                .Select(j => new BookingJournalFact(j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate))
                .ToListAsync(ct);
            frontier = kids.Where(k => entries.TryAdd(k.Id, k)).Select(k => k.Id).ToList();
        }
        var parentIds = entries.Values.Where(e => e.OriginalEntryId is Guid o && !entries.ContainsKey(o))
            .Select(e => e.OriginalEntryId!.Value).Distinct().ToList();
        if (parentIds.Count > 0)
        {
            var parents = await db.JournalEntries.AsNoTracking()
                .Where(j => j.CompanyId == companyId && !j.IsDeleted && parentIds.Contains(j.Id))
                .Select(j => new BookingJournalFact(j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate))
                .ToListAsync(ct);
            foreach (var p in parents) entries.TryAdd(p.Id, p);
        }

        // 4) บรรทัดที่อยู่ในสมุดของบัญชีมัดจำ/รับล่วงหน้า
        var ids = entries.Keys.ToList();
        var rawLines = await db.JournalEntryLines.AsNoTracking()
            .WhereInLedger()
            .Where(l => !l.IsDeleted && ids.Contains(l.JournalEntryId) && l.JournalEntry.CompanyId == companyId)
            .Join(db.ChartOfAccounts.AsNoTracking().Where(a => a.CompanyId == companyId), l => l.AccountId, a => a.Id,
                (l, a) => new { l.JournalEntryId, l.AccountId, l.DebitAmount, l.CreditAmount, a.AccountType, a.AccountCode, a.AccountName })
            .ToListAsync(ct);
        var depositLines = rawLines.Where(l => BookingDepositDrawdown.IsDepositLiabilityAccount(l.AccountType, l.AccountCode, l.AccountName)).ToList();

        return new BookingDepositSnapshot
        {
            Key = key,
            TraceFound = docs.Count > 0 || entries.Count > 0,
            Lines = depositLines.Select(l => new DepositLedgerLine(l.JournalEntryId, entries[l.JournalEntryId].EntryNumber,
                l.AccountId, l.DebitAmount, l.CreditAmount)).ToList(),
            Entries = entries.Values.ToList(),
            VoidedDocumentNumbers = docs.Where(d => d.Status == DocumentStatus.Voided).Select(d => d.DocumentNumber).Distinct().ToList(),
            AccountLabels = depositLines.GroupBy(l => l.AccountId).ToDictionary(g => g.Key, g => $"{g.First().AccountCode} {g.First().AccountName}"),
        };
    }

    /// <summary>ด่านฝั่งรับ JE ใหม่ (จากระบบภายนอก): บรรทัดที่จะลง + ข้อความอ้างอิงของ JE ⇒ ข้อความปฏิเสธ (null = ผ่าน/ไม่เกี่ยว) ·
    /// <paramref name="accounts"/> = ผังของบรรทัด (tenant แล้ว)</summary>
    public static async Task<string?> DrawdownProblemAsync(AccountingDbContext db, Guid companyId,
        IEnumerable<JournalEntryLine> lines, IReadOnlyDictionary<Guid, ChartOfAccount> accounts,
        string? reference, string? description, CancellationToken ct = default)
    {
        var incoming = lines
            .Where(l => accounts.TryGetValue(l.AccountId, out var a)
                && BookingDepositDrawdown.IsDepositLiabilityAccount(a.AccountType, a.AccountCode, a.AccountName))
            .GroupBy(l => l.AccountId)
            .ToDictionary(g => g.Key, g => g.Sum(l => l.DebitAmount - l.CreditAmount));
        if (!incoming.Any(kv => kv.Value > BookingDepositDrawdown.Tolerance)) return null;   // ไม่ได้ตัดมัดจำ ⇒ ไม่แตะ
        var lineTexts = lines.Select(l => l.Description).Prepend(description).Prepend(reference).ToArray();
        foreach (var key in BookingDepositDrawdown.ExtractKeys(lineTexts))
        {
            var snap = await LoadAsync(db, companyId, key, ct);
            var shortfalls = BookingDepositDrawdown.EvaluateDrawdown(incoming, snap.Lines, snap.TraceFound);
            if (shortfalls.Count > 0)
                return BookingDepositDrawdown.DrawdownMessage(key, shortfalls,
                    id => accounts.TryGetValue(id, out var a) ? $"{a.AccountCode} {a.AccountName}" : snap.AccountLabel(id),
                    snap.VoidedDocumentNumbers);
        }
        return null;
    }

    /// <summary>ด่านฝั่งยกเลิก: ยกเลิก/กลับรายการ JE ชุด <paramref name="removedRootIds"/> (พร้อมตัวกลับรายการของมัน) ของรายการที่อ้างการจอง ⇒ ข้อความบล็อก
    /// (null = ยกเลิกได้) · <paramref name="what"/> = "ยกเลิกเอกสาร RV-…" / "กลับรายการ JV-…"</summary>
    public static async Task<string?> RemovalProblemAsync(AccountingDbContext db, Guid companyId,
        IReadOnlyCollection<Guid> removedRootIds, string?[] texts, string what, CancellationToken ct = default)
    {
        if (removedRootIds.Count == 0) return null;
        foreach (var key in BookingDepositDrawdown.ExtractKeys(texts))
        {
            var snap = await LoadAsync(db, companyId, key, ct);
            var removed = snap.FamilyOf(removedRootIds);
            var shortfalls = BookingDepositDrawdown.EvaluateRemoval(snap.Lines, removed);
            if (shortfalls.Count > 0)
                return BookingDepositDrawdown.RemovalMessage(key, what, shortfalls, snap.AccountLabel,
                    shortfalls.SelectMany(s => snap.DrawingEntryNumbers(s.AccountId, removed)).Distinct().ToList());
        }
        return null;
    }
}

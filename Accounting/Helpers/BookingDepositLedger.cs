/// <summary>หัว JE หนึ่งใบที่ผูกการจอง (ข้อเท็จจริงจากฐาน)</summary>
public sealed record BookingJournalFact(Guid Id, string EntryNumber, JournalEntryStatus Status, Guid? OriginalEntryId,
    Guid? SourceDocumentId, bool IsAutoGenerated, DateTime EntryDate);

/// <summary>ภาพบัญชีมัดจำของการจองหนึ่งรายการ (tenant แล้ว) — ผลของ <see cref="BookingDepositLedger.LoadManyAsync"/></summary>
public sealed class BookingDepositSnapshot
{
    public required string Key { get; init; }
    /// <summary>ข้อมูลเกินเพดานการโหลด ⇒ <b>ห้ามตัดสิน</b> (ตัดสินจากข้อมูลไม่ครบ = อันตรายกว่าไม่ตอบ · ฝ่ายค้านข้อ 3)</summary>
    public required bool Truncated { get; init; }
    /// <summary>บรรทัดที่อยู่ในสมุด (Posted + Reversed) ของบัญชีมัดจำ/รับล่วงหน้า</summary>
    public required IReadOnlyList<DepositLedgerLine> Lines { get; init; }
    public required IReadOnlyList<BookingJournalFact> Entries { get; init; }
    /// <summary>เลขเอกสารที่ผูกการจองนี้และถูกยกเลิกแล้ว (ใช้ในข้อความเท่านั้น)</summary>
    public required IReadOnlyList<string> VoidedDocumentNumbers { get; init; }
    /// <summary>เอกสารต้นทางของ JE (id → เลขที่ · ยกเลิกแล้วไหม)</summary>
    public required IReadOnlyDictionary<Guid, (string Number, bool Voided)> SourceDocuments { get; init; }
    public required IReadOnlyDictionary<Guid, string> AccountLabels { get; init; }

    public string AccountLabel(Guid id) => AccountLabels.TryGetValue(id, out var l) ? l : "บัญชีมัดจำ";

    /// <summary>JE ชุด <paramref name="roots"/> + ตัวกลับรายการของมันทุกชั้น (ตาม <c>OriginalEntryId</c>)</summary>
    public IReadOnlyCollection<Guid> FamilyOf(IEnumerable<Guid> roots)
    {
        var family = new HashSet<Guid>(roots);
        bool grew = true;
        while (grew)
        {
            grew = false;
            foreach (var e in Entries)
                if (e.OriginalEntryId is Guid o && family.Contains(o) && family.Add(e.Id)) grew = true;
        }
        return family;
    }

    /// <summary>รายการที่ "ตัด" บัญชีนั้นและยังมีผล (Posted · ไม่ใช่ตัวกลับรายการ) นอกชุดที่ยกเลิก — แยก JE สมุดรายวัน (กลับรายการได้)
    /// กับ JE ของเอกสาร (ต้องยกเลิกเอกสาร — ฝ่ายค้านข้อ 7)</summary>
    public (IReadOnlyList<string> Journals, IReadOnlyList<string> Documents) DrawingSources(Guid accountId, IReadOnlyCollection<Guid> exclude)
    {
        var posted = Entries.Where(e => e.Status == JournalEntryStatus.Posted && e.OriginalEntryId == null && !exclude.Contains(e.Id))
            .ToDictionary(e => e.Id);
        var drawing = Lines.Where(l => l.AccountId == accountId && posted.ContainsKey(l.JournalEntryId))
            .GroupBy(l => l.JournalEntryId)
            .Where(g => g.Sum(l => l.Debit - l.Credit) > BookingDepositDrawdown.Tolerance)
            .Select(g => posted[g.Key]).ToList();
        var journals = drawing.Where(e => e.SourceDocumentId == null).Select(e => e.EntryNumber).Distinct().OrderBy(n => n).ToList();
        var docs = drawing.Where(e => e.SourceDocumentId != null)
            .Select(e => SourceDocuments.TryGetValue(e.SourceDocumentId!.Value, out var d) ? d.Number : e.EntryNumber)
            .Distinct().OrderBy(n => n).ToList();
        return (journals, docs);
    }
}

/// <summary>
/// **ตัวโหลดข้อเท็จจริง "บัญชีมัดจำของการจอง" — ตัวเดียว** ของด่าน <see cref="BookingDepositDrawdown"/> (ทีม S 2026-10-26 · หลังฝ่ายค้าน)
///
/// <para>ผูก JE กับการจองแบบ<b>ตรงตัว</b>: ค้นในฐานด้วย <c>Document.BookingNumber ==</c> (มี index) หรือข้อความที่มีเลขเต็ม (LIKE ใช้กรองหยาบเท่านั้น)
/// แล้วยืนยันด้วย <c>BookingDepositDrawdown.ExtractKeys</c> ตามชุดรูปแบบของบริษัท (<see cref="PatternsAsync"/> — ค่าเริ่มต้น + ที่ตั้งต่อคีย์ · R-56) (เลขเต็ม — RES-101-2609-0001 ไม่ปน 101) · ตัวกลับรายการของ JE เหล่านั้นทุกชั้น ·
/// นับบรรทัดด้วย <see cref="ReportableJournal.WhereInLedger(IQueryable{JournalEntryLine})"/> · ไม่มี Take ที่ตัดผลเงียบ — เกินเพดาน ⇒ <c>Truncated</c> (ไม่ตัดสิน) ·
/// หลายการจองโหลดเป็นชุดเดียว (ชุดละ <see cref="KeyChunk"/> เลข) · ทุก query กรอง <c>CompanyId</c></para>
/// </summary>
public static class BookingDepositLedger
{
    /// <summary>เพดานแถวต่อชุด — เกิน ⇒ ทุกการจองในชุดเป็น Truncated</summary>
    public const int RowCap = 20000;
    public const int KeyChunk = 40;

    /// <summary>ผังที่ระบบตั้งเป็นบัญชีมัดจำจริง (ประเภทเงินมัดจำ · ผังพักมัดจำของที่พัก) — ตัวหลักของ <see cref="BookingDepositDrawdown.IsDepositLiabilityAccount"/></summary>
    public static async Task<IReadOnlyCollection<string>> ConfiguredDepositCodesAsync(AccountingDbContext db, Guid companyId, CancellationToken ct = default)
    {
        var kinds = await db.DepositKinds.AsNoTracking()
            .Where(k => k.CompanyId == companyId && k.LiabilityAccountCode != null)
            .Select(k => k.LiabilityAccountCode!).ToListAsync(ct);
        var props = await db.LodgingProperties.AsNoTracking()
            .Where(p => p.CompanyId == companyId && p.DepositDeferredAccountCode != null)
            .Select(p => p.DepositDeferredAccountCode!).ToListAsync(ct);
        return kinds.Concat(props).Select(c => c.Trim()).Where(c => c.Length > 0).ToHashSet();
    }

    /// <summary>ชุดรูปแบบเลขอ้างอิงการจองของบริษัท — ค่าเริ่มต้น 2 รูป + ที่เจ้าของตั้งเพิ่มในทุกคีย์ integration ของบริษัท
    /// (<c>ExternalIntegration.BookingRefPatternsJson</c> · รวมคีย์ที่ปิดใช้แล้วด้วย — มัดจำที่ลงไว้สมัยคีย์นั้นยังต้องถูกเห็น · ไม่รวมที่ลบ) ·
    /// ตัวตั้ง/ตัวรวม = <see cref="BookingRefPattern.Merge"/> (R-56 · ทีม W10 2026-10-26) · ทุกเส้นของด่านอ่านจากที่นี่ที่เดียว</summary>
    public static async Task<IReadOnlyList<Regex>> PatternsAsync(AccountingDbContext db, Guid companyId, CancellationToken ct = default)
    {
        var jsons = await db.ExternalIntegrations.AsNoTracking()
            .Where(i => i.CompanyId == companyId && !i.IsDeleted && i.BookingRefPatternsJson != null)
            .Select(i => i.BookingRefPatternsJson)
            .ToListAsync(ct);
        return BookingRefPattern.Merge(jsons);
    }

    public static async Task<IReadOnlyDictionary<string, BookingDepositSnapshot>> LoadManyAsync(
        AccountingDbContext db, Guid companyId, IReadOnlyCollection<string> keys, CancellationToken ct = default)
        => await LoadManyAsync(db, companyId, keys, await PatternsAsync(db, companyId, ct), ct);

    /// <summary>เหมือน <see cref="LoadManyAsync(AccountingDbContext, Guid, IReadOnlyCollection{string}, CancellationToken)"/> แต่ผู้เรียกส่งชุดรูปแบบที่โหลดไว้แล้ว
    /// (ด่าน/รายงานที่ใช้ชุดเดียวกันทั้งคำขอ — ไม่โหลดซ้ำ)</summary>
    public static async Task<IReadOnlyDictionary<string, BookingDepositSnapshot>> LoadManyAsync(
        AccountingDbContext db, Guid companyId, IReadOnlyCollection<string> keys, IReadOnlyList<Regex> patterns, CancellationToken ct = default)
    {
        var result = new Dictionary<string, BookingDepositSnapshot>();
        var configured = await ConfiguredDepositCodesAsync(db, companyId, ct);
        foreach (var chunk in keys.Distinct().Chunk(KeyChunk))
            foreach (var kv in await LoadChunkAsync(db, companyId, chunk, configured, patterns, ct))
                result[kv.Key] = kv.Value;
        return result;
    }

    private static async Task<Dictionary<string, BookingDepositSnapshot>> LoadChunkAsync(
        AccountingDbContext db, Guid companyId, string[] keys, IReadOnlyCollection<string> configured, IReadOnlyList<Regex> patterns, CancellationToken ct)
    {
        var keySet = keys.ToHashSet();
        var bookingNumbers = keys.SelectMany(BookingDepositDrawdown.BookingNumberForms).ToList();
        bool truncated = false;

        // 1) เอกสารที่ผูกการจอง: เลขจองตรงตัว (index) หรือข้อความที่มีเลขเต็ม → ยืนยันตรงตัวด้วย ExtractKeys
        var docText = AnyContains<Document>(keys, d => d.Reference, d => d.Notes);
        var docRows = await db.Documents.AsNoTracking()
            .Where(d => d.CompanyId == companyId)
            .Where(Or(docText, d => d.BookingNumber != null && bookingNumbers.Contains(d.BookingNumber)))
            .Select(d => new { d.Id, d.DocumentNumber, d.Status, d.BookingNumber, d.Reference, d.Notes })
            .Take(RowCap + 1).ToListAsync(ct);
        if (docRows.Count > RowCap) truncated = true;
        var docKeys = new Dictionary<Guid, HashSet<string>>();
        foreach (var d in docRows)
        {
            var ks = BookingDepositDrawdown.ExtractKeys(patterns, d.BookingNumber, d.Reference, d.Notes).Where(keySet.Contains).ToHashSet();
            if (d.BookingNumber != null && keySet.Contains(d.BookingNumber.Trim())) ks.Add(d.BookingNumber.Trim());
            if (ks.Count > 0) docKeys[d.Id] = ks;
        }
        var docIds = docKeys.Keys.ToList();

        // 2) JE ที่อ้างการจองตรง ๆ หรือมาจากเอกสารข้อ 1
        var jeText = AnyContains<JournalEntry>(keys, j => j.Reference, j => j.Description);
        var directRows = await db.JournalEntries.AsNoTracking()
            .Where(j => j.CompanyId == companyId && !j.IsDeleted)
            .Where(Or(jeText, j => j.SourceDocumentId != null && docIds.Contains(j.SourceDocumentId.Value)))
            .Select(j => new { j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate, j.Reference, j.Description })
            .Take(RowCap + 1).ToListAsync(ct);
        if (directRows.Count > RowCap) truncated = true;

        var entries = new Dictionary<Guid, BookingJournalFact>();
        var entryKeys = new Dictionary<Guid, HashSet<string>>();
        foreach (var j in directRows)
        {
            var ks = BookingDepositDrawdown.ExtractKeys(patterns, j.Reference, j.Description).Where(keySet.Contains).ToHashSet();
            if (j.SourceDocumentId is Guid s && docKeys.TryGetValue(s, out var dk)) ks.UnionWith(dk);
            if (ks.Count == 0) continue;
            entries[j.Id] = new BookingJournalFact(j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate);
            entryKeys[j.Id] = ks;
        }

        // 3) ตัวกลับรายการ (ลูกทุกชั้น · สืบเลขการจองจากใบต้น) + ใบต้นของตัวกลับที่อ้างการจอง (สืบจากลูก)
        var frontier = entries.Keys.ToList();
        for (var depth = 0; depth < 10 && frontier.Count > 0; depth++)
        {
            var kids = await db.JournalEntries.AsNoTracking()
                .Where(j => j.CompanyId == companyId && !j.IsDeleted && j.OriginalEntryId != null && frontier.Contains(j.OriginalEntryId.Value))
                .Select(j => new BookingJournalFact(j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate))
                .ToListAsync(ct);
            var next = new List<Guid>();
            foreach (var k in kids)
            {
                var inherited = entryKeys[k.OriginalEntryId!.Value];
                if (entries.TryAdd(k.Id, k)) { entryKeys[k.Id] = new HashSet<string>(inherited); next.Add(k.Id); }
                else entryKeys[k.Id].UnionWith(inherited);
            }
            frontier = next;
        }
        var parentIds = entries.Values.Where(e => e.OriginalEntryId is Guid o && !entries.ContainsKey(o))
            .Select(e => e.OriginalEntryId!.Value).Distinct().ToList();
        if (parentIds.Count > 0)
        {
            var parents = await db.JournalEntries.AsNoTracking()
                .Where(j => j.CompanyId == companyId && !j.IsDeleted && parentIds.Contains(j.Id))
                .Select(j => new BookingJournalFact(j.Id, j.EntryNumber, j.Status, j.OriginalEntryId, j.SourceDocumentId, j.IsAutoGenerated, j.EntryDate))
                .ToListAsync(ct);
            foreach (var p in parents)
            {
                entries.TryAdd(p.Id, p);
                var fromKids = entries.Values.Where(e => e.OriginalEntryId == p.Id).SelectMany(e => entryKeys[e.Id]);
                entryKeys[p.Id] = new HashSet<string>(fromKids);
            }
        }

        // 4) บรรทัดที่อยู่ในสมุดของบัญชีมัดจำ/รับล่วงหน้า (ชุดเดียว)
        var ids = entries.Keys.ToList();
        var rawLines = await db.JournalEntryLines.AsNoTracking()
            .WhereInLedger()
            .Where(l => !l.IsDeleted && ids.Contains(l.JournalEntryId) && l.JournalEntry.CompanyId == companyId)
            .Join(db.ChartOfAccounts.AsNoTracking().Where(a => a.CompanyId == companyId), l => l.AccountId, a => a.Id,
                (l, a) => new { l.JournalEntryId, l.AccountId, l.DebitAmount, l.CreditAmount, l.Description, a.AccountType, a.AccountCode, a.AccountName })
            .ToListAsync(ct);
        var depositLines = rawLines
            .Where(l => BookingDepositDrawdown.IsDepositLiabilityAccount(l.AccountType, l.AccountCode, l.AccountName, configured)).ToList();

        // 5) เอกสารต้นทางของ JE (ข้อความทางไปต่อ — JE ของเอกสารต้องยกเลิกเอกสาร)
        var srcIds = entries.Values.Where(e => e.SourceDocumentId != null).Select(e => e.SourceDocumentId!.Value).Distinct().ToList();
        var srcDocs = new Dictionary<Guid, (string Number, bool Voided)>();
        if (srcIds.Count > 0)
            foreach (var sd in await db.Documents.AsNoTracking()
                         .Where(d => d.CompanyId == companyId && srcIds.Contains(d.Id))
                         .Select(d => new { d.Id, d.DocumentNumber, d.Status })
                         .ToListAsync(ct))
                srcDocs[sd.Id] = (sd.DocumentNumber, sd.Status == DocumentStatus.Voided);

        var labels = depositLines.GroupBy(l => l.AccountId).ToDictionary(g => g.Key, g => $"{g.First().AccountCode} {g.First().AccountName}");
        var snaps = new Dictionary<string, BookingDepositSnapshot>();
        foreach (var key in keys)
        {
            var mine = entries.Values.Where(e => entryKeys[e.Id].Contains(key)).ToList();
            var mineIds = mine.Select(e => e.Id).ToHashSet();
            snaps[key] = new BookingDepositSnapshot
            {
                Key = key,
                Truncated = truncated,
                // JE ที่หัวอ้างหลายการจอง (night audit) ⇒ นับเฉพาะบรรทัดที่ระบุการจองนี้ (ฝ่ายค้านข้อ 1 — ฝั่งยอดเดิมต้องแยกแบบเดียวกับฝั่งรับ)
                Lines = depositLines.Where(l => mineIds.Contains(l.JournalEntryId)
                        && (entryKeys[l.JournalEntryId].Count == 1 || BookingDepositDrawdown.Mentions(patterns, key, l.Description)))
                    .Select(l => new DepositLedgerLine(l.JournalEntryId, entries[l.JournalEntryId].EntryNumber, l.AccountId,
                        l.DebitAmount, l.CreditAmount, entries[l.JournalEntryId].EntryDate, entries[l.JournalEntryId].OriginalEntryId != null))
                    .ToList(),
                Entries = mine,
                VoidedDocumentNumbers = docRows.Where(d => d.Status == DocumentStatus.Voided && docKeys.TryGetValue(d.Id, out var dk) && dk.Contains(key))
                    .Select(d => d.DocumentNumber).Distinct().ToList(),
                SourceDocuments = srcDocs,
                AccountLabels = labels,
            };
        }
        return snaps;
    }

    /// <summary>ด่านฝั่งรับ JE ใหม่ (จากระบบภายนอก — สมุดรายวัน · สรุปรายวัน): ข้อความปฏิเสธ (null = ผ่าน/ไม่เกี่ยว) ·
    /// แยกยอดต่อการจองตามบรรทัด (<c>BookingDepositDrawdown.AssignDrawdown</c> ด้วยชุดรูปแบบของบริษัท) · อยู่ในธุรกรรม ⇒ ล็อกต่อการจอง
    /// (<see cref="AdvisoryLockKey.BookingDeposit"/>) ก่อนอ่านยอด กันสองคำขอพร้อมกันผ่านทั้งคู่ · <paramref name="accounts"/> = ผังของบรรทัด (tenant แล้ว)</summary>
    public static async Task<string?> DrawdownProblemAsync(AccountingDbContext db, Guid companyId,
        IReadOnlyList<JournalEntryLine> lines, IReadOnlyDictionary<Guid, ChartOfAccount> accounts,
        string? reference, string? description, CancellationToken ct = default)
    {
        var configured = await ConfiguredDepositCodesAsync(db, companyId, ct);
        // รูปแบบเลขอ้างอิง = ค่าเริ่มต้น + ที่ตั้งต่อคีย์ของบริษัท (R-56) — ชุดเดียวทั้งฝั่งแยกยอดที่เข้ามาและฝั่งโหลดยอดเดิม (ห้ามต่างกัน)
        var patterns = await PatternsAsync(db, companyId, ct);
        bool IsDep(Guid id) => accounts.TryGetValue(id, out var a)
            && BookingDepositDrawdown.IsDepositLiabilityAccount(a.AccountType, a.AccountCode, a.AccountName, configured);
        var perKey = BookingDepositDrawdown.AssignDrawdown(patterns, new[] { reference, description },
            lines.Select(l => new IncomingJournalLine(l.AccountId, l.DebitAmount, l.CreditAmount, l.Description)), IsDep);
        if (perKey.Count == 0) return null;   // ไม่ได้ตัดมัดจำของการจองที่ระบุชัด ⇒ ไม่แตะ

        if (db.Database.CurrentTransaction != null)
            foreach (var key in perKey.Keys.OrderBy(k => k, StringComparer.Ordinal))
                await db.Database.ExecuteSqlRawAsync("SELECT pg_advisory_xact_lock({0})",
                    new object[] { AdvisoryLockKey.For(companyId, AdvisoryLockKey.BookingDeposit, key) }, ct);

        var snaps = await LoadManyAsync(db, companyId, perKey.Keys.ToList(), patterns, ct);
        foreach (var (key, incoming) in perKey)
        {
            if (!snaps.TryGetValue(key, out var snap) || snap.Truncated) continue;
            var shortfalls = BookingDepositDrawdown.EvaluateDrawdown(incoming, snap.Lines);
            if (shortfalls.Count > 0)
                return BookingDepositDrawdown.DrawdownMessage(key, shortfalls,
                    id => accounts.TryGetValue(id, out var a) ? $"{a.AccountCode} {a.AccountName}" : snap.AccountLabel(id),
                    snap.VoidedDocumentNumbers);
        }
        return null;
    }

    /// <summary>ด่านฝั่งยกเลิก: ยกเลิก/กลับรายการ JE ชุด <paramref name="removedRootIds"/> (พร้อมตัวกลับรายการ) ของรายการที่อ้างการจอง ⇒ ข้อความบล็อก
    /// (null = ยกเลิกได้) · <paramref name="what"/> = "ยกเลิกเอกสาร RV-…" / "กลับรายการ JV-…"</summary>
    public static async Task<string?> RemovalProblemAsync(AccountingDbContext db, Guid companyId,
        IReadOnlyCollection<Guid> removedRootIds, string?[] texts, string what, CancellationToken ct = default)
    {
        if (removedRootIds.Count == 0) return null;
        var patterns = await PatternsAsync(db, companyId, ct);
        var keys = BookingDepositDrawdown.ExtractKeys(patterns, texts);
        if (keys.Count == 0) return null;
        var snaps = await LoadManyAsync(db, companyId, keys, patterns, ct);
        foreach (var key in keys)
        {
            if (!snaps.TryGetValue(key, out var snap) || snap.Truncated) continue;
            var removed = snap.FamilyOf(removedRootIds);
            var shortfalls = BookingDepositDrawdown.EvaluateRemoval(snap.Lines, removed);
            if (shortfalls.Count == 0) continue;
            var sources = shortfalls.Select(s => snap.DrawingSources(s.AccountId, removed)).ToList();
            return BookingDepositDrawdown.RemovalMessage(key, what, shortfalls, snap.AccountLabel,
                sources.SelectMany(s => s.Journals).Distinct().ToList(),
                sources.SelectMany(s => s.Documents).Distinct().ToList());
        }
        return null;
    }

    // ── ตัวประกอบเงื่อนไข OR สำหรับหลายเลขการจอง (แปลเป็น SQL ได้ — คีย์เป็นตัวเลข/ขีดล้วนจาก ExtractKeys) ──

    private static Expression<Func<T, bool>> AnyContains<T>(IReadOnlyCollection<string> keys, params Expression<Func<T, string?>>[] fields)
    {
        var p = Expression.Parameter(typeof(T), "x");
        var contains = typeof(string).GetMethod(nameof(string.Contains), new[] { typeof(string) })!;
        Expression body = Expression.Constant(false);
        foreach (var f in fields)
        {
            var member = new Rebind(f.Parameters[0], p).Visit(f.Body)!;
            foreach (var k in keys)
                body = Expression.OrElse(body, Expression.AndAlso(
                    Expression.NotEqual(member, Expression.Constant(null, typeof(string))),
                    Expression.Call(member, contains, Expression.Constant(k, typeof(string)))));
        }
        return Expression.Lambda<Func<T, bool>>(body, p);
    }

    private static Expression<Func<T, bool>> Or<T>(Expression<Func<T, bool>> a, Expression<Func<T, bool>> b)
    {
        var p = a.Parameters[0];
        var bBody = new Rebind(b.Parameters[0], p).Visit(b.Body)!;
        return Expression.Lambda<Func<T, bool>>(Expression.OrElse(a.Body, bBody), p);
    }

    private sealed class Rebind : ExpressionVisitor
    {
        private readonly ParameterExpression _from, _to;
        public Rebind(ParameterExpression from, ParameterExpression to) { _from = from; _to = to; }
        protected override Expression VisitParameter(ParameterExpression node) => node == _from ? _to : base.VisitParameter(node);
    }

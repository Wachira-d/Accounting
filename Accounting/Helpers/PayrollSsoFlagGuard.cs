namespace Accounting.Helpers;

/// <summary>
/// ด่าน "ฐาน ปกส. ที่กรอกด้วยมือขัดกับธงประกันสังคมของพนักงาน" — ตัวเดียวของ ➕ เพิ่มพนักงานเข้ารอบ และ ✏️ แก้ยอด
/// (เมื่อฐานเปลี่ยน) · รอบ 201 ทีม PR2 · ผลฝ่ายค้าน PR1 X1
///
/// <para>ที่มา: ➕ บังคับกรอกฐาน ปกส. (ระบบไม่เดา) แต่ไม่เคยเทียบกับ <c>Employee.IsSubjectToSocialSecurity</c> ⇒
/// (ก) พนักงานที่ระบุว่า<b>ไม่อยู่</b>ใน ม.33 ถูกหักเงินสมทบและไปโผล่ในไฟล์ สปส.1-10 ·
/// (ข) พนักงานที่<b>อยู่</b>ใน ม.33 มีรายได้แต่ฐาน 0 ⇒ ไม่หัก/ไม่นำส่ง = นำส่งขาดเงียบ (เงินเพิ่ม ม.49) —
/// สองทิศนี้คือเงินสมทบผิดที่ผู้ใช้มองไม่เห็นจนวันตรวจ (DOCTRINE G5) ⇒ ปฏิเสธพร้อมทางไปต่อ</para>
///
/// <para>เส้นคำนวณรอบไม่ต้องใช้ด่านนี้: <c>SsoWageBase.ForPeriod</c> อ่านธงเองแล้ว (ไม่อยู่ ⇒ ฐาน 0 ·
/// อยู่ + มีเงินจ่าย ⇒ ขั้นต่ำ 1,650)</para>
/// </summary>
public static class PayrollSsoFlagGuard
{
    /// <summary>ตรวจคู่ "ธงพนักงาน × ฐานที่กรอก × รายได้รวมของงวด" — null = ผ่าน · ข้อความ = เหตุผลพร้อมทางไปต่อ</summary>
    /// <param name="employeeLabel">ชื่อ (รหัส) พนักงานสำหรับข้อความ</param>
    public static string? Check(bool employeeSubjectToSso, decimal ssoBase, decimal grossIncome, string employeeLabel)
    {
        if (!employeeSubjectToSso && ssoBase > 0)
            return $"{employeeLabel} ถูกระบุว่าไม่อยู่ในระบบประกันสังคม (ม.33) แต่กรอกฐานค่าจ้าง ปกส. {ssoBase:N2} บาท — "
                + "ถ้าพนักงานไม่อยู่ในระบบจริง ให้ใส่ฐาน 0 · ถ้าอยู่ในระบบ ให้แก้ธง “อยู่ในระบบประกันสังคม” ที่หน้าพนักงานก่อน "
                + "แล้วค่อยบันทึกยอดนี้ (ไม่งั้นเงินสมทบจะถูกหักและไปอยู่ในไฟล์ สปส.1-10 ของคนที่ระบบบอกว่าไม่ได้ขึ้นทะเบียน)";
        if (employeeSubjectToSso && ssoBase <= 0 && grossIncome > 0)
            return $"{employeeLabel} อยู่ในระบบประกันสังคม (ม.33) และมีรายได้งวดนี้ {grossIncome:N2} บาท แต่ฐานค่าจ้าง ปกส. เป็น 0 — "
                + "ระบบจะไม่หัก/ไม่นำส่งเงินสมทบ (นำส่งขาดมีเงินเพิ่มตาม ม.49) · กรอกฐานค่าจ้างของงวดนี้ "
                + "(ค่าจ้างตาม ม.5 — ต่ำกว่า 1,650 ระบบคิดขั้นต่ำให้) หรือถ้าพนักงานพ้นจากระบบแล้ว "
                + "ให้แก้ธง “อยู่ในระบบประกันสังคม” ที่หน้าพนักงานก่อน";
        return null;
    }

    /// <summary>รอบ 202 (ผู้ใช้รายงาน "แก้ไขยอดประกันสังคมไม่ได้"): ฐาน ปกส. ที่กรอกมากกว่ารายได้รวมของงวด — ค่าจ้างตาม ม.33 คือค่าจ้างที่จ่ายจริง
    /// ในงวด จึงแทบเป็นไปไม่ได้ที่ฐานจะสูงกว่ารายได้ (เคสจริง: เข้างานกลางเดือน แก้เงินเดือนงวดเป็น 7,000 แต่ฐานค้างเงินเดือนเต็ม 30,000
    /// ⇒ หัก ปกส. 875 แทน 350) · <b>ไม่บล็อก</b> (ผู้ใช้อาจมีเหตุผลเฉพาะ) แต่บอกในข้อความผลลัพธ์ — null = ไม่มีอะไรต้องบอก</summary>
    public static string? BaseAboveWagesNotice(decimal ssoBase, decimal grossIncome)
        => ssoBase > 0 && grossIncome > 0 && ssoBase > grossIncome
            ? $"⚠️ ฐาน ปกส. {ssoBase:N2} บาท มากกว่ารายได้งวดนี้ {grossIncome:N2} บาท — เงินสมทบคิดจากค่าจ้างที่จ่ายจริงในงวด "
              + "ถ้าพนักงานเข้า/ออกกลางงวด ให้แก้ฐานเป็นค่าจ้างของงวดนี้ (ปุ่ม ✏️ แก้ยอด)"
            : null;
}

using Accounting.Models.DTOs.Accounting;

namespace Accounting.Helpers;

/// <summary>ข้อเท็จจริงของใบสำคัญหนึ่งใบที่ใช้ตัดสินว่า "เอกสารต้นทางคืออะไร" — service ค้นมาให้ (กรอง CompanyId ทุกตาราง)</summary>
public sealed record JournalSourceFacts(
    bool Hidden,
    Guid? SourceDocumentId,
    Guid? DocumentId,
    string? DocumentNumber,
    string? DocumentTypeTitle,
    Guid? PosOrderId,
    string? PosOrderNumber,
    Guid? PayrollRunId,
    string? PayrollLabel,
    Guid? FixedAssetId,
    string? FixedAssetLabel,
    Guid? ExpenseClaimId,
    string? ExpenseClaimNumber,
    Guid? OriginalEntryId,
    bool IsAutoGenerated);

/// <summary>
/// **ใบสำคัญ → เอกสารต้นทาง (ตัวตัดสินเดียว · ทีม M 2026-10-22)** — drill-down ของงบกำไรขาดทุนใช้ตัดสินว่าแต่ละรายการ "คลิกต่อไปที่ไหน"
///
/// <para><b>ข้อเท็จจริงของระบบ:</b> <c>JournalEntry.SourceDocumentId</c> ชี้ <c>Document</c> (ใบกำกับ/ใบเสร็จ/ใบสำคัญจ่าย/สลิป POS ที่ออก
/// ใบกำกับแล้ว ฯลฯ) · แหล่งอื่นไม่ตั้งฟิลด์นี้ แต่ผูก <b>ย้อนกลับ</b> ด้วย <c>JournalEntryId</c> บนตัวเอง: บิล POS (<c>PosOrder</c>) ·
/// รอบเงินเดือน (<c>PayrollRun</c>) · ค่าเสื่อม (<c>AssetDepreciation</c>) · ใบเบิก (<c>ExpenseClaim</c>) · ใบที่ไม่มีทั้งสองทาง
/// = <b>แสดงตามจริง</b> ว่าไม่มีเอกสารต้นทาง (หลักการ F2 ข้อ 3 — ห้ามแต่งลิงก์)</para>
///
/// <para>ลำดับ: ซ่อนตามสิทธิ์ (ไม่บอกแม้แต่ชนิด) → เอกสาร → บิล POS → เงินเดือน → ค่าเสื่อม → ใบเบิก → อ้างเอกสารที่หาไม่พบ →
/// กลับรายการ (ชี้ใบเดิม) → ระบบลงอัตโนมัติแต่ไม่ผูก → บันทึกมือ/รายการปรับปรุง</para>
/// </summary>
public static class JournalSourceLink
{
    /// <summary>ชนิดที่ "ไม่มีเอกสารต้นทางให้เปิด" — นับเป็น WithoutSourceCount ของ drill-down</summary>
    public static bool IsWithoutSource(string kind) => kind is "MissingDocument" or "AutoNoSource" or "Manual";

    public static string JournalHref(Guid entryId) => "/pages/journals.html?entryId=" + entryId.ToString("D");

    public static PnlSourceLink Resolve(JournalSourceFacts f)
    {
        if (f.Hidden)
            return new PnlSourceLink("Hidden", "[ซ่อน] ไม่มีสิทธิ์ดูเอกสารต้นทาง", null, null);
        if (f.DocumentId is Guid docId)
            return new PnlSourceLink("Document", Join(f.DocumentTypeTitle, f.DocumentNumber, "เอกสาร"),
                "/pages/documents.html?openDoc=" + docId.ToString("D"), null);
        if (f.PosOrderId is Guid posId)
            return new PnlSourceLink("PosOrder", Join("บิล POS", f.PosOrderNumber, "บิล POS"),
                "/pages/pos-reports.html?orderId=" + posId.ToString("D"), null);
        if (f.PayrollRunId is Guid runId)
            return new PnlSourceLink("Payroll", Join("รอบเงินเดือน", f.PayrollLabel, "รอบเงินเดือน"),
                "/pages/payroll.html?runId=" + runId.ToString("D"), null);
        if (f.FixedAssetId is Guid assetId)
            return new PnlSourceLink("Depreciation", Join("ค่าเสื่อมราคา", f.FixedAssetLabel, "ค่าเสื่อมราคา"),
                "/pages/fixed-assets.html?id=" + assetId.ToString("D"), null);
        if (f.ExpenseClaimId is Guid claimId)
            return new PnlSourceLink("ExpenseClaim", Join("ใบเบิกค่าใช้จ่าย", f.ExpenseClaimNumber, "ใบเบิกค่าใช้จ่าย"),
                "/pages/expense.html?claimId=" + claimId.ToString("D"), null);
        if (f.SourceDocumentId.HasValue)
            return new PnlSourceLink("MissingDocument", "ไม่พบเอกสารต้นทางที่อ้างไว้",
                null, "ใบสำคัญอ้างเอกสารที่ถูกลบหรือไม่อยู่ในบริษัทนี้ — ดูรายละเอียดที่ใบสำคัญ");
        if (f.OriginalEntryId is Guid orig)
            return new PnlSourceLink("Reversal", "กลับรายการของใบสำคัญเดิม", JournalHref(orig),
                "เปิดใบสำคัญเดิมเพื่อดูเอกสารต้นทาง");
        if (f.IsAutoGenerated)
            return new PnlSourceLink("AutoNoSource", "ระบบลงอัตโนมัติ — ไม่ได้ผูกเอกสารต้นทาง", null,
                "ดูคำอธิบาย/เลขอ้างอิงของใบสำคัญ");
        return new PnlSourceLink("Manual", "รายการปรับปรุง/บันทึกด้วยมือ — ไม่มีเอกสารต้นทาง", null, null);
    }

    private static string Join(string? prefix, string? number, string fallback)
    {
        var p = string.IsNullOrWhiteSpace(prefix) ? null : prefix.Trim();
        var n = string.IsNullOrWhiteSpace(number) ? null : number.Trim();
        return (p, n) switch
        {
            (null, null) => fallback,
            (null, _) => n!,
            (_, null) => p!,
            _ => p + " " + n,
        };
    }
}

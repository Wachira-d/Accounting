using Accounting.Models.Enums;

namespace Accounting.Helpers;

/// <summary>แก้ "อายุใช้งาน · มูลค่าซาก · วิธีคิดค่าเสื่อม" ของสินทรัพย์ที่ลงทะเบียนแล้ว — ตัวตัดสินเดียว (รอบ 200 ทีม R · A12/E-04)
///
/// ═══ ที่มา ═══
/// หน้าแก้ไขสินทรัพย์ (รวมปุ่ม "ตรวจสอบและยืนยัน" ของสินทรัพย์ที่ OCR ขึ้นทะเบียนให้) เปิดให้แก้ราคาทุน/อายุ/วิธีคิด/วันที่ซื้อ
/// แต่ <c>UpdateFixedAssetRequest</c> ไม่มีช่องเหล่านี้ ⇒ ขึ้น "แก้ไขสำเร็จ" + ปลด NeedsReview + ออกเลข FA จริง แต่ค่าไม่เข้าเลย
/// ⇒ ค่าเสื่อมเดินบนตัวเลขเดิมที่ผิด (silent no-op · กฎเหล็ก #4 A)
///
/// ═══ กติกา ═══
/// • อายุ/ซาก/วิธีคิด แก้ได้ <b>ก่อนมีค่าเสื่อมลงบัญชี</b> (ตารางที่ยังไม่ลงบัญชีถูกสร้างใหม่) — มีงวดลงบัญชีแล้ว = ปฏิเสธพร้อมทางไปต่อ
///   (การเปลี่ยนประมาณการหลังเริ่มคิดค่าเสื่อมต้องมีผลไปข้างหน้า TFRS บทที่ 10 — เส้นนั้นคือ <see cref="DepreciationEstimateChange"/>
///   ผ่านปุ่ม “ปรับอายุการใช้งาน” (รอบ 201 A-IN3) ⇒ หน้าแก้ไขไม่แก้ย้อนหลังเงียบ ๆ)
/// • ราคาทุน/วันที่ซื้อ/ประเภท/สัญญาเช่า <b>ไม่รับ</b>ตอนแก้ (ผูกกับรายการบัญชีตอนซื้อ) — หน้าเว็บล็อกช่อง + บอกเหตุผล
/// • ผังที่ดิน/งานระหว่างก่อสร้างคิดค่าเสื่อมไม่ได้ (ด่านเดียวกับเส้นสร้าง)</summary>
public static class FixedAssetValuationEdit
{
    /// <summary>ข้อความที่หน้าเว็บแสดงข้างช่องที่ล็อกตอนแก้ไข</summary>
    public const string LockedFieldsNotice =
        "ราคาทุน · วันที่ซื้อ · ประเภทสินทรัพย์ · ข้อมูลสัญญาเช่า ผูกกับรายการบัญชีตอนซื้อ — แก้ที่เอกสารต้นทาง "
        + "หรือจำหน่าย/ลบรายการที่ลงทะเบียนผิดแล้วลงทะเบียนใหม่";

    /// <summary>
    /// รอบ 250 WP-08 (คำตัดสิน 250-26 · ASSET §6 Q5): ตั้ง/ล้าง "วันที่พร้อมใช้งาน" ของสินทรัพย์<b>ใบเดียว</b> — null = ทำได้ · ข้อความ = ปฏิเสธพร้อมทางไปต่อ ·
    /// <paramref name="newDate"/> null = ล้าง (กลับไปเริ่มค่าเสื่อมที่วันที่เอกสาร) · แก้ได้จนกว่ามีค่าเสื่อมลงบัญชี (งวดที่ลงแล้วคิดจากวันเดิม — แก้ย้อนหลังไม่ได้)
    /// </summary>
    public static string? AvailableDateProblem(bool isUnderAcquisition, bool hasCostSources, bool hasPostedDepreciation,
        DateTime purchaseDate, DateTime? newDate, DateTime todayBangkok)
    {
        if (isUnderAcquisition)
            return "สินทรัพย์ระหว่างจัดหา — ตั้งวันที่พร้อมใช้งานตอนกด “โอนเป็นสินทรัพย์พร้อมใช้” (ค่าเสื่อมเริ่มจากวันนั้น)";
        if (hasCostSources)
            return "สินทรัพย์ที่สร้างจากเอกสารหลายใบตั้งวันที่พร้อมใช้งานตอนโอนแล้ว (วันที่ซื้อ = วันพร้อมใช้) — ช่องนี้ใช้กับสินทรัพย์ใบเดียว";
        if (hasPostedDepreciation)
            return "สินทรัพย์นี้มีค่าเสื่อมราคาที่ลงบัญชีแล้ว — เปลี่ยนวันที่พร้อมใช้งานย้อนหลังไม่ได้ (งวดที่ลงแล้วคิดจากวันเดิม) · "
                + "ถ้าวันผิดจริง ให้กลับรายการค่าเสื่อมที่ลงแล้วก่อน หรือแจ้งนักบัญชีบันทึกปรับปรุง";
        if (newDate is not DateTime d) return null;
        if (d.Date < purchaseDate.Date)
            return $"วันที่พร้อมใช้งานต้องไม่ก่อนวันที่ซื้อ ({purchaseDate:dd/MM/yyyy}) — ซื้อมาแล้วจึงพร้อมใช้";
        if (d.Date > todayBangkok.Date.AddYears(1))
            return "วันที่พร้อมใช้งานไกลเกิน 1 ปีจากวันนี้ — ตรวจปี (ค.ศ./พ.ศ.) อีกครั้ง";
        return null;
    }

    /// <summary>null = แก้ได้ · ข้อความ = ปฏิเสธ (ไทย พร้อมทางไปต่อ)</summary>
    public static string? Problem(bool hasPostedDepreciation, DepreciationMethod newMethod, int newLifeMonths,
        decimal newSalvage, decimal purchaseCost, bool accountNonDepreciable)
    {
        if (hasPostedDepreciation)
            return "สินทรัพย์นี้มีค่าเสื่อมราคาที่ลงบัญชีแล้ว — เปลี่ยนอายุใช้งาน/มูลค่าซาก/วิธีคิดค่าเสื่อมย้อนหลังไม่ได้ "
                + "(TFRS บทที่ 10: การเปลี่ยนประมาณการมีผลไปข้างหน้า) — ใช้ปุ่ม “ปรับอายุการใช้งาน” ที่หน้ารายละเอียดสินทรัพย์ "
                + "(มีผลตั้งแต่งวดถัดไป งวดที่ลงแล้วไม่ถูกแตะ) · ถ้าลงทะเบียนผิดตั้งแต่ต้น ให้จำหน่าย/กลับรายการค่าเสื่อมก่อน "
                + "หรือแจ้งนักบัญชีบันทึกปรับปรุง";
        if (newSalvage < 0)
            return "มูลค่าซากต้องไม่ติดลบ";
        if (newMethod == DepreciationMethod.None) return null;
        if (accountNonDepreciable)
            return "ผังบัญชีของสินทรัพย์นี้เป็นที่ดิน/งานระหว่างก่อสร้าง คิดค่าเสื่อมราคาไม่ได้ (พ.ร.ฎ.145) — "
                + "เลือกวิธีคิดค่าเสื่อมเป็น “ไม่คิดค่าเสื่อม” หรือเปลี่ยนผังบัญชีให้ตรงกับสินทรัพย์จริง";
        if (newLifeMonths <= 0)
            return "อายุใช้งาน (เดือน) ต้องมากกว่า 0 — หรือเลือก “ไม่คิดค่าเสื่อม”";
        if (newSalvage >= purchaseCost)
            return "มูลค่าซากต้องน้อยกว่าราคาทุน";
        return null;
    }
}

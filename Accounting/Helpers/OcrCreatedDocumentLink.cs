namespace Accounting.Helpers;

/// <summary>
/// **"สแกนใบนี้สร้างเอกสารไปแล้วจริงไหม" — ตัวตัดสินตัวเดียว** (pure ไม่มี I/O)
///
/// <para>═══ ที่มา (ผู้ใช้รายงาน 2026-09-18) ═══ ลบเอกสารที่สร้างจากสแกนทิ้ง
/// แล้วการ์ดบนหน้า OCR ยัง<b>ติดป้าย "สร้างแล้ว"</b> อยู่ · กดแล้วเด้ง "ไม่พบเอกสาร"
/// เพราะ <c>DeleteDocumentAsync</c> ลบแถว <c>Documents</c> ทิ้งจริง (hard delete —
/// ใบร่างไม่เคยเข้าบัญชี จึงไม่มีภาระ audit) แต่<b>ไม่เคยแตะ</b>
/// <c>OcrScanResult.CreatedDocumentId</c> ซึ่งเป็น <c>Guid?</c> เปล่า ๆ ไม่มี FK
/// ⇒ เหลือ "ตัวชี้ค้าง" ที่ไม่มีอะไรฟ้อง</para>
///
/// <para>ผลที่ตามมามากกว่าป้ายผิด: ตัวกรองแท็บ "สร้างแล้ว"/"รอตรวจสอบ" ใช้ช่องนี้
/// ตัดสิน ⇒ สแกนที่เอกสารถูกลบไปแล้วจะ<b>ค้างอยู่แท็บผิดถาวร</b> และ<b>ด่านกัน
/// สร้างซ้ำ</b> ก็อ่านช่องนี้ ⇒ ผู้ใช้สร้างเอกสารใหม่จากสแกนเดิมไม่ได้เลย
/// ทั้งที่ของเก่าถูกลบไปแล้ว</para>
///
/// <para>กติกา: ป้าย "สร้างแล้ว" เป็นจริงก็ต่อเมื่อ<b>มีตัวชี้ และปลายทางยังอยู่</b>
/// — มีตัวชี้อย่างเดียวไม่พอ (ญาติของหลักการ "มี ≠ ถูกเรียก" ในรูปของข้อมูล:
/// "ชี้ไป ≠ ปลายทางมีจริง")</para>
/// </summary>
public static class OcrCreatedDocumentLink
{
    /// <summary>ตัวชี้ค้าง = มีค่าแต่ปลายทางหายไปแล้ว — ต้องล้างทิ้งและบอกผู้ใช้
    ///
    /// <para>ตรงข้ามของมัน ("สร้างแล้วจริง" = มีตัวชี้ <b>และ</b> ปลายทางยังอยู่) ตั้งใจ
    /// <b>ไม่</b>เขียนเป็นอีกเมธอด — เมื่อผู้เรียกล้างตัวชี้ค้างทิ้งแล้ว ช่องที่ยังมีค่า
    /// ก็คือช่องที่เป็นจริงโดยปริยาย · การมีสองเมธอดที่เป็นนิเสธของกันแล้วใช้จริงตัวเดียว
    /// = ของที่ไม่มีใครเรียก (หลักการข้อ 2 "มี ≠ ถูกเรียก")</para></summary>
    /// <param name="createdDocumentId">ค่าที่เก็บไว้ในแถวสแกน</param>
    /// <param name="documentStillExists">ปลายทางยังมีอยู่ในฐานไหม (ผู้เรียกไปถามมา)</param>
    public static bool IsDangling(Guid? createdDocumentId, bool documentStillExists)
        => createdDocumentId.HasValue && createdDocumentId.Value != Guid.Empty && !documentStillExists;

    /// <summary>ข้อความที่เขียนลงบันทึกของสแกนเมื่อเอกสารปลายทางถูกลบ —
    /// ต้องบอก<b>ว่าเกิดอะไร</b>และ<b>ทำอะไรต่อได้</b> ไม่ใช่แค่ล้างค่าเงียบ ๆ</summary>
    public static string UnlinkNote(string? documentNumber, DateTime whenUtc)
        => $"\n[Unlink] เอกสาร {(string.IsNullOrWhiteSpace(documentNumber) ? "(ไม่มีเลขที่)" : documentNumber)} "
         + $"ที่สร้างจากสแกนนี้ถูกลบเมื่อ {whenUtc.AddHours(7):yyyy-MM-dd HH:mm} น. "
         + "— สแกนกลับไปสถานะ \"ยังไม่ได้สร้างเอกสาร\" และสร้างใหม่ได้";
}

namespace Accounting.Helpers;

/// <summary>
/// ช่องไหนของ "ค่าที่รู้ว่าถูก ต่อผู้ขายหนึ่งราย" (<c>VendorKnownGoodValues</c>)
/// เอาไปแก้ผลอ่านของ OCR แบบ fuzzy ได้ — **ตัวตัดสินเดียว** ที่ทั้งฝั่งเขียน
/// (<c>AzureDiPatternLearner</c>) และฝั่งอ่าน (<c>VendorKnownGoodCorrector</c>) ใช้ร่วม
///
/// ═══ ที่มาของกฎ (บั๊กจริง) ═══
/// เดิมฝั่งอ่านเอา <b>เลขที่เอกสาร</b> ของใบที่กำลังสแกน ไป fuzzy-match กับเลขที่
/// ของใบ<b>ก่อนหน้า</b>ของผู้ขายรายเดียวกัน แล้วแทนที่เมื่อ similarity ≥ 0.80 —
/// แต่เลขที่เอกสารเป็นค่า <b>"ต่อใบ"</b> ไม่ใช่ <b>"ต่อผู้ขาย"</b>: เลขรันติดกัน
/// ต่างกันแค่หลักเดียว ⇒ similarity 0.83–0.92 <b>เกินเกณฑ์เสมอ</b>
/// (simulation กับเลขจริง 8 รูปแบบ: ถูกทับ 6/8 · `INV-2026-00124` → กลายเป็น
/// `INV-2026-00123`) ⇒ ใบใหม่ถือเลขของใบเก่า ⇒ (ก) รายงานภาษีซื้อ §87 ยื่นเลข
/// ใบกำกับผิด (ข) ด่านกันสแกนซ้ำมองว่าเป็นใบเดิม (ค) กระทบยอดกับผู้ขายไม่ตรง
///
/// <b>รหัสสาขา §86/4</b> แย่กว่านั้น — 5 หลักที่ต่างกัน 1 ตัวได้ ratio = 1 − 1/5
/// = <b>0.80 พอดี</b> ⇒ ผ่านเกณฑ์ทุกคู่ (00001 → 00000 ฯลฯ) ⇒ ใบของสาขาที่ 1
/// ถูกเขียนเป็นสำนักงานใหญ่ทุกใบ
///
/// ═══ กติกา ═══
/// แก้ได้เฉพาะช่องที่ <b>คงที่ตลอดชีวิตของผู้ขาย</b> และเป็น <b>ข้อความ</b>
/// (มี "การสะกด" ให้ซ่อม). ช่องที่เปลี่ยนทุกใบ หรือเป็น <b>ตัวเลขล้วน</b>
/// (ตัวเลขไม่มีการสะกดผิด — มันถูกหรือผิดเท่านั้น การเดาคือการแต่งข้อมูล)
/// **ห้ามแก้** — ตรงกับหลัก "ไม่รู้ = ต้องบอกว่าไม่รู้ ห้ามแต่งค่า default"
/// </summary>
public static class VendorKnownGoodFields
{
    /// <summary>ช่องที่ยอมให้ fuzzy-correct ได้ (คงที่ต่อผู้ขาย + เป็นข้อความ)</summary>
    private static readonly HashSet<string> Correctable = new(StringComparer.Ordinal)
    {
        "SellerName",
        "VendorAddress",
    };

    /// <summary>ช่องที่ยัง <b>เก็บ</b> ได้ (ใช้อ้างอิง/สอนโมเดลภายหลัง) แต่
    /// <b>ห้ามเอาไปทับ</b>ผลอ่าน — เหตุผลรายช่องอยู่ใน doc-comment ของคลาส
    /// (ตัวเลขล้วน = ไม่มีการสะกดให้ซ่อม · ต่อสาขา = ไม่คงที่ต่อผู้ขาย)</summary>
    public static bool IsCorrectable(string fieldName) => Correctable.Contains(fieldName);

    /// <summary>ช่องที่เป็น "ตัวตนของใบนั้นใบเดียว" — เก็บลงคลังค่าประจำผู้ขาย
    /// ไม่ได้เลย เพราะจะได้ 1 แถวต่อ 1 ใบตลอดไป (คลังบวม) และเป็นเชื้อของบั๊ก
    /// ข้างบน. ฝั่งเขียนต้องข้ามช่องเหล่านี้</summary>
    public static bool IsPerDocument(string fieldName) => fieldName is "DocumentNumber";
}

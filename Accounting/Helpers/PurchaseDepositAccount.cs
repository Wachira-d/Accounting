using System.Text.RegularExpressions;

namespace Accounting.Helpers;

/// <summary>
/// ผังบัญชีที่ควรใช้เมื่อ<b>เราเป็นผู้จ่าย</b>มัดจำ/เงินล่วงหน้า
///
/// ═══ ทำไมต้องมี (ผลตรวจ OCR 2026-09-06 · T1-15) ═══
/// ระบบรู้จัก "ใบมัดจำ" เฉพาะ<b>ฝั่งขาย</b> (เรารับเงิน → Cr 217xx ขายรอรับรู้)
/// ส่วน<b>ฝั่งซื้อ</b>ไม่มีเส้นทางเลย ⇒ ใบเสร็จรับเงินมัดจำ 30% จากผู้รับเหมา/
/// ผู้ขายเครื่องจักร ถูก resolver จัดเป็นค่าจ้าง/ต้นทุนแล้วลงเป็น<b>ค่าใช้จ่าย
/// ทันที</b> ทั้งที่ยังไม่ได้รับมอบงาน ⇒ (1) รับรู้ค่าใช้จ่ายเร็วเกิน ผิดงวด
/// (2) เมื่อใบจริงมาทีหลังจะลงซ้ำทั้งก้อน · นักบัญชีลง Dr เงินมัดจำจ่าย
/// (สินทรัพย์) แล้วโอนเข้าค่าใช้จ่าย/ต้นทุนเมื่อรับมอบ
///
/// (ขั้นนี้แก้เฉพาะ<b>ผังบัญชีที่แนะนำ</b> ซึ่งตัดความผิดเรื่องงวดได้แล้ว —
/// flow หักมัดจำอัตโนมัติตอนใบจริงมาถึงยังเป็นงานแยก ดู backlog T1-15)
/// </summary>
public static class PurchaseDepositAccount
{
    /// <summary>คำที่หมายถึง "จ่ายล่วงหน้าค่าสินค้า/บริการ" มากกว่า "มัดจำ"</summary>
    private static readonly Regex AdvanceWords = new(
        @"ล่วงหน้า|ADVANCE|PRE-?PAYMENT|PAYMENT[ \t]*IN[ \t]*ADVANCE",
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    /// <summary>รหัสผังบัญชีเรียงตามความเหมาะสม (ผู้เรียกเลือกตัวแรกที่มีจริง
    /// ในผังของบริษัทนั้น) — ทุกตัวเป็นรหัสในผังมาตรฐาน `ChartOfAccountTemplates`
    /// (118 เงินมัดจำจ่ายล่วงหน้า · 11810 เงินมัดจำ · 11820 เงินจ่ายล่วงหน้าค่าสินค้า/บริการ)</summary>
    public static string[] PreferredCodes(string? rawText)
        => AdvanceWords.IsMatch(rawText ?? "")
            ? new[] { "11820", "11810", "118" }
            : new[] { "11810", "11820", "118" };
}

namespace Accounting.Helpers;

/// <summary>ผลตรวจ "ใบนี้น่าจะเป็นบริการจากต่างประเทศ (§83/6) แต่ยังไม่ได้ติ๊ก"</summary>
/// <param name="Suspect">true = ควรเตือนผู้ใช้ก่อนอนุมัติ</param>
/// <param name="Reason">ข้อความไทยที่บอก **หลักฐาน** + **ผลถ้าปล่อยไว้** + **ทางไปต่อ**</param>
public readonly record struct ForeignServiceSuspicion(bool Suspect, string Reason);

/// <summary>
/// **ตัวตรวจ "ลืมติ๊กบริการต่างประเทศ (ภ.พ.36 §83/6)"** — pure · ไม่รับ DbContext
///
/// ═══ ที่มา (ผู้ใช้ส่งภาพ 2 ใบ 2026-09-21) ═══
/// ใบสำคัญจ่ายค่าคอมมิชชั่นให้ <b>Booking.com B.V.</b> (ผู้ขายต่างประเทศ ไม่มีเลข
/// ผู้เสียภาษีไทย) สองใบของคู่ค้ารายเดียวกัน ลงบัญชี**คนละแบบ**:
/// <code>
///   ใบ ก.ค. (ติ๊กแล้ว — ถูก)          ใบ ส.ค. (ไม่ได้ติ๊ก — ผิด)
///   Dr 52150 ค่าคอมมิชชั่น  10,221.75   Dr 52150 ค่าคอมมิชชั่น  10,074.75
///   Dr 11640 ภาษีซื้อฯ         715.52   Dr 11640 ภาษีซื้อฯ         705.23
///     Cr 21912 ภ.พ.36          715.52     Cr ผู้รับเงิน/ธนาคาร  10,779.98  ← รวม VAT
///     Cr ธนาคาร            10,221.75                                        ← ไม่มี 21912
/// </code>
///
/// ผู้ขายต่างประเทศ<b>ไม่เก็บ VAT ไทย</b> — เราประเมิน 7% เองแล้วนำส่งแทนเขา ⇒
/// ใบที่ไม่ได้ติ๊กพังพร้อมกัน 3 ทาง และ<b>เงียบทั้งสามทาง</b>:
/// <list type="number">
/// <item><b>ไม่มีหนี้ ภ.พ.36</b> (ไม่มี <c>Cr 21912</c>) ⇒ ไม่โผล่หน้านำส่งภาษี
///   ⇒ <b>ไม่เคยนำส่ง</b> ⇒ เบี้ยปรับ/เงินเพิ่ม ม.27 เมื่อสรรพากรตรวจพบ</item>
/// <item><b>เครดิตผู้รับเงินเกินไป 7%</b> (10,779.98 แทน 10,074.75) ⇒ เจ้าหนี้/
///   บัญชีธนาคารเกินจริง ⇒ <b>กระทบยอดธนาคารไม่ลง</b> ทุกเดือนที่มีใบแบบนี้</item>
/// <item><b>ภาษีซื้อค้างที่ 11640 โดยไม่มีทางออก</b> — เส้นปลดล็อกของ ภ.พ.36
///   (<c>นำส่ง → รับรู้ภาษีซื้อ</c>) อ่าน <c>Document.IsForeignService</c> และเส้น
///   §86/4 (เติมใบกำกับผู้ขายไทย) ก็ปิดอยู่เพราะผู้ขายต่างประเทศไม่มีเลขภาษีไทย
///   ⇒ ครบ 6 เดือนงาน §82/3 จะ<b>โยนเป็นค่าใช้จ่าย</b> ⇒ เสียสิทธิเคลมถาวร</item>
/// </list>
///
/// ═══ ทำไมเป็น "เตือน" ไม่ใช่ "บล็อก" ═══
/// หลักฐานที่ระบบมีคือ <b>ประเทศของคู่ค้า</b> กับ <b>รูปเลขผู้เสียภาษี</b> ซึ่ง
/// ตอบไม่ได้ 100% (ผู้ขายไทยที่ยังไม่กรอกประเทศ · สาขาของบริษัทต่างชาติที่จด VAT
/// ไทยแล้ว = ออกใบกำกับไทยได้ ไม่ใช่ §83/6) ⇒ บล็อกจะไปล้มใบที่ถูกอยู่แล้ว
/// (F2 ข้อ 8 "คำเตือนที่ฟ้องใบถูกทุกใบ = ปิดด่านโดยไม่ตั้งใจ") ·
/// ทิศนี้ผ่าน G5 เพราะความเสียหายที่เหลือถูก<b>เห็นตอนอนุมัติ</b>แล้วผู้ใช้กดยืนยันเอง
/// </summary>
public static class ForeignServiceEvidence
{
    public const string RuleCode = "RD-83/6-UNFLAGGED";
    public const string LegalReference = "ป.รัษฎากร §83/6 (ภ.พ.36) + §77/2";

    /// <summary>ประเทศไทย — คู่ค้าที่ระบุประเทศเป็นค่านี้ (หรือไม่ระบุ) ไม่ถือเป็น
    /// หลักฐานว่าเป็นผู้ขายต่างประเทศ</summary>
    public const string ThaiCountryCode = "TH";

    // เลขผู้เสียภาษีไทยมี 13 หลักเสมอ — ผู้ขายต่างประเทศไม่มี (ใบของ Booking.com
    // พิมพ์ "VAT Number: NL805734958B01" ซึ่งเป็นเลข EU) · ใช้ `ThaiTaxId.IsWellFormed`
    // ตัวเดิมของเรพ **ห้ามเขียนกติกา 13 หลักชุดที่สอง** (F2 ข้อ 4)

    /// <summary>ใบนี้ควรถูกติ๊ก "บริการต่างประเทศ" แต่ยังไม่ได้ติ๊กหรือเปล่า
    ///
    /// <para>เรียกเฉพาะเอกสาร**ฝั่งซื้อที่มี VAT** — ผู้เรียกกรองชนิดเอกสารมาก่อน
    /// (helper ไม่รู้จัก <c>DocumentType</c> โดยตั้งใจ เพื่อให้เทสต์ได้โดยไม่ต้อง
    /// ลาก enum ทั้งชุดมา)</para>
    ///
    /// <para>ลำดับหลักฐานตาม DECISION_DOCTRINE §1 — <b>ประเทศของคู่ค้า</b> เป็น
    /// หลักฐานตรงที่สุด (ผู้ใช้กรอกเอง มีความหมายเดียว) · <b>เลขผู้เสียภาษีที่ไม่ใช่
    /// รูปไทย</b> รองลงมา · ส่วน "ภาษีซื้อถูกปักไว้ที่ 11640" เป็นเพียง<b>ตัวขยาย</b>
    /// ไม่ใช่หลักฐานเดี่ยว ๆ เพราะใบไทยที่เอกสารไม่ครบ §86/4 ก็พักที่ 11640 เหมือนกัน</para></summary>
    public static ForeignServiceSuspicion Judge(
        bool isForeignService,
        decimal vatAmount,
        string? contactCountryCode,
        string? contactTaxId,
        bool inputVatParkedAsUndue)
    {
        if (isForeignService) return new ForeignServiceSuspicion(false, "");
        if (vatAmount <= 0m) return new ForeignServiceSuspicion(false, "");

        var country = contactCountryCode?.Trim();
        var countryIsForeign = !string.IsNullOrWhiteSpace(country)
            && !string.Equals(country, ThaiCountryCode, StringComparison.OrdinalIgnoreCase);
        var taxIdNotThai = !string.IsNullOrWhiteSpace(contactTaxId)
            && !ThaiTaxId.IsWellFormed(contactTaxId);

        string evidence;
        if (countryIsForeign)
            evidence = $"คู่ค้ารายนี้ระบุประเทศเป็น \"{country}\" (ไม่ใช่ไทย)";
        else if (taxIdNotThai && inputVatParkedAsUndue)
            evidence = $"เลขผู้เสียภาษีของคู่ค้า (\"{contactTaxId!.Trim()}\") ไม่ใช่รูปแบบเลขไทย 13 หลัก "
                + "และภาษีซื้อของใบนี้ถูกพักไว้ที่ 11640";
        else
            return new ForeignServiceSuspicion(false, "");

        return new ForeignServiceSuspicion(true,
            $"({RuleCode}) {evidence} แต่ใบนี้**ยังไม่ได้ติ๊ก \"ซื้อบริการจากต่างประเทศ (ภ.พ.36 §83/6)\"** — "
            + $"ถ้าเป็นผู้ขายต่างประเทศจริง เขาไม่เก็บ VAT ไทย เราต้องประเมิน 7% เองแล้วนำส่งแทน ⇒ "
            + $"ปล่อยไว้จะเกิด 3 อย่างพร้อมกัน: (1) ไม่มีหนี้ ภ.พ.36 (Cr 21912) ⇒ ไม่โผล่หน้านำส่งภาษี "
            + $"⇒ ไม่เคยนำส่ง (2) เครดิตผู้รับเงินเกินไปเท่ากับ VAT {vatAmount:N2} บาท ⇒ ยอดเจ้าหนี้/ธนาคาร"
            + $"เกินจริงและกระทบยอดไม่ลง (3) ภาษีซื้อค้างที่ 11640 โดยไม่มีทางเคลม และครบ 6 เดือนจะถูกโยน"
            + $"เป็นค่าใช้จ่ายตาม §82/3 · **ทางแก้**: ติ๊กช่อง \"ซื้อบริการจากต่างประเทศ\" บนฟอร์มก่อนอนุมัติ "
            + $"(ถ้าอนุมัติไปแล้ว ใช้ปุ่ม \"แก้เป็นบริการต่างประเทศ (ภ.พ.36)\" ที่หน้าเอกสาร) · "
            + $"ถ้าคู่ค้ารายนี้จด VAT ไทยและออกใบกำกับไทยได้จริง ให้กรอกประเทศ/เลขผู้เสียภาษีไทยให้ถูก "
            + $"แล้วคำเตือนนี้จะหายไปเอง");
    }
}

## 4. คุกกี้และข้อมูลที่เก็บในเบราว์เซอร์

- เราใช้ `localStorage` เก็บโทเคนการเข้าสู่ระบบ บริษัทที่เลือกอยู่ และการตั้งค่าหน้าจอของท่าน เพื่อให้ไม่ต้องเข้าสู่ระบบใหม่ทุกครั้ง — เป็นสิ่งที่**จำเป็นต่อการทำงานของบริการ**
- ระหว่างการเข้าสู่ระบบด้วย LINE เราใช้ `sessionStorage` เก็บค่าตรวจสอบ (state) ชั่วคราวเพื่อป้องกันการปลอมคำขอ และลบทิ้งทันทีที่ใช้เสร็จ
- การล้างข้อมูลเบราว์เซอร์จะทำให้ท่านต้องเข้าสู่ระบบใหม่ แต่ไม่กระทบข้อมูลในบัญชีของท่าน

## 5. การเปิดเผยข้อมูลให้บุคคลภายนอก

เราไม่ขายข้อมูลส่วนบุคคล และเปิดเผยเท่าที่จำเป็นต่อการให้บริการ ได้แก่

- **ผู้ให้บริการโครงสร้างพื้นฐานและอีเมล** — เพื่อจัดเก็บข้อมูลและส่งอีเมลระบบ (ยืนยันตัวตน แจ้งเตือน ใบเสร็จ)
- **ผู้ให้บริการยืนยันตัวตน** — Google / Facebook / LINE เฉพาะเมื่อท่านเลือกเข้าสู่ระบบด้วยวิธีนั้น
- **ผู้ให้บริการปัญญาประดิษฐ์** — เมื่อใช้ฟังก์ชันอ่านเอกสารหรือคำแนะนำอัตโนมัติ ระบบออกแบบให้**ประมวลผลด้วยแบบจำลองภายในเป็นหลัก** และส่งออกไปยังผู้ให้บริการภายนอกเฉพาะรายการที่แบบจำลองภายในยังตัดสินไม่ได้ ผู้ดูแลระบบสามารถปิดการเรียกใช้บริการภายนอกได้ทั้งหมด
- **หน่วยงานรัฐ** — เมื่อมีหน้าที่ตามกฎหมายหรือคำสั่งศาล

## 6. การส่งข้อมูลไปต่างประเทศ

ผู้ให้บริการบางรายอาจมีเครื่องแม่ข่ายอยู่นอกราชอาณาจักร ในกรณีดังกล่าวเราจะดำเนินการให้เป็นไปตาม ม.28 โดยเลือกผู้ให้บริการที่มีมาตรฐานการคุ้มครองข้อมูลที่เพียงพอ และผูกพันด้วยข้อสัญญามาตรฐานว่าด้วยการคุ้มครองข้อมูล

## 7. ระยะเวลาเก็บรักษาข้อมูล

| ข้อมูล | ระยะเวลา | ที่มา |
|---|---|---|
| บัญชีผู้ใช้และข้อมูลโปรไฟล์ | ตลอดอายุการใช้บริการ | สัญญา |
| บัญชี เอกสารประกอบการลงบัญชี และงบการเงิน | **5 ปี** | พ.ร.บ.การบัญชี ม.10 |
| รายงานภาษีซื้อ/ภาษีขาย และเอกสารประกอบ | **5 ปี** นับจากวันยื่นแบบ | ประมวลรัษฎากร §87/3 |
| บันทึกการเข้าถึงข้อมูลส่วนบุคคล (PII access log) | ไม่น้อยกว่า **1 ปี** | PDPA ม.37 |
| หลักฐานความยินยอม | ตลอดอายุบัญชี และต่อไปอีกตามอายุความ | PDPA ม.19 (ภาระพิสูจน์) |

เมื่อข้อมูลรายการเดียวอยู่ภายใต้หลายกฎหมาย ระบบใช้**ระยะเวลาที่ยาวที่สุด** และตั้งสถานะ *legal hold* เพื่อกันการลบก่อนกำหนด เมื่อพ้นกำหนดจะลบหรือทำให้ไม่สามารถระบุตัวบุคคลได้

## 8. สิทธิของเจ้าของข้อมูลส่วนบุคคล

- **ขอเข้าถึงและขอสำเนา** ข้อมูลของท่าน (ม.30)
- **ขอให้โอนย้ายข้อมูล** ในรูปแบบที่อ่านได้ด้วยเครื่อง (ม.31)
- **คัดค้าน** การเก็บรวบรวม ใช้ หรือเปิดเผย (ม.32)
- **ขอให้ลบหรือทำลาย** หรือทำให้ไม่สามารถระบุตัวบุคคลได้ (ม.33)
- **ขอให้ระงับการใช้** ข้อมูล (ม.34)
- **ขอให้แก้ไข** ข้อมูลให้ถูกต้องเป็นปัจจุบัน (ม.35)
- **ถอนความยินยอม** ที่เคยให้ไว้ได้ทุกเมื่อ (ม.19 วรรคห้า) — การถอนไม่กระทบความชอบด้วยกฎหมายของการประมวลผลที่ทำไปแล้ว

ใช้สิทธิได้โดยส่งคำขอมาที่อีเมล [{{controller.email}}](mailto:{{controller.email}}) หรือถ้าท่านเข้าสู่ระบบอยู่แล้ว ใช้เมนู **ความเป็นส่วนตัว (PDPA)** ในระบบ เราจะดำเนินการภายใน **30 วัน** นับแต่ได้รับคำขอ

> **ข้อจำกัดที่ต้องทราบ:** คำขอลบข้อมูลจะทำไม่ได้กับข้อมูลที่เรามีหน้าที่ตามกฎหมายต้องเก็บ เช่น เอกสารทางบัญชีและรายงานภาษีที่ยังอยู่ในระยะเวลา 5 ปีตามข้อ 7 ในกรณีนี้เราจะแจ้งเหตุผลและกำหนดเวลาที่จะลบได้ให้ท่านทราบ

## 9. มาตรการรักษาความมั่นคงปลอดภัย (ม.37)

- เข้ารหัสข้อมูลระหว่างรับส่งด้วย TLS และเข้ารหัสข้อมูลอ่อนไหวขณะจัดเก็บ
- ควบคุมสิทธิ์การเข้าถึงตามบทบาท (RBAC) และแยกข้อมูลของแต่ละกิจการออกจากกัน
- เก็บบันทึกการเข้าถึงข้อมูลส่วนบุคคลและร่องรอยการแก้ไขแบบเพิ่มได้อย่างเดียว (append-only) พร้อมค่าตรวจสอบความถูกต้องแบบต่อเนื่อง
- ล็อกบัญชีชั่วคราวเมื่อพยายามเข้าสู่ระบบล้มเหลวเกินจำนวนที่กำหนด

## 10. การแจ้งเหตุละเมิดข้อมูลส่วนบุคคล


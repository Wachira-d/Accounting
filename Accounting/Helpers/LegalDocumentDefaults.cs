## 3. ความถูกต้องของข้อมูลบัญชีและภาษี

- บริการเป็น**เครื่องมือ**ช่วยจัดทำบัญชีและคำนวณภาษี ไม่ใช่การให้บริการวิชาชีพบัญชีหรือคำแนะนำทางภาษีเป็นรายกรณี
- ตาม พ.ร.บ.การบัญชี พ.ศ. 2543 ม.7 ผู้มีหน้าที่จัดทำบัญชีต้องจัดให้มี**ผู้ทำบัญชีที่มีคุณสมบัติครบถ้วน** การใช้ระบบไม่ทดแทนหน้าที่ดังกล่าว
- การยื่นแบบแสดงรายการภาษีต่อกรมสรรพากร การนำส่งงบการเงินต่อกรมพัฒนาธุรกิจการค้า และความถูกต้องครบถ้วนของข้อมูลที่ยื่น เป็นความรับผิดชอบของท่าน
- ท่านควรตรวจทานเอกสาร รายงานภาษี และรายการบัญชีที่ระบบสร้างขึ้นก่อนนำไปใช้จริงทุกครั้ง

## 4. ฟังก์ชันที่ใช้ปัญญาประดิษฐ์ (AI) และการอ่านเอกสารอัตโนมัติ (OCR)

- ระบบมีฟังก์ชันช่วยอ่านเอกสารและแนะนำผังบัญชี/การจัดประเภทรายการ ผลลัพธ์เป็น**ข้อเสนอแนะ** ที่ต้องได้รับการยืนยันจากท่านก่อนบันทึกจริงเสมอ
- ระบบแสดงป้ายกำกับให้ทราบว่าคำแนะนำแต่ละรายการมาจากแบบจำลองภายในหรือจากผู้ให้บริการ AI ภายนอก
- เราไม่รับประกันความถูกต้องสมบูรณ์ของผลลัพธ์อัตโนมัติ — ท่านยังคงมีหน้าที่ตรวจสอบตามข้อ 3

## 5. ค่าบริการและแพ็กเกจ

- ค่าบริการ ขอบเขตการใช้งาน และโควตาของแต่ละแพ็กเกจเป็นไปตามที่แสดงบนหน้าแพ็กเกจ ณ เวลาที่สมัคร
- แพ็กเกจแบบทดลองใช้จะสิ้นสุดตามระยะเวลาที่กำหนด หากไม่ชำระค่าบริการต่อ บัญชีจะถูกจำกัดสิทธิ์การใช้งาน แต่**ข้อมูลของท่านจะยังไม่ถูกลบทันที** (ดูข้อ 6)
- การเปลี่ยนแปลงค่าบริการจะแจ้งล่วงหน้าไม่น้อยกว่า 30 วันผ่านอีเมลที่ลงทะเบียนไว้

## 6. การเก็บรักษาข้อมูลและการยุติการใช้บริการ

- ท่าน**ส่งออกข้อมูลของท่านได้ตลอดเวลา**ที่บัญชียังใช้งานอยู่
- เมื่อท่านยุติการใช้บริการ เราจะเก็บข้อมูลไว้ตามระยะเวลาที่กฎหมายกำหนดให้เก็บ ได้แก่ **5 ปี**สำหรับบัญชีและเอกสารประกอบการลงบัญชี (พ.ร.บ.การบัญชี ม.10) และรายงานภาษี (ประมวลรัษฎากร §87/3) หลังพ้นกำหนดจึงจะลบหรือทำให้ไม่สามารถระบุตัวบุคคลได้
- ในช่วงเวลาที่มีหน้าที่ตามกฎหมายต้องเก็บ ข้อมูลจะถูกตั้งสถานะ *legal hold* และ**ไม่สามารถลบตามคำขอได้** (รายละเอียดใน[นโยบายความเป็นส่วนตัว](/privacy.html) ข้อ 7-8)
- เราอาจระงับบริการทันทีหากพบการใช้งานที่ผิดกฎหมายหรือกระทบความปลอดภัยของระบบโดยรวม

## 7. ข้อห้าม

- ใช้บริการเพื่อการใด ๆ ที่ผิดกฎหมาย รวมถึงการจัดทำเอกสารทางบัญชีหรือใบกำกับภาษีอันเป็นเท็จ
- เจาะระบบ ทดสอบเจาะระบบโดยไม่ได้รับอนุญาตเป็นลายลักษณ์อักษร ทำวิศวกรรมย้อนกลับ หรือพยายามเข้าถึงข้อมูลของผู้ใช้รายอื่น
- ใช้กระบวนการอัตโนมัติเรียกใช้บริการในลักษณะที่กระทบต่อผู้ใช้รายอื่น หรือหลบเลี่ยงโควตาของแพ็กเกจ
- ทำซ้ำ ดัดแปลง หรือให้บริการต่อ (resell) ซอฟต์แวร์โดยไม่ได้รับอนุญาต


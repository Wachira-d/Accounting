namespace Accounting.Helpers;

/// <summary>ผู้แก้รายการประจำ (รอบ 259 · B-M3) — <c>CanApprove</c> = ผู้แก้มีสิทธิ์อนุมัติเอกสารชนิดของรายการ (หลังแก้) และไม่ได้มาทางคีย์ API
/// (คีย์ถือตัวตนเจ้าของผู้ออกคีย์ ⇒ ประทับว่า "คนรับรอง" ไม่ได้ · แนวเดียวกับ <c>[RejectApiKey]</c> ของการตั้งนโยบาย)</summary>
public sealed record RecurringEditor(string UserId, bool CanApprove);

/// <summary>
/// รอบ 259 (B-M3 · คำตัดสิน 259-4-1 ทับ 257-4-7) — ตัวตัดสินเดียวว่า "แก้รายการประจำแล้ว ค่าเริ่มต้น/ใบรับรองนโยบายอนุมัติอัตโนมัติเป็นอย่างไรต่อ"
/// <para>เดิม (257-4-7): แก้ยอด/ผู้ติดต่อ/บรรทัด/ตารางเวลา ⇒ ลายนิ้วมือไม่ตรง ⇒ ค่าเริ่มต้นรอบ 256 และใบรับรองหยุดมีผล<b>เงียบ ๆ</b> แม้ผู้แก้เองมีสิทธิ์อนุมัติ
/// (ด่านเขียน 257-1-1 บังคับอยู่แล้วว่าผู้แก้รายการอนุมัติอัตโนมัติต้องมีสิทธิ์อนุมัติ) ⇒ ปรับราคารายปีแล้วเดือนถัดไปใบค้างร่าง ไม่ส่ง</para>
/// <para>ตอนนี้: ผู้แก้มีสิทธิ์อนุมัติ ⇒ ประทับใหม่ในชื่อผู้แก้ (ผู้รับผิดชอบค่าเริ่มต้น/ผู้รับรอง = ผู้แก้) · ไม่มีสิทธิ์ ⇒ หยุดมีผล + บอกบนหน้าตรง ๆ ว่าใครเปิดคืนได้ ·
/// ไม่ "ชุบชีวิต" ค่าที่ไม่ตรงอยู่ก่อนแก้ (แก้แค่ชื่อไม่ทำให้ใบรับรองที่หยุดไปแล้วกลับมามีผล — ต้องรับรองที่ขั้นอนุมัติ)</para>
/// </summary>
public static class RecurringPolicyRestamp
{
    public const string RuleCode = "RECURRING-POLICY-RESTAMP";

    public enum Outcome
    {
        /// <summary>ไม่มีอะไรต้องทำ — การแก้ไม่แตะลายนิ้วมือ หรือค่าที่ประทับไม่ตรงอยู่ก่อนแล้ว</summary>
        None,
        /// <summary>ประทับใหม่ในชื่อผู้แก้</summary>
        Restamp,
        /// <summary>หยุดมีผล (ผู้แก้ไม่มีสิทธิ์อนุมัติ / มาทางคีย์ API / ผู้เรียกไม่ส่งผู้แก้)</summary>
        Suspend,
    }

    /// <param name="liveBeforeEdit">ค่าเริ่มต้นหรือใบรับรองยังตรงกับค่าของรายการก่อนแก้</param>
    /// <param name="bindingChanged">ลายนิ้วมือหลังแก้ ≠ ก่อนแก้</param>
    /// <param name="editorCanApprove">ผู้แก้มีสิทธิ์อนุมัติเอกสารชนิดนี้ (null ผู้แก้ = false)</param>
    public static Outcome Decide(bool liveBeforeEdit, bool bindingChanged, bool editorCanApprove)
        => !liveBeforeEdit || !bindingChanged ? Outcome.None
            : editorCanApprove ? Outcome.Restamp : Outcome.Suspend;

    /// <summary>คำเตือนหลังบันทึก (SaveWarnings) ของผลประทับใหม่</summary>
    public static string RestampedNotice(bool hadCertificate)
        => hadCertificate
            ? "นโยบายอนุมัติอัตโนมัติของรายการนี้ผูกกับค่าใหม่ (ยอด/ผู้ติดต่อ/บรรทัด/ตารางเวลา) แล้ว — ผู้รับรองคือคุณ (ผู้แก้ที่มีสิทธิ์อนุมัติ) · "
              + "ตรวจข้อที่ปล่อยได้ที่ขั้น \"อนุมัติ\" ถ้าต้องการเปลี่ยน"
            : "ค่าเริ่มต้นการอนุมัติอัตโนมัติ (ลูกค้าค้างชำระ ⇒ อนุมัติใบงวดใหม่ต่อ) ผูกกับค่าใหม่แล้ว — ผู้รับผิดชอบคือคุณ (ผู้แก้ที่มีสิทธิ์อนุมัติ) · "
              + "อยากให้หยุดรอคน เลือก \"ตั้งเองสำหรับรายการนี้\" ที่ขั้น \"อนุมัติ\"";

    /// <summary>คำเตือนหลังบันทึกของผลหยุดมีผล — บอกว่าใครเปิดคืนได้ (ชื่อผู้มีสิทธิ์ที่หาได้ · ไม่พบ = บอกสิทธิ์ที่ต้องมี)</summary>
    public static string SuspendedNotice(bool hadCertificate, IReadOnlyList<string>? approverNames)
    {
        var what = hadCertificate ? "นโยบายอนุมัติอัตโนมัติของรายการนี้" : "ค่าเริ่มต้นการอนุมัติอัตโนมัติ (ลูกค้าค้างชำระ ⇒ อนุมัติต่อ)";
        var who = approverNames is { Count: > 0 }
            ? "ผู้มีสิทธิ์อนุมัติเอกสารชนิดนี้ เช่น " + string.Join(", ", approverNames)
            : "ผู้มีสิทธิ์อนุมัติเอกสารชนิดนี้ (Document.Approve) ของบริษัท";
        return $"{what} หยุดมีผลแล้ว เพราะผู้แก้ไม่มีสิทธิ์อนุมัติ (หรือแก้ผ่านคีย์ API) — ใบงวดใหม่ที่ลูกค้ามีใบค้างจะหยุดเป็นร่างรอคน · "
               + $"เปิดคืนได้โดย{who}: เปิดรายการนี้ › ขั้น \"อนุมัติ\" › บันทึก";
    }
}

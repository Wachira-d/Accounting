namespace Accounting.Helpers;

/// <summary>
/// แปลง "รหัสประเภทเงินได้ภายในระบบ" → **รหัสที่ลงช่อง Col7 ของไฟล์นำเข้า
/// ภ.ง.ด.3/53/54** ตาม ท.ป.4/2528 + §3 เตรส
///
/// <para><b>ทำไมต้องอยู่ที่นี่</b> — เดิมตารางนี้เป็น <c>private static</c> อยู่ใน
/// <c>TaxFilingExportService</c> ⇒ อีกทางออกหนึ่งของไฟล์เดียวกัน (ปุ่ม e-Filing
/// ในหน้ารายงานภาษี → <c>TaxService.EFiling.BuildPndAsync</c>) เรียกไม่ได้ จึงส่ง
/// **รหัสภายในดิบ** ลงไฟล์ RD (<c>"40(8)"</c> · <c>"8ad"</c>) ⇒ สองปุ่มให้ไฟล์
/// Col7 คนละค่าจากงวดเดียวกัน — defect class "สอง renderer ห้าม drift"</para>
/// </summary>
public static class PndIncomeTypeCode
{
    /// <summary>
    /// รับได้ทั้งรหัสภายใน (<c>"8ad"</c>) · เลขมาตราแบบเต็ม (<c>"40(8)"</c>) ·
    /// ตัวเลขล้วน (<c>"8"</c>) — ทุกทางที่พบจริงในเรพ
    ///
    /// ⚠️ <b>ยังไม่ยืนยันกับหน้า import จริง</b>: ค่าโฆษณา (2%) และค่าขนส่ง (1%)
    /// เป็นเงินได้ <c>40(8)</c> เหมือนค่าจ้างทำของ (3%) จึงลงรหัสเดียวกันคือ
    /// <c>"6"</c> ตามพฤติกรรมเดิมของระบบ — <b>ไม่ได้เปลี่ยนคำตอบ เพียงทำให้
    /// เป็นการตัดสินใจที่ตั้งใจ ไม่ใช่การตกไป default เงียบ ๆ</b>. ถ้าหน้า RD มี
    /// รหัสแยกสำหรับสองตัวนี้ ให้แก้ที่นี่ที่เดียวแล้วทั้งสองปุ่มตามทันที
    /// (อาการที่ควรสงสัย: Col7 บอก "ค่าจ้างทำของ" แต่ Col9 เป็น 2.00/1.00)
    /// </summary>
    public static string ForFile(string? internalCode)
    {
        var c = (internalCode ?? "").Trim();
        return c switch
        {
            "1" or "40(1)" => "1",                 // เงินเดือน ม.40(1) — ปกติไปแบบ ภ.ง.ด.1
            "2" or "40(2)" => "2",                 // ค่านายหน้า/ค่าบริการ
            "3" or "40(3)" => "3",                 // ค่าสิทธิ/ลิขสิทธิ์
            "4a" or "40(4)a" or "40(4)(ก)" or "40(4)(a)" => "4A",
            "4b" or "40(4)b" or "40(4)(ข)" or "40(4)(b)" => "4B",
            "5" or "40(5)" => "5",                 // ค่าเช่าทรัพย์สิน
            "6" or "40(6)" => "6",                 // ค่าวิชาชีพอิสระ
            "7" or "40(7)" => "6",                 // ค่ารับเหมา → §3 เตรส ค่าจ้างทำของ
            "8" or "40(8)" => "6",                 // ค่าจ้างทำของ/บริการอื่น
            "8ad" => "6",                          // ค่าโฆษณา 2% — 40(8) เช่นกัน (ดูหมายเหตุ)
            "8tr" => "6",                          // ค่าขนส่ง 1% — 40(8) เช่นกัน (ดูหมายเหตุ)
            _ => "6",
        };
    }
}

using Accounting.Models.Enums;

namespace Accounting.Helpers;

/// <summary>
/// **"ด่านตอนอนุมัติที่ผูกกับ 'การจ่ายเงินให้คู่ค้า' ควรทำงานกับใบนี้ไหม"**
/// (pure ไม่มี I/O) — ใช้ที่ด่านหัก ณ ที่จ่าย (ท.ป.4/2528 ข้อ 12) และด่าน
/// ภาษีซื้อต้องห้าม (§82/5) ใน <c>CollectApprovalWarningsAsync</c>
///
/// <para>═══ ทำไมต้องมี (ผลตรวจ D1-B2 รอบ 181) ═══ เดิมสองด่านนั้นถามว่า
/// <c>DocumentSide.IsPurchase(doc.DocumentType)</c> <b>โดยไม่ส่งบทบาท</b>
/// ซึ่ง helper ตัวนั้นเขียน doc ของตัวเองไว้ชัดว่า "ชนิดกำกวม (CN/DN/ใบส่งของ)
/// ต้องดู <c>OurRole</c> ประกอบ ผู้เรียกที่ไม่มีบทบาทให้เช็ค <c>IsAmbiguous</c>
/// ก่อน ห้ามเดาเงียบ ๆ" ⇒ ผลที่เกิดจริง:</para>
/// <list type="bullet">
/// <item><b>ใบลดหนี้ฝั่งขาย</b> (เราลดหนี้ให้ลูกค้า) ตกเป็น "ฝั่งซื้อ" ⇒ เข้าด่าน
///   หัก ณ ที่จ่าย + ด่านภาษีซื้อต้องห้าม ทั้งที่ไม่มีทั้งการจ่ายและภาษีซื้อ</item>
/// <item><b>ใบขอซื้อ/ใบสั่งซื้อ/ใบรับสินค้า</b> อยู่ในเซ็ต <c>AlwaysPurchase</c>
///   ⇒ PO ค่าบริการเด้งคำเตือนหัก ณ ที่จ่าย และถูกเขียน audit "ระบบเลือกเงียบ"
///   ทั้งที่ยัง<b>ไม่มีการจ่ายเงิน</b>เกิดขึ้น (เป็นเพียงคำสั่งซื้อ)</item>
/// </list>
///
/// <para>═══ ชุดชนิดเอกสารมาจากไหน ═══ <b>ไม่มีชุดที่สอง</b> — delegate ตรงไป
/// <see cref="WhtCumulativeScope.Counts"/> ซึ่งเป็นนิยาม "เอกสารที่แทนการจ่าย/
/// ภาระจ่ายต่อคู่สัญญา" ที่ใช้คิดยอดสะสมอยู่แล้ว. ถ้าด่าน<b>เตือน</b>ใช้ชุดหนึ่ง
/// แต่<b>ยอดสะสม</b>ใช้อีกชุด จะเกิดสภาพ "เตือนว่ายอดถึงเกณฑ์ แต่ยอดที่โชว์
/// ไม่นับใบชนิดนี้" — สองความจริงบนคำเตือนใบเดียว</para>
/// </summary>
public static class WhtGateScope
{
    /// <summary>ใบนี้เป็น "การจ่าย/ภาระจ่ายให้คู่ค้า" ที่ด่านต้องทำงานไหม</summary>
    /// <param name="type">ชนิดเอกสาร</param>
    /// <param name="cnDnPurchaseSide">ใบเพิ่มหนี้/ลดหนี้ใบนี้อยู่ฝั่งซื้อไหม
    /// (<c>Document.CnDnPurchaseSideOverride</c> หรือผลค้นใบต้นทาง) —
    /// <c>null</c> = ไม่ระบุ ⇒ ไม่นับ (ห้ามเดาเงียบ ๆ)</param>
    public static bool Applies(DocumentType type, bool? cnDnPurchaseSide)
        => WhtCumulativeScope.Counts(type, cnDnPurchaseSide);
}

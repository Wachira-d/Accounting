    /// <summary>ที่มาของเนื้อหา — ใช้แยก “ระบบใส่ให้” ออกจาก “แอดมินเขียนเอง”</summary>
    public const string SystemAuthor = "system";

    private record Article(
        string Slug, HelpCategory Category, string Title, string Summary, string Body,
        int SortOrder, string? ModuleCode = null);

    public async Task<int> SeedAsync(CancellationToken ct = default)
    {
        var written = 0;
        var slugs = Articles.Select(a => a.Slug).ToList();
        var existing = await _db.HelpResources
            .Where(r => r.Slug != null && slugs.Contains(r.Slug))
            .ToDictionaryAsync(r => r.Slug!, ct);

        foreach (var a in Articles)
        {
            if (existing.TryGetValue(a.Slug, out var row))
            {
                // แอดมินแก้เองแล้ว = ของเขา ห้ามทับ (ไม่งั้นงานที่เขาเขียนหายทุก deploy)
                var touchedByAdmin = row.UpdatedBy != null && row.UpdatedBy != SystemAuthor;
                if (touchedByAdmin || row.IsDeleted) continue;
            }
            else
            {
                row = new HelpResource { Slug = a.Slug, CreatedBy = SystemAuthor };
                _db.HelpResources.Add(row);
            }

            row.Title = a.Title;
            row.Description = a.Summary;
            row.Body = a.Body;
            row.Category = a.Category;
            row.ModuleCode = a.ModuleCode;
            row.Kind = HelpResourceKind.Article;
            row.Provider = HelpMediaProviderNone;
            row.SortOrder = a.SortOrder;
            row.IsPublished = true;
            row.IsPublic = true;
            row.UpdatedAt = DateTime.UtcNow;
            row.UpdatedBy = SystemAuthor;
            written++;
        }

        if (written > 0)
        {
            await _db.SaveChangesAsync(ct);
            _logger.LogInformation("คู่มือสอนใช้งาน: เขียน/อัปเดต {Count} บทความ", written);
        }
        return written;
    }


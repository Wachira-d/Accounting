/// <summary>
/// งบกำไรขาดทุนเปรียบเทียบ (รายเดือน/ไตรมาส/ปี ตามรอบบัญชี) + drill-down ช่องตัวเลข → รายการ JE → เอกสารต้นทาง (ทีม M 2026-10-22)
///
/// <para><b>ไม่มีสูตรงบใหม่</b>: ทุกคอลัมน์ = <see cref="GetProfitAndLossAsync"/> ของช่วงนั้น (GroupBy+Sum ในฐานข้อมูล ·
/// Posted+Reversed · ไม่นับร่าง/ยกเลิก/ใบปิดบัญชี · ตัวกรองสาขา/มิติ/โครงการ + ส่วนปันส่วนชุดเดียวกับงบทดลอง) ·
/// drill-down = <see cref="GetGeneralLedgerForUserAsync"/> ของผังนั้นในช่วงนั้น (ตัวกรองเดียวกัน + ปิดบังตามสิทธิ์) ลบใบปิดบัญชี ⇒
/// ผลรวมแถว = ตัวเลขในช่องที่คลิก (เทสต์ <c>PnlComparisonDbTests</c>)</para>
/// </summary>
public partial class AccountingService

    /// <summary>เพดานแถวต่อหน้าของ drill-down</summary>
    public const int PnlDrilldownMaxPageSize = 500;

    public async Task<PnlComparisonResponse> GetProfitAndLossComparisonAsync(Guid companyId, DateTime? from, DateTime? to,
        PnlCompareGranularity granularity, bool comparePriorYear, Guid? projectId = null, Guid? branchId = null, Guid? dimensionId = null)
    {
        var startMonth = await FiscalStartMonthAsync(companyId);
        // ไม่ระบุช่วง ⇒ ต้นรอบบัญชีปัจจุบันของบริษัท ถึงวันนี้ (เวลาไทย) — ปุ่ม "ปีบัญชีนี้" ของหน้าใช้ค่านี้ (หน้าไม่ต้องรู้เดือนเริ่มรอบเอง)
        var toDate = (to ?? ThaiDate.CalendarDateUtc(DateTime.UtcNow)).Date;
        var fromDate = (from ?? FiscalYear.RangeFor(FiscalYear.FiscalYearOf(toDate, startMonth), startMonth).Start).Date;
        var periods = PnlComparison.BuildPeriods(fromDate, toDate, granularity, startMonth);

        // DbContext ไม่ thread-safe ⇒ ทีละช่วง (แต่ละครั้ง = aggregate ในฐานข้อมูล 1–2 query)
        var current = new List<ProfitAndLossResponse>(periods.Count);
        foreach (var p in periods)
            current.Add(await GetProfitAndLossAsync(companyId, p.Start, p.EndInclusive, projectId, branchId, dimensionId));

        List<ProfitAndLossResponse>? prior = null;
        if (comparePriorYear)
        {
            prior = new List<ProfitAndLossResponse>(periods.Count);
            foreach (var p in periods)
            {
                var (ps, pe) = PnlComparison.PriorYear(p.Start, p.EndInclusive);
                prior.Add(await GetProfitAndLossAsync(companyId, ps, pe, projectId, branchId, dimensionId));
            }
        }

        return PnlComparison.Assemble(fromDate, toDate, granularity, startMonth, periods, current, prior);
    }

    public async Task<PnlDrilldownResponse> GetProfitAndLossDrilldownAsync(Guid companyId, Guid userId, Guid accountId,
        DateTime fromDate, DateTime toDate, Guid? projectId = null, Guid? branchId = null, Guid? dimensionId = null,
        int page = 1, int pageSize = 100)
    {
        if (toDate.Date < fromDate.Date) throw new BusinessRuleException("วันที่สิ้นสุดต้องไม่ก่อนวันที่เริ่ม");
        var account = await _db.ChartOfAccounts.AsNoTracking()
            .Where(a => a.Id == accountId && a.CompanyId == companyId)
            .Select(a => new { a.Id, a.AccountCode, a.AccountName, a.AccountType })
            .FirstOrDefaultAsync()
            ?? throw new KeyNotFoundException("ไม่พบผังบัญชีนี้ในบริษัท");
        if (account.AccountType != AccountType.Revenue && account.AccountType != AccountType.Expense)
            throw new BusinessRuleException("ดูรายการได้เฉพาะผังรายได้/ค่าใช้จ่าย (บรรทัดของงบกำไรขาดทุน)");

        // บัญชีแยกประเภทของผังนี้ (ตัวกรอง + ส่วนปันส่วน + ปิดบังตามสิทธิ์ ชุดเดียวกับหน้า GL)
        var gl = await GetGeneralLedgerForUserAsync(companyId, userId, fromDate.Date, toDate.Date, accountId, dimensionId, branchId, projectId);
        var txs = gl.Accounts.Where(a => a.AccountId == accountId).SelectMany(a => a.Transactions).ToList();

        // งบกำไรขาดทุนไม่นับใบปิดบัญชี (C-T02) ⇒ drill-down ต้องตัดออกเหมือนกัน ไม่งั้นผลรวม ≠ ช่องที่คลิก
        var entryIds = txs.Select(t => t.JournalEntryId).Distinct().ToList();
        var heads = entryIds.Count == 0
            ? new Dictionary<Guid, JeHead>()
            : await _db.JournalEntries.AsNoTracking()
                .Where(j => j.CompanyId == companyId && entryIds.Contains(j.Id))
                .Select(j => new JeHead(j.Id, j.IsClosingEntry, j.SourceDocumentId, j.OriginalEntryId, j.IsAutoGenerated, j.Reference))
                .ToDictionaryAsync(j => j.Id);
        txs = txs.Where(t => heads.TryGetValue(t.JournalEntryId, out var h) && !h.IsClosingEntry).ToList();

        var debitNormal = account.AccountType == AccountType.Expense;
        decimal Signed(GeneralLedgerTransaction t) => debitNormal ? t.DebitAmount - t.CreditAmount : t.CreditAmount - t.DebitAmount;

        // บรรทัดที่ถูกปิดบัง (LedgerRedaction) ไม่มี JournalLineId + คำอธิบายขึ้นต้น "[ซ่อน]" ⇒ ไม่เปิดเผยเอกสารต้นทาง
        static bool IsHidden(GeneralLedgerTransaction t)
            => t.JournalLineId == null && (t.Description ?? "").StartsWith(LedgerRedaction.HiddenPrefix, StringComparison.Ordinal);

        var sources = await ResolveJournalSourcesAsync(companyId, heads.Values.Where(h => !h.IsClosingEntry).ToList(),
            txs.Where(IsHidden).Select(t => t.JournalEntryId).ToHashSet());

        var all = txs
            .OrderByDescending(t => t.EntryDate).ThenByDescending(t => t.EntryNumber, StringComparer.Ordinal)
            .Select(t =>
            {
                var hidden = IsHidden(t);
                var src = sources.TryGetValue(t.JournalEntryId, out var s) ? s : JournalSourceLink.Resolve(new JournalSourceFacts(
                    hidden, null, null, null, null, null, null, null, null, null, null, null, null, null, false));
                return new PnlDrilldownLine(t.JournalEntryId, t.EntryNumber, t.EntryDate, t.JournalType.ToString(), t.Description,
                    hidden ? null : (t.EntryReference ?? (heads.TryGetValue(t.JournalEntryId, out var h) ? h.Reference : null)),
                    t.DebitAmount, t.CreditAmount, Signed(t), JournalSourceLink.JournalHref(t.JournalEntryId), src);
            })
            .ToList();

        var size = Math.Clamp(pageSize, 1, PnlDrilldownMaxPageSize);
        var pg = Math.Max(1, page);
        // คำเตือนของบัญชีแยกประเภทเป็นเรื่องยอดยกมา (ไม่เกี่ยวกับยอดเคลื่อนไหวของงบกำไรขาดทุน) ⇒ ไม่ส่งต่อ
        var notes = new List<string>();
        if (txs.Any(IsHidden))
            notes.Add("บางรายการถูกรวมเป็นแถวเดียวต่อใบและซ่อนรายละเอียดตามสิทธิ์ของคุณ — ยอดรวมยังครบ");

        return new PnlDrilldownResponse(account.Id, account.AccountCode, account.AccountName, account.AccountType.ToString(),
            fromDate.Date, toDate.Date, all.Sum(l => l.Amount), all.Count, pg, size,
            all.Count(l => JournalSourceLink.IsWithoutSource(l.Source.Kind)),
            all.Skip((pg - 1) * size).Take(size).ToList(), notes);
    }

    private sealed record JeHead(Guid Id, bool IsClosingEntry, Guid? SourceDocumentId, Guid? OriginalEntryId, bool IsAutoGenerated, string? Reference);

    /// <summary>ค้นเอกสารต้นทางของหลายใบในครั้งเดียว (ทุกตารางกรอง CompanyId) → ตัวตัดสิน <see cref="JournalSourceLink.Resolve"/></summary>
    private async Task<Dictionary<Guid, PnlSourceLink>> ResolveJournalSourcesAsync(Guid companyId, List<JeHead> heads, HashSet<Guid> hidden)
    {
        var result = new Dictionary<Guid, PnlSourceLink>();
        if (heads.Count == 0) return result;
        var ids = heads.Select(h => h.Id).ToList();
        var docIds = heads.Where(h => h.SourceDocumentId.HasValue).Select(h => h.SourceDocumentId!.Value).Distinct().ToList();

        var docs = docIds.Count == 0
            ? new Dictionary<Guid, (string Number, DocumentType Type)>()
            : (await _db.Documents.AsNoTracking()
                    .Where(d => d.CompanyId == companyId && docIds.Contains(d.Id))
                    .Select(d => new { d.Id, d.DocumentNumber, d.DocumentType })
                    .ToListAsync())
                .ToDictionary(d => d.Id, d => (Number: d.DocumentNumber, Type: d.DocumentType));
        var pos = (await _db.PosOrders.AsNoTracking()
                .Where(o => o.CompanyId == companyId && o.JournalEntryId != null && ids.Contains(o.JournalEntryId!.Value))
                .Select(o => new { JeId = o.JournalEntryId!.Value, o.Id, o.OrderNumber })
                .ToListAsync())
            .GroupBy(o => o.JeId).ToDictionary(g => g.Key, g => g.First());
        var payroll = (await _db.PayrollRuns.AsNoTracking()
                .Where(r => r.CompanyId == companyId && r.JournalEntryId != null && ids.Contains(r.JournalEntryId!.Value))
                .Select(r => new { JeId = r.JournalEntryId!.Value, r.Id, r.PayrollNumber, r.Name })
                .ToListAsync())
            .GroupBy(r => r.JeId).ToDictionary(g => g.Key, g => g.First());
        var depreciation = (await _db.AssetDepreciations.AsNoTracking()
                .Where(d => d.CompanyId == companyId && d.JournalEntryId != null && ids.Contains(d.JournalEntryId!.Value))
                .Select(d => new { JeId = d.JournalEntryId!.Value, d.FixedAssetId, d.FixedAsset.AssetCode, d.FixedAsset.Name, d.Year, d.Month })
                .ToListAsync())
            .GroupBy(d => d.JeId).ToDictionary(g => g.Key, g => g.ToList());
        var claims = (await _db.ExpenseClaims.AsNoTracking()
                .Where(c => c.CompanyId == companyId && c.JournalEntryId != null && ids.Contains(c.JournalEntryId!.Value))
                .Select(c => new { JeId = c.JournalEntryId!.Value, c.Id, c.ClaimNumber })
                .ToListAsync())
            .GroupBy(c => c.JeId).ToDictionary(g => g.Key, g => g.First());

        foreach (var h in heads)
        {
            Guid? docId = null; string? docNo = null, docType = null;
            if (h.SourceDocumentId is Guid sd && docs.TryGetValue(sd, out var d))
            { docId = sd; docNo = d.Number; docType = DocumentTypeNames.Title(d.Type, null); }
            pos.TryGetValue(h.Id, out var po);
            payroll.TryGetValue(h.Id, out var pr);
            depreciation.TryGetValue(h.Id, out var dep);
            claims.TryGetValue(h.Id, out var cl);
            // ค่าเสื่อมรวมหลายสินทรัพย์ในใบเดียวได้ ⇒ ลิงก์สินทรัพย์แรก + บอกจำนวน
            string? depLabel = dep == null ? null
                : (dep.Count == 1 ? $"{dep[0].AssetCode} {dep[0].Name}" : $"{dep[0].AssetCode} {dep[0].Name} และอีก {dep.Count - 1} รายการ")
                    + $" ({dep[0].Month:D2}/{dep[0].Year + 543})";
            result[h.Id] = JournalSourceLink.Resolve(new JournalSourceFacts(
                hidden.Contains(h.Id), h.SourceDocumentId, docId, docNo, docType,
                po?.Id, po?.OrderNumber,
                pr?.Id, pr == null ? null : (string.IsNullOrWhiteSpace(pr.Name) ? pr.PayrollNumber : $"{pr.PayrollNumber} {pr.Name}"),
                dep?[0].FixedAssetId, depLabel,
                cl?.Id, cl?.ClaimNumber,
                h.OriginalEntryId, h.IsAutoGenerated));
        }
        return result;
    }

using Accounting.Services.Implementations.Ocr;
using Xunit;

namespace Accounting.Tests;

/// <summary>
/// ด่าน "DBD ชนะได้ก็ต่อเมื่อกุญแจถูก" — <c>OcrService.EnrichFromDbdAsync</c>
///
/// ═══ ที่มา ═══
/// การค้น DBD ใช้ <c>VendorTaxId</c> เป็นคีย์ ซึ่งเป็นช่องที่ OCR อ่านผิดได้บ่อย
/// ที่สุดช่องหนึ่ง (บาร์โค้ด EAN-13 ที่ผ่าน mod-11 · เลขผู้ซื้อถูกหยิบมาเป็นผู้ขาย ·
/// หลักเดียวเพี้ยน). เมื่อเลขผิด DBD คืน <b>คนละบริษัท</b> แล้วโค้ดเดิม:
/// <list type="number">
/// <item>ทับชื่อผู้ขายที่อ่านมา<b>ถูกแล้ว</b>ด้วยชื่อบริษัทอื่น</item>
/// <item>บันทึกชื่อที่ถูกต้องเป็น <b>negative example</b> = สอนตัวเรียนรู้ผิดถาวร</item>
/// <item>ตั้ง confidence 0.95 ⇒ ไม่ขึ้นไฮไลต์เตือนตามกฎเหล็ก #3 ข้อ 3</item>
/// <item>สร้าง Contact ผู้ขายรายใหม่ของบริษัทที่ไม่เกี่ยวกับใบนี้เลย</item>
/// </list>
///
/// ตัวแยกคือ <b>ระดับความต่าง</b>: OCR ที่อ่าน "ชื่อเดียวกัน" ผิด ได้สตริงที่
/// <i>คล้าย</i> เสมอ — คนละบริษัทได้คะแนนเกือบศูนย์. เทสต์นี้ล็อกช่องว่างนั้นไว้
/// (ถ้าวันหนึ่งสองกลุ่มทับกัน แปลว่าเกณฑ์ 0.45 ใช้ไม่ได้แล้ว ต้องคิดใหม่ —
/// ตรงกับบทเรียน "threshold ที่ตั้งจากตัวอย่างชนิดเดียวจะพังกับชนิดอื่น")
/// </summary>
public class DbdNameGuardTests
{
    // เกณฑ์เดียวกับของจริง — อ่านจากตัวตั้งตัวเดียว ไม่พิมพ์เลขซ้ำ
    // (เดิมเขียน 0.45 ไว้เองพร้อมคอมเมนต์ว่า "ตรงกับ DbdSameCompanyFloor ใน OcrService"
    //  ซึ่งเป็นสำเนาที่สาม และสำเนาใน OcrService ถูกถอดแล้วในรอบ 174)
    private const double Floor = Accounting.Helpers.DbdIdentityGuard.SameCompanyFloor;

    [Theory]
    // บริษัทเดียวกันที่ OCR สะกดเพี้ยน → ต้องผ่านด่าน (DBD ชนะ + เรียนรู้ได้)
    [InlineData("บริษัท สยามคอมเมอร์เชียล จำกัด", "บริษัท สยามคอมเมอร์เชียส จำกัด")]
    [InlineData("หจก. แอมแฮปปี๊เนส", "หจก . แอมแฮปปี้เนสล")]
    [InlineData("บริษัท ไทยเบฟเวอเรจ จำกัด (มหาชน)", "บริษัท ไทยเบฟเวอเรจ จํากัด (มหาซน)")]
    [InlineData("บริษัท เอ บี ซี เทรดดิ้ง จำกัด", "บริษัท เอบีซี เทรดดิง จำกัด")]
    public void ชื่อที่_OCR_สะกดเพี้ยน_ต้องยังถือว่าเป็นบริษัทเดียวกัน(string dbdName, string ocrName)
    {
        var sim = FuzzyMatcher.Similarity(dbdName, ocrName);
        Assert.True(sim >= Floor, $"ได้ {sim:F3} — ต่ำกว่าเกณฑ์ แปลว่าด่านจะไปบล็อกการแก้ที่ถูกต้อง");
    }

    [Theory]
    // เลขผู้เสียภาษีอ่านผิด → DBD คืนคนละบริษัท → ต้องตกด่าน (ห้ามทับ ห้ามสอน)
    [InlineData("บริษัท ปูนซิเมนต์ไทย จำกัด (มหาชน)", "บริษัท ไทยเบฟเวอเรจ จำกัด")]
    [InlineData("บริษัท แอดวานซ์ อินโฟร์ เซอร์วิส จำกัด (มหาชน)", "ร้านวัสดุก่อสร้างสมชาย")]
    [InlineData("บริษัท ซีพี ออลล์ จำกัด (มหาชน)", "หจก. แอมแฮปปี๊เนส")]
    [InlineData("บริษัท กรุงเทพประกันภัย จำกัด (มหาชน)", "บริษัท เอบีซี เทรดดิ้ง จำกัด")]
    public void คนละบริษัท_ต้องตกด่าน_ไม่ทับชื่อและไม่สอนระบบ(string dbdName, string ocrName)
    {
        var sim = FuzzyMatcher.Similarity(dbdName, ocrName);
        Assert.True(sim < Floor, $"ได้ {sim:F3} — สูงเกินไป ด่านจะปล่อยให้ทับชื่อผู้ขายด้วยบริษัทอื่น");
    }

    [Fact]
    public void ช่องว่างระหว่างสองกลุ่มต้องกว้างพอให้เกณฑ์เดียวแยกได้()
    {
        double LowestSame = new[]
        {
            FuzzyMatcher.Similarity("บริษัท สยามคอมเมอร์เชียล จำกัด", "บริษัท สยามคอมเมอร์เชียส จำกัด"),
            FuzzyMatcher.Similarity("หจก. แอมแฮปปี๊เนส", "หจก . แอมแฮปปี้เนสล"),
            FuzzyMatcher.Similarity("บริษัท ไทยเบฟเวอเรจ จำกัด (มหาชน)", "บริษัท ไทยเบฟเวอเรจ จํากัด (มหาซน)"),
        }.Min();
        double HighestDifferent = new[]
        {
            FuzzyMatcher.Similarity("บริษัท ปูนซิเมนต์ไทย จำกัด (มหาชน)", "บริษัท ไทยเบฟเวอเรจ จำกัด"),
            FuzzyMatcher.Similarity("บริษัท แอดวานซ์ อินโฟร์ เซอร์วิส จำกัด (มหาชน)", "ร้านวัสดุก่อสร้างสมชาย"),
            FuzzyMatcher.Similarity("บริษัท ซีพี ออลล์ จำกัด (มหาชน)", "หจก. แอมแฮปปี๊เนส"),
        }.Max();
        Assert.True(HighestDifferent < Floor && Floor < LowestSame,
            $"เกณฑ์ {Floor} ต้องอยู่ระหว่าง {HighestDifferent:F3} (คนละบริษัทสูงสุด) " +
            $"และ {LowestSame:F3} (เพี้ยนต่ำสุด)");
    }
}

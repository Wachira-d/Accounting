    private static async Task<(Payment Pay, PaymentAllocation Alloc)> LateAllocationAsync(Accounting.Data.AccountingDbContext db, Seed s, Document inv, decimal amount, bool late = true)
    {
        var pay = new Payment
        {
            CompanyId = s.CompanyId, PaymentNumber = "RV-DS-" + Guid.NewGuid().ToString("N")[..6], PaymentDate = Today.AddDays(-3), Amount = 1_000m,
            DocumentId = inv.Id, ContactId = s.CustomerId, PaymentMethod = PaymentMethod.BankTransfer, UnappliedAmount = 1_000m - amount,
        };
        db.Payments.Add(pay);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = s.CompanyId, EntryNumber = "JV-" + pay.PaymentNumber, EntryDate = Today, Status = JournalEntryStatus.Posted, JournalType = JournalType.General,
            Description = "จัดสรรเงินรอจัดสรร", Reference = pay.PaymentNumber + "/A1", TotalDebit = amount, TotalCredit = amount, IsAutoGenerated = true, CreatedBy = "tester",
        };
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();
        var alloc = new PaymentAllocation
        {
            CompanyId = s.CompanyId, PaymentId = pay.Id, DocumentId = inv.Id, AllocatedAmount = amount, IsLateAllocation = late,
            AppliedAt = late ? Today : null, JournalEntryId = late ? je.Id : null,
        };
        db.PaymentAllocations.Add(alloc);
        await db.SaveChangesAsync();
        return (pay, alloc);
    }


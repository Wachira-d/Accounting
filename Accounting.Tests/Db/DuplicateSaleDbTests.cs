    [Fact]
    public async Task KeepInvoice_ServiceInvoiceAfterCashSale_CrossMonth_VatOnceInPp30_CashInMoneyMonth()
    {
        // H3 + M5: ลูกค้าจ่ายสดเดือนก่อน (RC มี VAT ลง 21911) · ผู้ทำบัญชีออกใบแจ้งหนี้บริการ (พัก 21913) เดือนนี้ → คงใบแจ้งหนี้
        // ⇒ เงินเข้าธนาคารเดือนรับเงิน · ภ.พ.30 ของสองเดือนรวมกันมีภาษีขายของการขายนี้ครั้งเดียว (70) · ใบขายสดหลุดจากรายงาน
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var s = await SeedAsync(db);
        var moneyDate = new DateTime(Today.Year, Today.Month, 1).AddMonths(-1);
        var cash = await CashSaleAsync(db, s, s.CustomerId, 1_000m, 70m, date: moneyDate);
        var inv = await ServiceInvoiceAsync(db, s, s.CustomerId, 1_000m, 70m, Today);

        await PreviewThenResolveAsync(s.CompanyId, cash.Id, inv.Id, DuplicateSaleKeep.Invoice, nameof(DuplicateSaleAction.VoidCashSaleAndRecordPayment));

        using var check = DbTestDatabase.TryCreateContext()!;
        Assert.Equal((DocumentStatus.Paid, 0m), ((await DocAsync(check, inv.Id)).Status, (await DocAsync(check, inv.Id)).BalanceDue));
        // เงินสด/ธนาคาร: ขาเงินรอจัดสรรลงวันที่รับเงิน (เดือนก่อน) — สุทธิของเดือนรับเงิน = เงินที่รับจริง
        var bankGl = await check.ChartOfAccounts.AsNoTracking().Where(a => a.CompanyId == s.CompanyId && a.AccountCode == "11122-001").Select(a => a.Id).SingleAsync();
        var moneyMonthCash = await (from l in check.JournalEntryLines.AsNoTracking()
                                    join j in check.JournalEntries.AsNoTracking() on l.JournalEntryId equals j.Id
                                    where j.CompanyId == s.CompanyId && !j.IsDeleted && j.EntryDate >= moneyDate && j.EntryDate < moneyDate.AddMonths(1)
                                          && (j.Status == JournalEntryStatus.Posted || j.Status == JournalEntryStatus.Reversed)
                                          && (l.AccountId == bankGl || l.AccountId == s.CashId)

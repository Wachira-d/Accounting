        Assert.True(await check.JournalEntries.AsNoTracking().AnyAsync(j => j.SourceDocumentId == cash.Id && j.Status == JournalEntryStatus.Posted && j.ReversedByEntryId == null));
        Assert.Equal(1, await AuditCountAsync(check, s.CompanyId));

    private static JournalEntry Je(Seed s, Document d, string kind, Guid debitAccount, decimal net, decimal vat)
    {
        var je = new JournalEntry
        {
            CompanyId = s.CompanyId, EntryNumber = kind + "-" + d.DocumentNumber, EntryDate = d.DocumentDate, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.Sales, Description = "ออกใบ " + d.DocumentNumber, Reference = d.DocumentNumber, TotalDebit = net + vat, TotalCredit = net + vat,
            SourceDocumentId = d.Id, IsAutoGenerated = true, CreatedBy = "tester",
        };
        je.Lines.Add(new JournalEntryLine { AccountId = debitAccount, DebitAmount = net + vat, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = s.RevenueId, CreditAmount = net, LineOrder = 2 });
        if (vat > 0) je.Lines.Add(new JournalEntryLine { AccountId = s.VatId, CreditAmount = vat, LineOrder = 3 });
        return je;
    }

    /// <summary>ใบกำกับภาษี/ใบแจ้งหนี้ขายที่อนุมัติแล้ว (ยังไม่รับชำระ) + JE ตั้งลูกหนี้ (ภาษีขายลง 21911 ตอนออก — ใบกำกับภาษี)</summary>
    private static async Task<Document> InvoiceAsync(Accounting.Data.AccountingDbContext db, Seed s, Guid contactId, decimal net, decimal vat = 0m,
        DateTime? date = null, DocumentType type = DocumentType.TaxInvoice)
    {
        var d = new Document
        {
            CompanyId = s.CompanyId, ContactId = contactId, DocumentType = type, DocumentNumber = "TIV-DS-" + Guid.NewGuid().ToString("N")[..8],
            Status = DocumentStatus.Approved, DocumentDate = date ?? Today, SubTotal = net, VatAmount = vat, TotalAmount = net + vat, BalanceDue = net + vat,

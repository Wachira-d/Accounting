    [Fact]
    public async Task M4_ไม่บันทึก_ไม่ลบไฟล์ทันที_ครบ90วันงานลบ_ลบ_แถวที่บันทึกแล้วไม่ถูกแตะ()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var root = Root();
        var storage = Storage(root);
        var s = await SeedAsync(db);
        var slip = await SlipAsync(db, storage, s, root);
        using var d1 = DbTestDatabase.TryCreateContext()!;
        await Intake(d1, storage).StaffRejectAsync(s.Provider, s.Owner, slip.Id, "ไม่ใช่สลิปของงวดที่ค้าง");
        Assert.NotNull(await storage.ReadAllBytesAsync(slip.StoragePath));   // เดิมลบทันที ⇒ งานลบ 90 วันไม่มีแถวเข้าเงื่อนไขเลย
        using var c1 = DbTestDatabase.TryCreateContext()!;
        var row = await c1.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id);
        Assert.Equal((TaxSlipIntakeService.Statuses.Rejected, (DateTime?)null), (row.Status, row.FilePurgedAt));
        // กดซ้ำ ⇒ 409 (atomic) ไม่ส่งการ์ดใบที่สอง
        using var d2 = DbTestDatabase.TryCreateContext()!;
        await Assert.ThrowsAsync<BusinessRuleException>(() => Intake(d2, storage).StaffRejectAsync(s.Provider, s.Owner, slip.Id, "ซ้ำ"));
        // ยังไม่ครบ ⇒ ไม่ลบ · ครบ 90 วัน ⇒ ลบ
        using var d3 = DbTestDatabase.TryCreateContext()!;
        await TaxSlipIntakeService.PurgeClosedFilesAsync(d3, storage, NullLogger.Instance, DateTime.UtcNow.AddDays(30), default);
        Assert.NotNull(await storage.ReadAllBytesAsync(slip.StoragePath));
        using var d4 = DbTestDatabase.TryCreateContext()!;
        await TaxSlipIntakeService.PurgeClosedFilesAsync(d4, storage, NullLogger.Instance, DateTime.UtcNow.AddDays(TaxSlipIntakeService.ClosedFileRetentionDays + 1), default);
        Assert.Null(await storage.ReadAllBytesAsync(slip.StoragePath));
        using var c2 = DbTestDatabase.TryCreateContext()!;
        Assert.NotNull((await c2.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id)).FilePurgedAt);
    }

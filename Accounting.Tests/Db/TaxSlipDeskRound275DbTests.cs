    private static async Task<TaxSlipEvidence> SlipAsync(Accounting.Data.AccountingDbContext db, IFileStorage storage, Seed s, string root, decimal? amount = Vat,
        string? candidatesJson = null, string status = TaxSlipIntakeService.Statuses.ToStaff)
    {
        var bytes = new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 1, 2, 3, (byte)Random.Shared.Next(255), (byte)Random.Shared.Next(255) };
        var path = Path.Combine(root, "wwwroot", "uploads", "tax-slips", Guid.NewGuid().ToString("N") + ".png");
        await storage.WriteAsync(path, bytes, "image/png");
        var row = new TaxSlipEvidence
        {
            CompanyId = s.Provider, ClientCompanyId = s.Client, Source = TaxSlipIntakeService.SourceLine, ExternalMessageId = Guid.NewGuid().ToString("N"),
            SourceKey = new string('b', 64), FileSha256 = Guid.NewGuid().ToString("N") + Guid.NewGuid().ToString("N"), StoragePath = path, ContentType = "image/png",
            Amount = amount, SlipDate = P1.AddMonths(1).AddDays(3), Status = status, RuleCode = TaxSlipMatch.Codes.Many, CandidatesJson = candidatesJson,
        };
        db.TaxSlipEvidences.Add(row);
        await db.SaveChangesAsync();
        return row;
    }


    [Fact]
    public async Task H2_สองคำขอพร้อมกัน_คนละงวด_สลิปเดียว_บันทึกได้ครั้งเดียว()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL (ACCOUNTING_TEST_PG) — ข้าม · หลักฐานอยู่ที่ job db-test"); return; }
        var root = Root();
        var storage = Storage(root);
        var s = await SeedAsync(db);
        var slip = await SlipAsync(db, storage, s, root);
        using var dbA = DbTestDatabase.TryCreateContext()!;
        using var dbB = DbTestDatabase.TryCreateContext()!;
        // ทรงจริงของผู้เรียกทุกทาง: แถวสลิปถูกโหลด (track) ไว้ใน DbContext เดียวกันก่อนเรียก ApplyAsync — ค่าที่ tracker ถือคือ "ก่อนล็อก"
        await dbA.TaxSlipEvidences.FirstAsync(x => x.Id == slip.Id);
        await dbB.TaxSlipEvidences.FirstAsync(x => x.Id == slip.Id);
        var a = Remitter(dbA, storage).ApplyAsync(new TaxSlipRemitService.ApplyRequest(s.Provider, slip.Id, Cand(s, P1), s.BankAccountId, null, s.Owner, false, slip.SlipDate!.Value, null));
        var b = Remitter(dbB, storage).ApplyAsync(new TaxSlipRemitService.ApplyRequest(s.Provider, slip.Id, Cand(s, P2), s.BankAccountId, null, s.Owner, false, slip.SlipDate!.Value, null));
        var results = new List<Exception?>();
        foreach (var t in new[] { a, b })
        {
            try { await t; results.Add(null); }
            catch (Exception ex) { results.Add(ex); }
        }
        using var check = DbTestDatabase.TryCreateContext()!;
        Assert.Equal(1, await check.StatutoryRemittances.CountAsync(r => r.CompanyId == s.Client && !r.IsDeleted));   // เดิม 2 (826.12 จากเงินจ่ายจริง 413.56)
        Assert.Single(results, r => r == null);
        var gate = Assert.IsType<TaxSlipRemitService.TaxSlipGateException>(results.Single(r => r != null));
        Assert.Equal(TaxSlipMatch.Codes.Duplicate, gate.RuleCode);
        Assert.Equal(TaxSlipIntakeService.Statuses.Remitted, (await check.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id)).Status);
    }

    [Fact]
    public async Task H2_M2_พนักงานกดซ้ำหลังบันทึกแล้ว_409_แถวยังบันทึกแล้ว_ไม่ส่งการ์ดซ้ำ()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var root = Root();
        var storage = Storage(root);
        var s = await SeedAsync(db);
        var json = System.Text.Json.JsonSerializer.Serialize(new[] { new { C = s.Client, T = "VatPp36", Y = P1.Year, M = P1.Month, A = Vat, S = 0m, P = 0m, R = (Guid?)null } });
        var slip = await SlipAsync(db, storage, s, root, candidatesJson: json);
        using var d1 = DbTestDatabase.TryCreateContext()!;
        await Intake(d1, storage).StaffRemitAsync(s.Provider, s.Owner, slip.Id, 0, s.BankAccountId);
        using var c1 = DbTestDatabase.TryCreateContext()!;
        var after1 = await c1.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id);
        Assert.Equal(TaxSlipIntakeService.Statuses.Remitted, after1.Status);
        Assert.StartsWith("✅", after1.LastCardText);
        // คำขอที่สอง (ดับเบิลคลิก) — เดิม: RemitAsync ปฏิเสธ แล้วทางล้มตั้งแถวกลับเป็น ToStaff + การ์ด "ยังไม่ได้บันทึก"

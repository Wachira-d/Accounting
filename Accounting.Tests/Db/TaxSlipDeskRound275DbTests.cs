        var ex = await Assert.ThrowsAsync<BusinessRuleException>(() => Intake(d2, storage).StaffRemitAsync(s.Provider, s.Owner, slip.Id, 0, s.BankAccountId));
        Assert.Equal(409, ex.StatusCode);
        using var c2 = DbTestDatabase.TryCreateContext()!;
        var after2 = await c2.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id);
        Assert.Equal(TaxSlipIntakeService.Statuses.Remitted, after2.Status);
        Assert.Equal(after1.LastCardAt, after2.LastCardAt);   // ไม่มีการ์ดใบที่สอง
        Assert.Equal(1, await c2.StatutoryRemittances.CountAsync(r => r.CompanyId == s.Client && !r.IsDeleted));
    }

    [Fact]
    public async Task H1_บันทึกเอง_ยอดไม่ตรงสลิป_ไม่บันทึก_ยอดตรงทุกสตางค์_บันทึก_การ์ดตามจริง()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var root = Root();
        var storage = Storage(root);
        var s = await SeedAsync(db);
        // สลิปจ่ายช้า: ภาษี 413.56 + เงินเพิ่ม 6.20 = 419.76 · ไม่มีผู้สมัคร (LateWithoutRequest)
        var slip = await SlipAsync(db, storage, s, root, amount: 419.76m);
        var bad = new TaxSlipIntakeService.ManualInput(s.Client, "VatPp36", P1.Year, P1.Month, Vat, 6.00m, 0m, s.BankAccountId, null, null);
        using var d1 = DbTestDatabase.TryCreateContext()!;
        var ex = await Assert.ThrowsAsync<BusinessRuleException>(() => Intake(d1, storage).StaffManualRemitAsync(s.Provider, s.Owner, slip.Id, bad));
        Assert.Equal(TaxSlipDeskRule.ManualRuleCode, ex.RuleCode);
        using var c1 = DbTestDatabase.TryCreateContext()!;
        Assert.False(await c1.StatutoryRemittances.AnyAsync(r => r.CompanyId == s.Client && !r.IsDeleted));
        Assert.Null((await c1.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id)).LastCardText);   // ล้ม = ไม่มีการ์ดเข้ากลุ่ม
        // ทิศตรงข้าม: ยอดรวมตรงทุกสตางค์ ⇒ บันทึกผ่าน RemitAsync ตัวเดียว (ภาษี = ยอดค้างในสมุด) + การ์ด "บันทึกแล้วโดยพนักงาน"
        using var d2 = DbTestDatabase.TryCreateContext()!;
        await Intake(d2, storage).StaffManualRemitAsync(s.Provider, s.Owner, slip.Id, bad with { Surcharge = 6.20m });
        using var c2 = DbTestDatabase.TryCreateContext()!;
        var rec = await c2.StatutoryRemittances.AsNoTracking().SingleAsync(r => r.CompanyId == s.Client && !r.IsDeleted);
        Assert.Equal((Vat, 6.20m, slip.Id), (rec.Amount, rec.LateFee, rec.SlipEvidenceId));
        var row = await c2.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id);
        Assert.Equal((TaxSlipIntakeService.Statuses.Remitted, TaxSlipDeskRule.ManualRuleCode), (row.Status, row.RuleCode));
        Assert.Contains("โดยพนักงาน", row.LastCardText);
        Assert.True(await c2.AuditLogs.AnyAsync(a => a.CompanyId == s.Client && a.EntityId == rec.Id.ToString() && a.NewValues!.Contains("\"manualEntry\":true")));
    }


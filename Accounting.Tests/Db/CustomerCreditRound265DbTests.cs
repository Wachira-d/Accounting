    /// <summary>เคสเจ้าของ: ใบแจ้งหนี้ใบเดียว 5,000 แต่ลูกค้าโอน 5,000 + <paramref name="excess"/> ⇒ เงินรอจัดสรร = excess (เหตุผล "ค้างออกใบ")</summary>
    private static async Task<(PaymentResponse Pay, Document Invoice)> CreditAsync(Accounting.Data.AccountingDbContext db, Seed s, decimal excess,
        DateTime? on = null, UnappliedReason reason = UnappliedReason.UninvoicedSupply)
    {
        var day = on ?? Today;
        var inv = await InvoiceAsync(db, s, 5_000m, day);
        using var req = DbTestDatabase.TryCreateContext()!;
        var pay = await Docs(req).CreateMultiDocPaymentAsync(s.CompanyId,
            new CreatePaymentRequest(inv.Id, day, 5_000m + excess, PaymentMethod.BankTransfer, "SLIP-265", null, null,
                Allocations: new List<PaymentAllocationRequest> { new(inv.Id, 5_000m) },
                ExcessReason: reason, ExcessNote: "ค่าบริการเดือน 2 ยังไม่ได้ออกใบ"), "tester");
        return (pay, inv);
    }

    private static CustomerCreditIssueReceiptRequest Req(decimal amount, decimal price, decimal vat = 0m, decimal wht = 0m, Guid? recurring = null,
        decimal? expected = null)
        => new(amount, new List<CustomerCreditReceiptLineRequest> { new("ค่าบริการเดือน 2", 1m, price, vat, wht) }, PricesIncludeVat: true,
            RecurringTransactionId: recurring, ExpectedUnappliedBefore: expected);

    private static async Task<decimal> GlCreditNetAsync(Accounting.Data.AccountingDbContext db, Guid companyId, Guid accountId)
        => await (from l in db.JournalEntryLines.AsNoTracking()
                  join j in db.JournalEntries.AsNoTracking() on l.JournalEntryId equals j.Id
                  where j.CompanyId == companyId && l.AccountId == accountId
                        && (j.Status == JournalEntryStatus.Posted || j.Status == JournalEntryStatus.Reversed)
                  select (decimal?)(l.CreditAmount - l.DebitAmount)).SumAsync() ?? 0m;

    private static async Task<Guid> SuspenseAsync(Accounting.Data.AccountingDbContext db, Guid companyId)
        => await db.ChartOfAccounts.AsNoTracking()
            .Where(a => a.CompanyId == companyId && a.AccountCode == UnappliedReceiptAccount.Code).Select(a => a.Id).SingleAsync();

    private static async Task<BusinessRuleException> RefusedAsync(Func<Task> act, string ruleCode)
    {
        var ex = await Assert.ThrowsAsync<BusinessRuleException>(act);
        Assert.Equal(ruleCode, ex.RuleCode);
        return ex;
    }


    /// <summary>ทีม 266 ความเสี่ยง 6 — เงินที่ออกใบเสร็จตรงจากเงินรอจัดสรรแล้ว ห้ามได้ใบเสร็จ ม.86/4 ใบที่สองเมื่อจัดสรรให้ใบแจ้งหนี้ทีหลัง (คำตัดสิน 265-1-7)</summary>
    [Fact]
    public async Task ใบเสร็จจากเงินรอจัดสรรแล้ว_จัดสรรทีหลังไม่ได้ใบเสร็จซ้ำ_ส่วนที่เหลือได้ใบเดียว_และใบเสร็จนั้นไม่ปิดทางใบเสร็จของเงินที่จัดสรร()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var s = await SeedAsync(db);
        // (ก) ใช้หมดด้วยใบเสร็จ ⇒ จัดสรรให้ใบที่ออกทีหลังไม่ได้ ⇒ ไม่มีใบเสร็จที่สองของเงินก้อนเดียวกัน
        var (full, _) = await CreditAsync(db, s, 2_000m);
        using (var req = DbTestDatabase.TryCreateContext()!)
            await Credits(req).IssueReceiptAsync(s.CompanyId, full.Id, Req(2_000m, 2_000m), "tester");
        var later = await InvoiceAsync(db, s, 2_000m, Today, "INV2-");
        using (var req = DbTestDatabase.TryCreateContext()!)
            await Assert.ThrowsAsync<BusinessRuleException>(() => Credits(req).AllocateAsync(s.CompanyId, full.Id,
                new AllocateCustomerCreditRequest(later.Id, 2_000m, Today), "tester"));
        using (var c = DbTestDatabase.TryCreateContext()!)
            Assert.False(await c.Documents.AsNoTracking().AnyAsync(d => d.CompanyId == s.CompanyId && d.SettlementPaymentId == full.Id && !d.IsDeleted));

        // (ข) ใช้บางส่วน 3,000 แล้วจัดสรร 2,000 ที่เหลือ ⇒ ใบเสร็จของการจัดสรรออกได้หนึ่งใบ (กดซ้ำ = ใบเดิม) · Σ ใบเสร็จ = เงินที่รับ
        var (pay, _) = await CreditAsync(db, s, 5_000m);
        CustomerCreditMovementResult r;
        using (var req = DbTestDatabase.TryCreateContext()!)
            r = await Credits(req).IssueReceiptAsync(s.CompanyId, pay.Id, Req(3_000m, 3_000m), "tester");
        var inv2 = await InvoiceAsync(db, s, 2_000m, Today, "INV3-");
        // ผูกใบเสร็จจากเงินรอจัดสรรกับใบแจ้งหนี้ใหม่ (เช่น เส้นผูกเอกสารด้วยมือ) — ต้องไม่ถูกนับว่าครอบเงิน 2,000 ที่จัดสรร
        await db.Documents.Where(d => d.Id == r.TargetDocumentId).ExecuteUpdateAsync(u => u.SetProperty(d => d.RelatedDocumentId, (Guid?)inv2.Id));
        using (var req = DbTestDatabase.TryCreateContext()!)
            await Credits(req).AllocateAsync(s.CompanyId, pay.Id, new AllocateCustomerCreditRequest(inv2.Id, 2_000m, Today), "tester");
        IssuedReceiptResult first, again;
        using (var req = DbTestDatabase.TryCreateContext()!)
            first = await Docs(req).IssueReceiptForPaymentAsync(s.CompanyId, pay.Id, "tester", inv2.Id);
        Assert.NotEqual(r.TargetDocumentId, first.ReceiptId);
        using (var req = DbTestDatabase.TryCreateContext()!)
            again = await Docs(req).IssueReceiptForPaymentAsync(s.CompanyId, pay.Id, "tester", inv2.Id);
        Assert.True(again.AlreadyExisted);
        Assert.Equal(first.ReceiptId, again.ReceiptId);
        using var c2 = DbTestDatabase.TryCreateContext()!;
        var forInv2 = await c2.Documents.AsNoTracking().Where(d => d.CompanyId == s.CompanyId && d.SettlementPaymentId == pay.Id && d.RelatedDocumentId == inv2.Id
            && !d.IsDeleted && d.Status != DocumentStatus.Voided).ToListAsync();
        Assert.Single(forInv2);
        Assert.Equal(2_000m, forInv2[0].TotalAmount);
    }


    private static async Task<Document> InvoiceAsync(Accounting.Data.AccountingDbContext db, Seed s, decimal amount, DateTime date, string prefix = "INV-")
    {
        var d = new Document
        {
            CompanyId = s.CompanyId, ContactId = s.CustomerId, DocumentType = DocumentType.Invoice, DocumentNumber = prefix + Guid.NewGuid().ToString("N")[..8],
            Status = DocumentStatus.Approved, DocumentDate = date, SubTotal = amount, TotalAmount = amount, BalanceDue = amount,
            Currency = "THB", WhtCertAutoIssue = false, BankAccountId = s.BankId,
        };
        d.Lines.Add(new DocumentLine { LineOrder = 1, Description = "ค่าบริการเดือน 1", Quantity = 1, UnitPrice = amount, Amount = amount });
        db.Documents.Add(d);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = s.CompanyId, EntryNumber = "SV-" + d.DocumentNumber, EntryDate = date, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.Sales, Description = "ออกใบ " + d.DocumentNumber, Reference = d.DocumentNumber,
            TotalDebit = amount, TotalCredit = amount, SourceDocumentId = d.Id, IsAutoGenerated = true, CreatedBy = "tester",
        };
        je.Lines.Add(new JournalEntryLine { AccountId = s.ArId, DebitAmount = amount, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = s.RevenueId, CreditAmount = amount, LineOrder = 2 });
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();
        return d;
    }


using Microsoft.Extensions.Logging.Abstractions;
using Xunit;
using Xunit.Abstractions;

namespace Accounting.Tests.Db;

/// <summary>รอบ 266 G-1 — branch พิสูจน์ช่องโหว่ (ฐานก่อนแก้ ไม่มีโค้ดแก้): สร้างใบเสร็จของลูกค้า ข อ้างใบแจ้งหนี้ของลูกค้า ก ผ่าน CreateDocumentAsync
/// แล้วอนุมัติ ⇒ ลูกหนี้ของ ก ถูกตัดด้วยเงินของ ข · เทสต์คาดหวัง "ถูกปฏิเสธ" — บนฐานก่อนแก้ต้องแดง (= ช่องโหว่มีจริง)</summary>
[Trait("Category", "Db")]
public class ReceiptLinkG1GapProofDbTests
{
    private readonly ITestOutputHelper _out;
    public ReceiptLinkG1GapProofDbTests(ITestOutputHelper output) => _out = output;

    [Fact]
    public async Task G1_GapProof_CreateAndApproveReceiptForOtherContactInvoice_ShouldBeRefused()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var company = new Company { Name = "G1 proof " + Guid.NewGuid().ToString("N")[..6], TaxId = "0105556000025", IsVatRegistered = false };
        db.Companies.Add(company);
        await db.SaveChangesAsync();
        ChartOfAccount Acc(string code, string name, AccountType t) => new() { CompanyId = company.Id, AccountCode = code, AccountName = name, AccountType = t, Level = 4, IsActive = true };
        var cash = Acc("11111", "เงินสด", AccountType.Asset);
        var ar = Acc("11310", "ลูกหนี้การค้า", AccountType.Asset);
        var rev = Acc("41100", "รายได้", AccountType.Revenue);
        db.ChartOfAccounts.AddRange(cash, ar, rev);
        var a = new Contact { CompanyId = company.Id, Name = "ลูกค้า ก", IsCustomer = true };
        var b = new Contact { CompanyId = company.Id, Name = "ลูกค้า ข", IsCustomer = true };
        db.Contacts.AddRange(a, b);
        await db.SaveChangesAsync();
        var inv = new Document
        {
            CompanyId = company.Id, ContactId = a.Id, DocumentType = DocumentType.Invoice, DocumentNumber = "INV-G1-" + Guid.NewGuid().ToString("N")[..6],
            Status = DocumentStatus.Approved, DocumentDate = DateTime.UtcNow.Date, SubTotal = 1000m, TotalAmount = 1000m, BalanceDue = 1000m,
            Currency = "THB", ExchangeRate = 1m, WhtCertAutoIssue = false,
        };
        inv.Lines.Add(new DocumentLine { LineOrder = 1, Description = "ค่าบริการ", Quantity = 1, UnitPrice = 1000m, Amount = 1000m, AccountId = rev.Id });
        db.Documents.Add(inv);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = company.Id, EntryNumber = "SV-" + inv.DocumentNumber, EntryDate = inv.DocumentDate, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.Sales, Description = "x", Reference = inv.DocumentNumber, TotalDebit = 1000m, TotalCredit = 1000m,
            SourceDocumentId = inv.Id, IsAutoGenerated = true, CreatedBy = "t",
        };
        je.Lines.Add(new JournalEntryLine { AccountId = ar.Id, DebitAmount = 1000m, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = rev.Id, CreditAmount = 1000m, LineOrder = 2 });
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();

        static DocumentService Docs(Accounting.Data.AccountingDbContext c) => new(c, new AccountingService(c),
            RecurringTransactionDbTests.AllowAll<ISubscriptionService>.Create(), null!, null!, NullLogger<DocumentService>.Instance, null!,
            new Accounting.Services.Implementations.Ocr.VendorIntelligenceService(c, NullLogger<Accounting.Services.Implementations.Ocr.VendorIntelligenceService>.Instance),
            null!);
        Exception? refused = null;
        try
        {
            DocumentResponse rc;
            using (var req = DbTestDatabase.TryCreateContext()!)
                rc = await Docs(req).CreateDocumentAsync(company.Id, new CreateDocumentRequest(
                    DocumentType: DocumentType.Receipt, DocumentDate: DateTime.UtcNow.Date, DueDate: null, ContactId: b.Id, Reference: null, Notes: null,
                    Lines: new List<DocumentLineRequest> { new("รับชำระ", 1m, "รายการ", 1000m, 0m, 0m, 0m, rev.Id) }, RelatedDocumentId: inv.Id), "tester");
            _out.WriteLine($"สร้างใบเสร็จของ ข อ้างใบของ ก ได้: {rc.DocumentNumber}");
            using (var req2 = DbTestDatabase.TryCreateContext()!)
                await Docs(req2).ApproveDocumentAsync(company.Id, rc.Id, "tester", acknowledgeWarnings: true);
        }
        catch (Exception ex) { refused = ex; }
        using var check = DbTestDatabase.TryCreateContext()!;
        var after = await check.Documents.AsNoTracking().SingleAsync(d => d.Id == inv.Id);
        _out.WriteLine($"G1-PROOF ผล: refused={refused?.GetType().Name}:{refused?.Message} · ยอดค้างใบของ ก หลังใบเสร็จของ ข = {after.BalanceDue} สถานะ {after.Status}");
        Assert.NotNull(refused);
        Assert.Equal(1000m, after.BalanceDue);
    }
}

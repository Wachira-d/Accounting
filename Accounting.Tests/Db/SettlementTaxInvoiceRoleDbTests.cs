    /// <summary>สภาพใบเก่า (ก่อนรอบ 275): การรับทางอัตโนมัติ + ใบรับเปล่า VAT 0 · <paramref name="reclassWholesale"/> = ภาษีย้ายทั้งก้อนแล้ว (JE Dr 21913 49,000 + OutputVatDueAt)</summary>
    private static async Task<(Payment Pay, Document Plain)> LegacyPaymentAsync(Accounting.Data.AccountingDbContext db, Seed s, Guid invoiceId, decimal amount, DateTime payDate)
    {
        var pay = new Payment
        {
            CompanyId = s.CompanyId, DocumentId = invoiceId, PaymentNumber = "PAY-275C-" + Guid.NewGuid().ToString("N")[..6], PaymentDate = payDate,
            Amount = amount, PaymentMethod = PaymentMethod.BankTransfer, CreatedBy = "legacy",
        };
        db.Payments.Add(pay);
        var plain = new Document
        {
            CompanyId = s.CompanyId, ContactId = s.CustomerId, DocumentType = DocumentType.Receipt, DocumentNumber = "REC-275C-" + Guid.NewGuid().ToString("N")[..6],
            Status = DocumentStatus.Paid, DocumentDate = payDate, RelatedDocumentId = invoiceId, IsSettlementReceipt = true, SettlementPaymentId = pay.Id,
            SubTotal = amount, TotalAmount = amount, PaidAmount = amount, Currency = "THB", ExchangeRate = 1m, IsTaxInvoiceByLaw = false,
        };
        db.Documents.Add(plain);
        var inv = await db.Documents.SingleAsync(d => d.Id == invoiceId);
        inv.PaidAmount += amount; inv.BalanceDue = inv.TotalAmount - inv.PaidAmount;
        inv.Status = inv.BalanceDue <= 0.005m ? DocumentStatus.Paid : DocumentStatus.PartiallyPaid;
        await db.SaveChangesAsync();
        pay.ReceiptDocumentId = plain.Id;
        await db.SaveChangesAsync();
        return (pay, plain);

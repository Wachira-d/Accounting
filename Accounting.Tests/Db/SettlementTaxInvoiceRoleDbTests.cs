    /// <summary>ใบแจ้งหนี้ (ไม่ใช่ใบกำกับ) 700,000 + VAT 49,000 อนุมัติแล้ว + JE ตั้งลูกหนี้ · <paramref name="service"/> = ภาษีขายพัก 21913 (งานบริการ) · false = ลง 21911 (ขายสินค้า)</summary>
    private static async Task<Document> InvoiceAsync(Accounting.Data.AccountingDbContext db, Seed s, DateTime date, bool service = true, decimal baseAmt = 700_000m)
    {
        var vat = Math.Round(baseAmt * 0.07m, 2, MidpointRounding.AwayFromZero);
        var no = "INV-275C-" + Guid.NewGuid().ToString("N")[..8];
        var d = new Document
        {
            CompanyId = s.CompanyId, ContactId = s.CustomerId, DocumentType = DocumentType.Invoice, DocumentNumber = no,
            Status = DocumentStatus.Approved, DocumentDate = date, SubTotal = baseAmt, VatAmount = vat, TotalAmount = baseAmt + vat,
            BalanceDue = baseAmt + vat, Currency = "THB", ExchangeRate = 1m, WhtCertAutoIssue = false,
        };
        d.Lines.Add(new DocumentLine { LineOrder = 1, Description = "ค่าบริการที่ปรึกษา", Quantity = 1, UnitPrice = baseAmt, Amount = baseAmt, VatRate = 7m, VatAmount = vat, AccountId = s.RevenueId });
        db.Documents.Add(d);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = s.CompanyId, EntryNumber = "SV-" + no, EntryDate = date, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.Sales, Description = "ออกใบ " + no, Reference = no, TotalDebit = baseAmt + vat, TotalCredit = baseAmt + vat,
            SourceDocumentId = d.Id, IsAutoGenerated = true, CreatedBy = "tester",
        };
        je.Lines.Add(new JournalEntryLine { AccountId = s.ArId, DebitAmount = baseAmt + vat, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = s.RevenueId, CreditAmount = baseAmt, LineOrder = 2 });
        je.Lines.Add(new JournalEntryLine { AccountId = service ? s.VatUndueId : s.VatDueId, CreditAmount = vat, LineOrder = 3 });
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();
        return d;
    }


    /// <summary>ใบแจ้งหนี้ (ไม่ใช่ใบกำกับ) 700,000 + VAT 49,000 อนุมัติแล้ว + JE ตั้งลูกหนี้ · <paramref name="service"/> = ภาษีขายพัก 21913 (งานบริการ) · false = ลง 21911 (ขายสินค้า)</summary>
    private static async Task<Document> InvoiceAsync(Accounting.Data.AccountingDbContext db, Seed s, DateTime date, bool service = true)
    {
        const decimal baseAmt = 700_000m, vat = 49_000m;
        var no = "INV-275C-" + Guid.NewGuid().ToString("N")[..8];
        var d = new Document
        {
            CompanyId = s.CompanyId, ContactId = s.CustomerId, DocumentType = DocumentType.Invoice, DocumentNumber = no,
            Status = DocumentStatus.Approved, DocumentDate = date, SubTotal = baseAmt, VatAmount = vat, TotalAmount = baseAmt + vat,
            BalanceDue = baseAmt + vat, Currency = "THB", ExchangeRate = 1m, WhtCertAutoIssue = false,
        };
        d.Lines.Add(new DocumentLine { LineOrder = 1, Description = "ค่าบริการที่ปรึกษา", Quantity = 1, UnitPrice = baseAmt, Amount = baseAmt, VatRate = 7m, VatAmount = vat, AccountId = s.RevenueId });
        db.Documents.Add(d);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = s.CompanyId, EntryNumber = "SV-" + no, EntryDate = date, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.Sales, Description = "ออกใบ " + no, Reference = no, TotalDebit = baseAmt + vat, TotalCredit = baseAmt + vat,
            SourceDocumentId = d.Id, IsAutoGenerated = true, CreatedBy = "tester",
        };
        je.Lines.Add(new JournalEntryLine { AccountId = s.ArId, DebitAmount = baseAmt + vat, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = s.RevenueId, CreditAmount = baseAmt, LineOrder = 2 });
        je.Lines.Add(new JournalEntryLine { AccountId = service ? s.VatUndueId : s.VatDueId, CreditAmount = vat, LineOrder = 3 });
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();
        return d;
    }

    private static DocumentService Docs(Accounting.Data.AccountingDbContext db)
        => new(db, new AccountingService(db), RecurringTransactionDbTests.AllowAll<ISubscriptionService>.Create(), null!, null!,
            NullLogger<DocumentService>.Instance, null!,
            new Accounting.Services.Implementations.Ocr.VendorIntelligenceService(db, NullLogger<Accounting.Services.Implementations.Ocr.VendorIntelligenceService>.Instance),
            null!);

    private static async Task<(Payment Pay, Document? Receipt)> PayAsync(Seed s, Guid invoiceId, decimal amount, DateTime date, decimal? fee = null,
        PaymentEntrySource source = PaymentEntrySource.Manual)
    {
        Guid payId;
        using (var req = DbTestDatabase.TryCreateContext()!)
            payId = (await Docs(req).CreatePaymentAsync(s.CompanyId,
                new CreatePaymentRequest(invoiceId, date, amount, PaymentMethod.BankTransfer, "SLIP-275C", null, null,
                    OverrideBankAccountId: s.BankId, FeeAmount: fee, IssueReceiptDocument: true), "recorder", source)).Id;
        using var check = DbTestDatabase.TryCreateContext()!;
        var pay = await check.Payments.AsNoTracking().SingleAsync(p => p.Id == payId);
        var rec = pay.ReceiptDocumentId is Guid rid
            ? await check.Documents.AsNoTracking().SingleAsync(d => d.Id == rid && d.CompanyId == s.CompanyId) : null;
        return (pay, rec);
    }

    private static async Task<decimal> Undue21913Async(Seed s, Guid invoiceId)
    {
        using var db = DbTestDatabase.TryCreateContext()!;
        return await db.JournalEntryLines.AsNoTracking()
            .Where(l => !l.IsDeleted && l.AccountId == s.VatUndueId && l.JournalEntry.CompanyId == s.CompanyId && l.JournalEntry.SourceDocumentId == invoiceId
                && (l.JournalEntry.Status == JournalEntryStatus.Posted || l.JournalEntry.Status == JournalEntryStatus.Reversed))
            .SumAsync(l => l.CreditAmount - l.DebitAmount);
    }

    [Fact]
    public async Task HIGH1_ใบแจ้งหนี้บริการจ่ายเต็มหักค่าธรรมเนียม30_ใบเสร็จเป็นใบกำกับเต็มใบ_ภาษีย้ายทั้งก้อน()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine(Skip); return; }
        var s = await SeedAsync(db);
        var inv = await InvoiceAsync(db, s, Today.AddDays(-3));
        var (_, rec) = await PayAsync(s, inv.Id, 748_970m, Today, fee: 30m);
        Assert.NotNull(rec);
        // เดิม priorPaidBefore = 30 ⇒ ใบรับเปล่า VAT 0 "ไม่ใช่ใบกำกับภาษี"
        Assert.Equal((true, 49_000m, 700_000m, 749_000m), (rec!.IsTaxInvoiceByLaw == true, rec.VatAmount, rec.SubTotal, rec.TotalAmount));
        Assert.Equal(0m, await Undue21913Async(s, inv.Id));
    }

    [Fact]
    public async Task MED3_บริการรับสองงวด_ใบกำกับทุกงวดVATตามส่วน_ย้ายภาษีตามส่วน_ยกเลิกงวดสองถอยเฉพาะงวดนั้น()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine(Skip); return; }
        var s = await SeedAsync(db);
        var inv = await InvoiceAsync(db, s, Today.AddDays(-40));

        // งวด 1 (เส้นมือ — เดิมถูกด่าน "รับบางส่วนไม่ได้" บังคับแปลงเป็นใบกำกับก่อน)
        var (p1, r1) = await PayAsync(s, inv.Id, 374_500m, Today.AddDays(-30));
        Assert.Equal((true, 350_000m, 24_500m, 374_500m), (r1!.IsTaxInvoiceByLaw == true, r1.SubTotal, r1.VatAmount, r1.TotalAmount));
        Assert.Equal(24_500m, await Undue21913Async(s, inv.Id));   // ย้ายเฉพาะ VAT ของงวดนี้ (เดิมย้าย 49,000 ทั้งก้อนเข้าเดือนแรก)
        using (var c = DbTestDatabase.TryCreateContext()!)
        {
            var line = await c.DocumentLines.AsNoTracking().SingleAsync(l => l.DocumentId == r1.Id && !l.IsDeleted);
            Assert.Equal((7m, 24_500m, 350_000m), (line.VatRate, line.VatAmount, line.Amount));
            Assert.StartsWith("รับชำระค่าบริการ (บางส่วน) ตามใบแจ้งหนี้เลขที่ ", line.Description);
            Assert.True(await c.JournalEntries.AnyAsync(j => j.CompanyId == s.CompanyId && j.SourceDocumentId == inv.Id
                && j.Note == SettlementTaxInvoiceLoader.InstallmentReclassTag(p1.Id)));
        }

        // งวด 2 ปิดยอด ⇒ ถือ VAT ที่เหลือ · ผลรวมสองใบ = 49,000 · ภาษีพักหมด
        var (p2, r2) = await PayAsync(s, inv.Id, 374_500m, Today);
        Assert.Equal((true, 24_500m), (r2!.IsTaxInvoiceByLaw == true, r2.VatAmount));
        Assert.Equal(0m, await Undue21913Async(s, inv.Id));

        // ยกเลิกงวด 2 (ยังเหลืองวด 1) ⇒ ใบกำกับงวด 2 ถูกยกเลิก + ถอยภาษีเฉพาะ 24,500 ของงวดนั้น (ใบกำกับงวด 1 ไม่ถูกแตะ)
        using (var v = DbTestDatabase.TryCreateContext()!)
            await Docs(v).VoidPaymentAsync(s.CompanyId, p2.Id);
        Assert.Equal(24_500m, await Undue21913Async(s, inv.Id));
        using var after = DbTestDatabase.TryCreateContext()!;
        Assert.Equal(DocumentStatus.Voided, (await after.Documents.AsNoTracking().SingleAsync(d => d.Id == r2.Id)).Status);
        Assert.NotEqual(DocumentStatus.Voided, (await after.Documents.AsNoTracking().SingleAsync(d => d.Id == r1.Id)).Status);
    }


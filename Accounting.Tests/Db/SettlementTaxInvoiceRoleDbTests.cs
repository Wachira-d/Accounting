        if (db == null) { _out.WriteLine(Skip); return; }
        var s = await SeedAsync(db);
        var inv = await InvoiceAsync(db, s, Today.AddDays(-40));

        // งวด 1 (เส้นมือ — เดิมถูกด่าน "รับบางส่วนไม่ได้" บังคับแปลงเป็นใบกำกับก่อน)
        var (p1, r1) = await PayAsync(s, inv.Id, 374_500m, Today.AddDays(-30));
        Assert.Equal((true, 350_000m, 24_500m, 374_500m), (r1!.IsTaxInvoiceByLaw == true, r1.SubTotal, r1.VatAmount, r1.TotalAmount));
        Assert.Equal(24_500m, await Undue21913Async(s, inv.Id));   // ย้ายเฉพาะ VAT ของงวดนี้ (เดิมย้าย 49,000 ทั้งก้อนเข้าเดือนแรก)
        using (var c = DbTestDatabase.TryCreateContext()!)
        {
            var line = await c.DocumentLines.AsNoTracking().SingleAsync(l => l.DocumentId == r1.Id && !l.IsDeleted);
            Assert.Equal((7m, 24_500m, 350_000m), (line.VatRate, line.VatAmount, line.Amount));
            Assert.StartsWith("รับชำระค่าบริการ (บางส่วน) ตามใบแจ้งหนี้เลขที่ ", line.Description);
            Assert.True(await c.JournalEntries.AnyAsync(j => j.CompanyId == s.CompanyId && j.SourceDocumentId == inv.Id
                && j.Note == SettlementTaxInvoiceLoader.InstallmentReclassTag(p1.Id)));
        }

        // งวด 2 ปิดยอด ⇒ ถือ VAT ที่เหลือ · ผลรวมสองใบ = 49,000 · ภาษีพักหมด
        var (p2, r2) = await PayAsync(s, inv.Id, 374_500m, Today);
        Assert.Equal((true, 24_500m), (r2!.IsTaxInvoiceByLaw == true, r2.VatAmount));
        Assert.Equal(0m, await Undue21913Async(s, inv.Id));

        // ยกเลิกงวด 2 (ยังเหลืองวด 1) ⇒ ใบกำกับงวด 2 ถูกยกเลิก + ถอยภาษีเฉพาะ 24,500 ของงวดนั้น (ใบกำกับงวด 1 ไม่ถูกแตะ)
        using (var v = DbTestDatabase.TryCreateContext()!)
            await Docs(v).VoidPaymentAsync(s.CompanyId, p2.Id);
        Assert.Equal(24_500m, await Undue21913Async(s, inv.Id));
        using var after = DbTestDatabase.TryCreateContext()!;
        var gone = await after.Documents.AsNoTracking().IgnoreQueryFilters().SingleAsync(d => d.Id == r2.Id);
        Assert.True(gone.Status == DocumentStatus.Voided || gone.IsDeleted);
        var kept = await after.Documents.AsNoTracking().SingleAsync(d => d.Id == r1.Id);
        Assert.Equal((false, 24_500m), (kept.Status == DocumentStatus.Voided, kept.VatAmount));
        // รอบ 275 แพ็ก C (ต่อ): ภาษีถึงกำหนดเหลือเฉพาะงวด 1 · ภ.พ.30 เดือนงวด 1 = 24,500 · เดือนงวด 2 (ยกเลิกแล้ว) = 0
        Assert.Equal(24_500m, await Due21911Async(s, inv.Id));
        Assert.Equal(24_500m, await Pp30VatAsync(s, Today.AddDays(-30), inv.Id, r1.Id, r2.Id));
        if (Today.AddDays(-30).Month != Today.Month)
            Assert.Equal(0m, await Pp30VatAsync(s, Today, inv.Id, r1.Id, r2.Id));
    }


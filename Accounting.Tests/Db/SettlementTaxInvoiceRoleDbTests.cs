        return (pay, rec);
    }

    private static async Task<decimal> Undue21913Async(Seed s, Guid invoiceId)
    {
        using var db = DbTestDatabase.TryCreateContext()!;
        return await db.JournalEntryLines.AsNoTracking()
            .Where(l => !l.IsDeleted && l.AccountId == s.VatUndueId && l.JournalEntry.CompanyId == s.CompanyId && l.JournalEntry.SourceDocumentId == invoiceId
                && (l.JournalEntry.Status == JournalEntryStatus.Posted || l.JournalEntry.Status == JournalEntryStatus.Reversed))
            .SumAsync(l => l.CreditAmount - l.DebitAmount);
    }


/// <summary>
/// รอบ 220 (คำตัดสินข้อ 181) — <b>นำส่งช้าพร้อมเงินเพิ่ม/เบี้ยปรับ/ค่าปรับ ลงบัญชีจริงบน PostgreSQL</b>:
/// บรรทัดแยกที่ผังค่าปรับ (54820) · Cr ธนาคาร = ภาษี + สามก้อน · แถวนำส่งเก็บยอดจริง + ค่าที่ระบบเสนอ (ผู้ใช้แก้แล้วยังตรวจย้อนได้) ·
/// ยอดเข้าบวกกลับ §65 ตรี(6) จากบรรทัดที่ลงบัญชีจริงตามวันที่ (กลับรายการวันเดียวกัน = 0 · ยกเลิกงวดถัดไป = งวดเดิมเต็ม/งวดใหม่ติดลบ) ·
/// ทิศตรงข้าม: นำส่งทันกำหนดไม่มีบรรทัดค่าปรับ และบริษัทที่ไม่มีผัง 54820 ได้ผังสร้างให้ใต้หมวด 548
/// </summary>
[Trait("Category", "Db")]
public class RemittancePenaltyPostingDbTests
{
    private readonly ITestOutputHelper _out;
    public RemittancePenaltyPostingDbTests(ITestOutputHelper output) => _out = output;

    private static readonly DateTime Period = new DateTime(DateTime.UtcNow.Year, DateTime.UtcNow.Month, 1).AddMonths(-3);

    private sealed record Seed(Guid CompanyId, Dictionary<string, Guid> Acc);

    private static async Task<Seed> SeedAsync(Accounting.Data.AccountingDbContext db, bool withPenaltyAccount)
    {
        var company = new Company { Name = "บริษัททดสอบเงินเพิ่ม", TaxId = "0105556000001", IsVatRegistered = true };
        db.Companies.Add(company);
        await db.SaveChangesAsync();
        var acc = new Dictionary<string, Guid>();
        var rows = new List<(string, string, AccountType)>
        {
            ("11120", "เงินฝากธนาคาร", AccountType.Asset),
            ("11610", "ภาษีซื้อ", AccountType.Asset),
            ("11640", "ภาษีซื้อยังไม่ถึงกำหนด", AccountType.Asset),
            ("21912", "ภาษีมูลค่าเพิ่มค้างนำส่ง ภ.พ.36", AccountType.Liability),
            ("52150", "ค่าคอมมิชชั่น", AccountType.Expense),
            ("548", "ค่าธรรมเนียมและค่าปรับ", AccountType.Expense),
        };
        if (withPenaltyAccount) rows.Add(("54820", "ค่าปรับ/เบี้ยปรับ", AccountType.Expense));
        foreach (var (code, name, type) in rows)
        {
            var a = new ChartOfAccount { CompanyId = company.Id, AccountCode = code, AccountName = name, AccountType = type,
                Level = code.Length == 3 ? 3 : 4, IsActive = true };
            db.ChartOfAccounts.Add(a);
            acc[code] = a.Id;
        }
        var contact = new Contact { CompanyId = company.Id, Name = "Booking.com B.V.", IsSupplier = true, CountryCode = "NL" };
        db.Contacts.Add(contact);
        await db.SaveChangesAsync();

        // PV บริการต่างประเทศ + JE §83/6 (ทรงเดียวกับ Pp36LifecycleGoldenDbTests) ⇒ ภ.พ.36 ค้างนำส่ง 413.56
        var paidOn = Period.AddDays(14);
        var doc = new Document
        {
            CompanyId = company.Id, ContactId = contact.Id, DocumentNumber = "PV-LATE-0001", DocumentType = DocumentType.PaymentVoucher,
            Status = DocumentStatus.Paid, DocumentDate = paidOn, PaymentDate = paidOn, TaxPointDate = paidOn,
            IsForeignService = true, SubTotal = 5908m, VatAmount = 413.56m, TotalAmount = 6321.56m,
            Currency = "THB", ExchangeRate = 1m, InputVatPostedAsUndue = true,
        };
        doc.Lines.Add(new DocumentLine { LineOrder = 1, Description = "Commission", Quantity = 1, UnitPrice = 5908m, Amount = 5908m,
            VatRate = 7, VatAmount = 413.56m, AccountId = acc["52150"], IsVatClaimable = true });
        db.Documents.Add(doc);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = company.Id, EntryNumber = "JV-PV-LATE-0001", EntryDate = paidOn, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.CashPayments, SourceDocumentId = doc.Id, IsAutoGenerated = true,
            TotalDebit = 6321.56m, TotalCredit = 6321.56m,
        };
        je.Lines.Add(new JournalEntryLine { AccountId = acc["52150"], DebitAmount = 5908m, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = acc["11640"], DebitAmount = 413.56m, LineOrder = 2 });
        je.Lines.Add(new JournalEntryLine { AccountId = acc["21912"], CreditAmount = 413.56m, LineOrder = 3 });
        je.Lines.Add(new JournalEntryLine { AccountId = acc["11120"], CreditAmount = 5908m, LineOrder = 4 });
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();
        return new Seed(company.Id, acc);
    }

    private static StatutoryRemittanceService Svc(Accounting.Data.AccountingDbContext db)
        => new(db, new AccountingService(db), NullLogger<StatutoryRemittanceService>.Instance, new TaxService(db));

    private static async Task<List<JournalEntryLine>> LinesAsync(Accounting.Data.AccountingDbContext db, Guid jeId)
        => await db.JournalEntryLines.AsNoTracking().Include(l => l.Account).Where(l => l.JournalEntryId == jeId).ToListAsync();

    [Fact]
    public async Task นำส่งช้า_เงินเพิ่มเบี้ยปรับค่าปรับ_แยกบรรทัดผังค่าปรับ_ธนาคารรวมทุกก้อน_บวกกลับ65ตรี()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL (ACCOUNTING_TEST_PG) — ข้าม · หลักฐานอยู่ที่ job db-test"); return; }
        var s = await SeedAsync(db, withPenaltyAccount: true);
        // จ่ายช้า ~1 เดือนเศษหลังกำหนด (ไม่ใช่วันอนาคต)
        var payDate = Period.AddMonths(2).AddDays(10);

        var preview = await Svc(db).PreviewAsync(s.CompanyId, "VatPp36", Period.Year, Period.Month, payDate);
        Assert.NotNull(preview);
        Assert.True(preview!.LateFeePreview > 0);

        var r = await Svc(db).RemitAsync(s.CompanyId, new RemitRequest("VatPp36", Period.Year, Period.Month, payDate,
            BankGlAccountId: s.Acc["11120"], LateSurcharge: 12.34m, Penalty: 50m, OtherFine: 200m), "tester");
        Assert.Equal(413.56m, r.Amount);
        Assert.Equal((12.34m, 50m, 200m), (r.LateFee, r.Penalty, r.OtherFine));

        using var check = DbTestDatabase.TryCreateContext()!;
        var lines = await LinesAsync(check, r.JournalEntryId!.Value);
        var pen = lines.Where(l => l.AccountId == s.Acc["54820"]).OrderBy(l => l.DebitAmount).Select(l => l.DebitAmount).ToList();
        Assert.Equal(new[] { 12.34m, 50m, 200m }, pen);
        Assert.Equal(413.56m + 262.34m, lines.Where(l => l.AccountId == s.Acc["11120"]).Sum(l => l.CreditAmount));
        Assert.Equal(lines.Sum(l => l.DebitAmount), lines.Sum(l => l.CreditAmount));

        var row = await check.StatutoryRemittances.AsNoTracking().SingleAsync(x => x.Id == r.Id);
        Assert.Equal((12.34m, 50m, 200m), (row.LateFee, row.Penalty, row.OtherFine));
        // ค่าที่ระบบเสนอเก็บคู่ (ผู้ใช้แก้แล้ว) — ตัวตั้งเดียวกับ preview
        Assert.Equal(preview.LateFeePreview, row.SuggestedLateFee);
        Assert.Equal(0m, row.SuggestedPenalty);

        var addBack = await new TaxService(check).ComputeSection65TerAddBackAsync(s.CompanyId, Period, DateTime.UtcNow.Date.AddDays(1));
        Assert.Equal(262.34m, addBack);
    }

    [Fact]
    public async Task นำส่งทันกำหนด_ไม่มีบรรทัดค่าปรับ_ไม่สร้างผัง_บวกกลับศูนย์()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL — ข้าม"); return; }
        var s = await SeedAsync(db, withPenaltyAccount: false);
        var r = await Svc(db).RemitAsync(s.CompanyId, new RemitRequest("VatPp36", Period.Year, Period.Month, Period.AddDays(20),
            BankGlAccountId: s.Acc["11120"]), "tester");
        Assert.Equal((0m, 0m, 0m), (r.LateFee, r.Penalty, r.OtherFine));

        using var check = DbTestDatabase.TryCreateContext()!;
        var lines = await LinesAsync(check, r.JournalEntryId!.Value);
        Assert.Equal(2, lines.Count);   // Dr 21912 / Cr ธนาคาร เท่านั้น
        Assert.False(await check.ChartOfAccounts.AnyAsync(a => a.CompanyId == s.CompanyId && a.AccountCode == "54820"));
        Assert.Equal(0m, await new TaxService(check).ComputeSection65TerAddBackAsync(s.CompanyId, Period, DateTime.UtcNow.Date.AddDays(1)));
    }

    [Fact]
    public async Task ผังเก่าไม่มี54820_สร้างให้ใต้หมวด548_แล้วลงค่าปรับ()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL — ข้าม"); return; }
        var s = await SeedAsync(db, withPenaltyAccount: false);
        var r = await Svc(db).RemitAsync(s.CompanyId, new RemitRequest("VatPp36", Period.Year, Period.Month, Period.AddMonths(2).AddDays(10),
            BankGlAccountId: s.Acc["11120"], LateSurcharge: 0m, OtherFine: 100m), "tester");

        using var check = DbTestDatabase.TryCreateContext()!;
        var created = await check.ChartOfAccounts.AsNoTracking().SingleAsync(a => a.CompanyId == s.CompanyId && a.AccountCode == PenaltyExpenseAccount.DefaultCode);
        Assert.Equal(s.Acc["548"], created.ParentAccountId);
        Assert.Equal(AccountType.Expense, created.AccountType);
        var lines = await LinesAsync(check, r.JournalEntryId!.Value);
        Assert.Equal(100m, lines.Where(l => l.AccountId == created.Id).Sum(l => l.DebitAmount));
    }

    // ═══ ฝ่ายค้านข้อ 3: บวกกลับจากบรรทัดที่ลงบัญชีจริง ตามวันที่ลงบัญชี ═══

    private async Task<(Seed S, RemitResult R, DateTime Pay)> RemitLateAsync(Accounting.Data.AccountingDbContext db)
    {
        var s = await SeedAsync(db, withPenaltyAccount: true);
        var pay = Period.AddMonths(2).AddDays(10);
        var r = await Svc(db).RemitAsync(s.CompanyId, new RemitRequest("VatPp36", Period.Year, Period.Month, pay,
            BankGlAccountId: s.Acc["11120"], LateSurcharge: 12.34m, Penalty: 50m, OtherFine: 200m), "tester");
        return (s, r, pay);
    }

    [Fact]
    public async Task กลับรายการด้วยมือวันเดียวกัน_บวกกลับสุทธิศูนย์()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL — ข้าม"); return; }
        var (s, r, pay) = await RemitLateAsync(db);
        await new AccountingService(db).ReverseJournalEntryAsync(s.CompanyId, r.JournalEntryId!.Value, reversalDate: pay, description: "กลับรายการทดสอบ");

        using var check = DbTestDatabase.TryCreateContext()!;
        Assert.Equal(0m, await new TaxService(check).ComputeSection65TerAddBackAsync(s.CompanyId, Period, DateTime.UtcNow.Date.AddDays(1)));
    }

    [Fact]
    public async Task ยกเลิกการนำส่งในงวดถัดไป_งวดเดิมบวกกลับเต็ม_งวดที่กลับติดลบเท่ากัน()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL — ข้าม"); return; }
        var (s, r, pay) = await RemitLateAsync(db);
        // ปิดงวดของวันที่จ่าย ⇒ VoidRemittanceAsync กลับรายการลงวันนี้ (งวดถัดไป)
        db.FiscalPeriods.Add(new FiscalPeriod { CompanyId = s.CompanyId, Name = "ปิดแล้ว", Year = pay.Year, Month = pay.Month,
            StartDate = new DateTime(pay.Year, pay.Month, 1), EndDate = new DateTime(pay.Year, pay.Month, 1).AddMonths(1).AddDays(-1),
            Status = FiscalPeriodStatus.Closed });
        await db.SaveChangesAsync();
        await Svc(db).VoidRemittanceAsync(s.CompanyId, r.Id, "ทดสอบยกเลิกข้ามงวด", "tester");

        using var check = DbTestDatabase.TryCreateContext()!;
        var tax = new TaxService(check);
        var monthEnd = new DateTime(pay.Year, pay.Month, 1).AddMonths(1).AddDays(-1);
        Assert.Equal(262.34m, await tax.ComputeSection65TerAddBackAsync(s.CompanyId, Period, monthEnd));                       // งวดเดิมไม่ถูกย้อนลบ
        Assert.Equal(-262.34m, await tax.ComputeSection65TerAddBackAsync(s.CompanyId, monthEnd.AddDays(1), DateTime.UtcNow.Date.AddDays(1)));
        Assert.True(await check.StatutoryRemittances.IgnoreQueryFilters().AnyAsync(x => x.Id == r.Id && x.IsDeleted));
    }

    [Fact]
    public async Task ยอดติดลบ_ปฏิเสธ_ไม่มีแถวนำส่ง()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL — ข้าม"); return; }
        var s = await SeedAsync(db, withPenaltyAccount: true);
        await Assert.ThrowsAsync<BusinessRuleException>(() => Svc(db).RemitAsync(s.CompanyId,
            new RemitRequest("VatPp36", Period.Year, Period.Month, Period.AddDays(20), BankGlAccountId: s.Acc["11120"], Penalty: -1m), "tester"));
        using var check = DbTestDatabase.TryCreateContext()!;
        Assert.False(await check.StatutoryRemittances.AnyAsync(x => x.CompanyId == s.CompanyId));
    }
}

            $"UPDATE \"ProviderAutomationConsents\" SET \"WithdrawnAt\" = now(), \"WithdrawnByUserId\" = {s.Owner} WHERE \"Id\" = {row.Id}");
        Assert.Equal(1, n);
        await Assert.ThrowsAnyAsync<Exception>(() => db.Database.ExecuteSqlInterpolatedAsync(

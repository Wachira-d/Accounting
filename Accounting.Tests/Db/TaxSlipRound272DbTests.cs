            db.ChartOfAccounts.Add(a);
            acc[code] = a.Id;
        }
        var bank = new BankAccount { CompanyId = client.Id, AccountName = "บัญชีหลัก", BankName = "กสิกรไทย", AccountNumber = "123-4-51234-0", LinkedAccountId = acc["11120"] };

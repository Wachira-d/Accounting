        var root = Path.Combine(Path.GetTempPath(), "r272-" + Guid.NewGuid().ToString("N"));
        var storage = Storage(root);
        var s = await SeedAsync(db);
        await GrantAsync(db, s, ProviderConsent.SourcePowerOfAttorney);
        var slip = await SlipAsync(db, storage, s, root);
        var auto = new TaxSlipRemitService.ApplyRequest(s.Provider, slip.Id, Cand(s), s.BankAccountId, null, null, false, slip.SlipDate!.Value, null);
        var ex = await Assert.ThrowsAsync<TaxSlipRemitService.TaxSlipGateException>(() => Remitter(db, storage).ApplyAsync(auto));

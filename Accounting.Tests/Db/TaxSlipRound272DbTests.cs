        using var db2 = DbTestDatabase.TryCreateContext()!;
        var done = await Remitter(db2, storage).ApplyAsync(auto with { StaffUserId = s.Owner });
        Assert.NotEqual(Guid.Empty, done.Result.Id);
    }


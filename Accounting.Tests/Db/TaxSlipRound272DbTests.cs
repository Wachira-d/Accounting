    private static IFileStorage Storage(string root) => new LocalDiskFileStorage(new FileStorageLocator(Path.Combine(root, "uploads"), Path.Combine(root, "wwwroot"), root, root));

    private static ProviderConsentService Consent(Accounting.Data.AccountingDbContext db) => new(db, new NoPerms(), NullLogger<ProviderConsentService>.Instance);

    private static TaxSlipRemitService Remitter(Accounting.Data.AccountingDbContext db, IFileStorage storage)
        => new(db, new StatutoryRemittanceService(db, new AccountingService(db), NullLogger<StatutoryRemittanceService>.Instance, new TaxService(db)), Consent(db),
            new FileAttachmentService(db, NullLogger<FileAttachmentService>.Instance, F4Proxy<IErrorLogService>.Create((_, _) => null), storage), storage,
            NullLogger<TaxSlipRemitService>.Instance);

    private static async Task<ProviderAutomationConsent> GrantAsync(Accounting.Data.AccountingDbContext db, Seed s, string source = ProviderConsent.SourceWeb)
    {
        var at = PartnerConsent.TruncateToSecond(DateTime.UtcNow);
        const string types = "VatPp30,VatPp36,WhtPnd53";
        var row = new ProviderAutomationConsent
        {
            CompanyId = s.Client, ProviderCompanyId = s.Provider, Scope = ProviderConsent.Scope, TaxTypes = types, TextVersion = 1, HashVersion = 1,
            EvidenceSource = source, GrantedByUserId = s.Owner, GrantedAt = at,
            EvidenceHash = ProviderConsent.Hash(s.Client, s.Provider, types, null, null, false, 1, ProviderConsent.TextFor(1)!, s.Owner, at),
        };
        db.ProviderAutomationConsents.Add(row);
        await db.SaveChangesAsync();
        return row;
    }

    private static async Task<TaxSlipEvidence> SlipAsync(Accounting.Data.AccountingDbContext db, IFileStorage storage, Seed s, string root)
    {
        var bytes = new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 1, 2, 3, (byte)Random.Shared.Next(255) };
        var path = Path.Combine(root, "wwwroot", "uploads", "tax-slips", Guid.NewGuid().ToString("N") + ".png");
        await storage.WriteAsync(path, bytes, "image/png");
        var row = new TaxSlipEvidence
        {
            CompanyId = s.Provider, ClientCompanyId = s.Client, Source = TaxSlipIntakeService.SourceLine, ExternalMessageId = Guid.NewGuid().ToString("N"),
            SourceKey = new string('a', 64), FileSha256 = Guid.NewGuid().ToString("N") + Guid.NewGuid().ToString("N"), StoragePath = path, ContentType = "image/png",
            ControlCodeHash = TaxSlipRefHash.ControlCode(SlipCorpusRound272.ControlCode), ControlCodeLast4 = "3579", Amount = 413.56m, SlipDate = Period.AddMonths(1).AddDays(3),
            Status = TaxSlipIntakeService.Statuses.Received, RuleCode = TaxSlipMatch.Codes.OneNoControlCode,
        };
        db.TaxSlipEvidences.Add(row);
        await db.SaveChangesAsync();
        return row;
    }

    private static TaxSlipMatch.Candidate Cand(Seed s) => new(s.Client, "VatPp36", Period.Year, Period.Month, 413.56m, 0m, 0m, null);

    [Fact]
    public async Task สลิปผ่านทุกด่าน_บันทึกผ่านRemitAsync_แนบสลิป_ที่มาSlip_auditสองบริษัท()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL (ACCOUNTING_TEST_PG) — ข้าม · หลักฐานอยู่ที่ job db-test"); return; }
        var root = Path.Combine(Path.GetTempPath(), "r272-" + Guid.NewGuid().ToString("N"));
        var storage = Storage(root);
        var s = await SeedAsync(db);
        var consent = await GrantAsync(db, s);
        var slip = await SlipAsync(db, storage, s, root);

        var done = await Remitter(db, storage).ApplyAsync(new TaxSlipRemitService.ApplyRequest(s.Provider, slip.Id, Cand(s), s.BankAccountId, null, null, false,
            slip.SlipDate!.Value, "กสิกรไทย ••1234"));

        using var check = DbTestDatabase.TryCreateContext()!;
        var rec = await check.StatutoryRemittances.AsNoTracking().SingleAsync(r => r.Id == done.Result.Id);
        Assert.Equal((TaxSlipRemitView.SourceSlip, slip.Id, s.Provider, consent.Id, "3579"), (rec.Source, rec.SlipEvidenceId, rec.ActedByProviderCompanyId, rec.ProviderConsentId, rec.ControlCodeLast4));
        Assert.Null(rec.FilingNumber);   // 272-1-4: สลิปไม่ใช่เลขรับ
        Assert.Equal(done.AttachmentId, rec.ReceiptAttachmentId);
        Assert.True(await check.FileAttachments.AnyAsync(f => f.Id == done.AttachmentId && f.CompanyId == s.Client && f.EntityType == "StatutoryRemittance"));
        var lines = await check.JournalEntryLines.AsNoTracking().Where(l => l.JournalEntryId == rec.JournalEntryId).ToListAsync();
        Assert.Equal(413.56m, lines.Where(l => l.AccountId == s.Acc["21912"]).Sum(l => l.DebitAmount));
        Assert.Equal(413.56m, lines.Where(l => l.AccountId == s.Acc["11120"]).Sum(l => l.CreditAmount));
        var row = await check.TaxSlipEvidences.AsNoTracking().SingleAsync(x => x.Id == slip.Id);
        Assert.Equal(TaxSlipIntakeService.Statuses.Remitted, row.Status);
        Assert.Equal(rec.Id, row.StatutoryRemittanceId);
        Assert.True(await check.AuditLogs.AnyAsync(a => a.CompanyId == s.Client && a.EntityId == rec.Id.ToString() && a.NewValues!.Contains("TaxSlipRemitted")));
        Assert.True(await check.AuditLogs.AnyAsync(a => a.CompanyId == s.Provider && a.EntityId == slip.Id.ToString() && a.NewValues!.Contains("ProviderActedForClient")));
        Assert.Contains(TaxSlipRemitView.NoFilingNumber, (await new StatutoryRemittanceService(check, new AccountingService(check), NullLogger<StatutoryRemittanceService>.Instance,
            new TaxService(check)).GetDashboardAsync(s.Client)).RecentHistory.Single(h => h.Id == rec.Id).FilingNote ?? "");
        // บันทึกซ้ำสลิปเดิม ⇒ ด่าน (ไม่สร้างแถวนำส่งที่สอง)
        await Assert.ThrowsAsync<TaxSlipRemitService.TaxSlipGateException>(() => Remitter(db, storage).ApplyAsync(new TaxSlipRemitService.ApplyRequest(s.Provider, slip.Id, Cand(s),
            s.BankAccountId, null, null, false, slip.SlipDate!.Value, null)));
        Assert.Equal(1, await check.StatutoryRemittances.CountAsync(r => r.CompanyId == s.Client && r.RemittanceType == "VatPp36" && !r.IsDeleted));
    }

    [Fact]
    public async Task ไม่มีความยินยอม_หรือถอนแล้ว_ระบบไม่บันทึก()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var root = Path.Combine(Path.GetTempPath(), "r272-" + Guid.NewGuid().ToString("N"));
        var storage = Storage(root);
        var s = await SeedAsync(db);
        var slip = await SlipAsync(db, storage, s, root);
        var apply = new TaxSlipRemitService.ApplyRequest(s.Provider, slip.Id, Cand(s), s.BankAccountId, null, null, false, slip.SlipDate!.Value, null);
        var ex = await Assert.ThrowsAsync<TaxSlipRemitService.TaxSlipGateException>(() => Remitter(db, storage).ApplyAsync(apply));
        Assert.Contains(ProviderConsent.Codes.NoConsent, ex.RuleCode);

        using var db2 = DbTestDatabase.TryCreateContext()!;
        var consent = await GrantAsync(db2, s);
        await Consent(db2).WithdrawAsync(s.Client, s.Owner, consent.Id, "ทดสอบถอน");
        using var db3 = DbTestDatabase.TryCreateContext()!;
        var ex2 = await Assert.ThrowsAsync<TaxSlipRemitService.TaxSlipGateException>(() => Remitter(db3, storage).ApplyAsync(apply));
        Assert.Contains(ProviderConsent.Codes.NoConsent, ex2.RuleCode);   // แถวที่ถอนแล้วไม่ใช่ "แถวที่ใช้อยู่"
        Assert.False(await db3.StatutoryRemittances.AnyAsync(r => r.CompanyId == s.Client && !r.IsDeleted));
    }

    [Fact]
    public async Task หนังสือมอบอำนาจ_ระบบไม่บันทึกเอง_พนักงานกดได้()
    {
        using var db = DbTestDatabase.TryCreateContext();

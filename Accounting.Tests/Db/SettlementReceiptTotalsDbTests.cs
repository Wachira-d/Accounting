    /// <summary>ใบกำกับภาษีขายที่อนุมัติแล้ว มูลค่า 700,000 + VAT 49,000 (ตัวเลขจากรายงานผู้ใช้) + JE ตั้งลูกหนี้/ภาษีขาย</summary>
    private static async Task<Document> TaxInvoiceAsync(Accounting.Data.AccountingDbContext db, Seed s, DateTime date)
    {
        const decimal baseAmt = 700_000m, vat = 49_000m;
        var no = "TIV-273-" + Guid.NewGuid().ToString("N")[..8];
        var d = new Document
        {
            CompanyId = s.CompanyId, ContactId = s.CustomerId, DocumentType = DocumentType.TaxInvoice, DocumentNumber = no,
            Status = DocumentStatus.Approved, DocumentDate = date, SubTotal = baseAmt, VatAmount = vat, TotalAmount = baseAmt + vat,
            BalanceDue = baseAmt + vat, Currency = "THB", ExchangeRate = 1m, WhtCertAutoIssue = false, IsTaxInvoiceByLaw = true,
        };
        d.Lines.Add(new DocumentLine { LineOrder = 1, Description = "ค่าบริการติดตั้งระบบ", Quantity = 1, UnitPrice = baseAmt, Amount = baseAmt, VatRate = 7m, VatAmount = vat, AccountId = s.RevenueId });
        db.Documents.Add(d);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = s.CompanyId, EntryNumber = "SV-" + no, EntryDate = date, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.Sales, Description = "ออกใบ " + no, Reference = no, TotalDebit = baseAmt + vat, TotalCredit = baseAmt + vat,
            SourceDocumentId = d.Id, IsAutoGenerated = true, CreatedBy = "tester",
        };
        je.Lines.Add(new JournalEntryLine { AccountId = s.ArId, DebitAmount = baseAmt + vat, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = s.RevenueId, CreditAmount = baseAmt, LineOrder = 2 });
        je.Lines.Add(new JournalEntryLine { AccountId = s.VatId, CreditAmount = vat, LineOrder = 3 });
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();
        return d;
    }

    private static DocumentService Docs(Accounting.Data.AccountingDbContext db)
        => new(db, new AccountingService(db), RecurringTransactionDbTests.AllowAll<ISubscriptionService>.Create(), null!, null!,
            NullLogger<DocumentService>.Instance, null!,
            new Accounting.Services.Implementations.Ocr.VendorIntelligenceService(db, NullLogger<Accounting.Services.Implementations.Ocr.VendorIntelligenceService>.Instance),
            null!);

    /// <summary>บันทึกรับชำระ (เส้นจริง) + ออกใบเสร็จอัตโนมัติ — คืนใบเสร็จที่ได้</summary>
    private static async Task<Document> PayWithReceiptAsync(Seed s, Guid invoiceId, decimal amount, DateTime date, decimal? fee = null)
    {
        Guid payId;
        using (var req = DbTestDatabase.TryCreateContext()!)
            payId = (await Docs(req).CreatePaymentAsync(s.CompanyId,
                new CreatePaymentRequest(invoiceId, date, amount, PaymentMethod.BankTransfer, "SLIP-273", null, null,
                    OverrideBankAccountId: s.BankId, FeeAmount: fee, IssueReceiptDocument: true), "recorder", PaymentEntrySource.Manual)).Id;
        using var check = DbTestDatabase.TryCreateContext()!;
        var pay = await check.Payments.AsNoTracking().SingleAsync(p => p.Id == payId);
        Assert.NotNull(pay.ReceiptDocumentId);
        return await check.Documents.AsNoTracking().SingleAsync(d => d.Id == pay.ReceiptDocumentId!.Value && d.CompanyId == s.CompanyId);
    }

    private static async Task<string> HtmlAsync(Guid companyId, Guid documentId)
    {
        using var render = DbTestDatabase.TryCreateContext()!;
        return await new PdfGenerationService(render, new DocumentTemplateService(render))
            .GenerateDocumentHtmlAsync(companyId, new GeneratePdfRequest(documentId, null, null, null, null));
    }

    [Fact]
    public async Task ใบเสร็จรับชำระTIV700k_กระดาษและหน้ารายละเอียด_ยอดรับชำระ749k_อ้างอิงใบกำกับ_ข้อมูลไม่เปลี่ยน()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine(Skip); return; }
        var s = await SeedAsync(db);
        var tiv = await TaxInvoiceAsync(db, s, Today.AddDays(-3));
        var rec = await PayWithReceiptAsync(s, tiv.Id, 749_000m, Today);

        // ข้อมูลที่เก็บ: ใบเสร็จไม่ถือ VAT (กติการอบ 269 — นอก ภ.พ.30/§87) — ไม่มี migration เพราะค่าที่ persist ถูกอยู่แล้ว
        Assert.Equal((true, (Guid?)tiv.Id, 0m, 749_000m, 749_000m, (bool?)false),
            (rec.IsSettlementReceipt, rec.RelatedDocumentId, rec.VatAmount, rec.SubTotal, rec.TotalAmount, rec.IsTaxInvoiceByLaw));

        var html = await HtmlAsync(s.CompanyId, rec.Id);
        Assert.DoesNotContain("ยอดรวมก่อน VAT", html);
        Assert.Contains("<span>ยอดรับชำระ</span><span>749,000.00</span>", html);
        Assert.Contains($"(ตามใบกำกับภาษีเลขที่ {tiv.DocumentNumber}", html);
        Assert.Contains(System.Net.WebUtility.HtmlEncode("มูลค่า 700,000.00 · VAT 49,000.00 · รวม 749,000.00)"), html);
        Assert.DoesNotContain("รับชำระบางส่วน", html);

        using var read = DbTestDatabase.TryCreateContext()!;
        var resp = await Docs(read).GetDocumentAsync(s.CompanyId, rec.Id);
        Assert.NotNull(resp.SettlementTotals);
        Assert.Equal(("ยอดรับชำระ", 749_000m, (string?)null), (resp.SettlementTotals!.AmountLabel, resp.SettlementTotals.AmountReceived, resp.SettlementTotals.SettledGrossLabel));
        Assert.StartsWith($"(ตามใบกำกับภาษีเลขที่ {tiv.DocumentNumber} ลงวันที่ ", resp.SettlementTotals.Lines[0]);

        // ทิศตรงข้าม: ใบกำกับต้นทางเองยังพิมพ์ "ยอดรวมก่อน VAT / VAT" ตามเดิม
        var tivHtml = await HtmlAsync(s.CompanyId, tiv.Id);
        Assert.Contains("<span>ยอดรวมก่อน VAT</span><span>700,000.00</span>", tivHtml);
        Assert.Contains("49,000.00", tivHtml);
        Assert.Null((await Docs(read).GetDocumentAsync(s.CompanyId, tiv.Id)).SettlementTotals);
    }

    [Fact]
    public async Task รับชำระบางส่วน_ยอดรับชำระเท่าที่รับ_บอกว่าบางส่วนของยอดเต็ม()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine(Skip); return; }
        var s = await SeedAsync(db);
        var tiv = await TaxInvoiceAsync(db, s, Today.AddDays(-3));
        var rec = await PayWithReceiptAsync(s, tiv.Id, 300_000m, Today);
        Assert.Equal((0m, 300_000m), (rec.VatAmount, rec.TotalAmount));
        var html = await HtmlAsync(s.CompanyId, rec.Id);
        Assert.Contains("<span>ยอดรับชำระ</span><span>300,000.00</span>", html);
        Assert.Contains(System.Net.WebUtility.HtmlEncode("รับชำระบางส่วน — ยอดคงค้างก่อนรับครั้งนี้ 749,000.00 · คงค้างหลังรับครั้งนี้ 449,000.00"), html);
        Assert.DoesNotContain("ยอดรวมก่อน VAT", html);

        // งวดสองปิดใบ ⇒ ใบเสร็จงวดสองครบ (อ้างการรับก่อนหน้า) · ใบเสร็จงวดแรกยังเป็นบางส่วน (มีรายการหลังจากนั้น — ไล่ตามลำดับ ไม่ใช้ยอดค้างปัจจุบัน 0)
        var rec2 = await PayWithReceiptAsync(s, tiv.Id, 449_000m, Today);
        using var read = DbTestDatabase.TryCreateContext()!;
        var lines2 = (await Docs(read).GetDocumentAsync(s.CompanyId, rec2.Id)).SettlementTotals!.Lines;
        Assert.Contains("รับชำระก่อนหน้า 300,000.00", lines2);
        Assert.Contains("ชำระครบยอดคงค้าง 449,000.00", lines2);
        Assert.DoesNotContain(lines2, l => l.Contains("บางส่วน"));
        var lines1 = (await Docs(read).GetDocumentAsync(s.CompanyId, rec.Id)).SettlementTotals!.Lines;
        Assert.Contains("รับชำระบางส่วน — ยอดคงค้างก่อนรับครั้งนี้ 749,000.00 · คงค้างหลังรับครั้งนี้ 449,000.00", lines1);
    }

    [Fact]
    public async Task ฝ่ายค้านMED1_โอน748970หักค่าธรรมเนียม30ปิดใบ_ไม่ใช่บางส่วน_หน้าลูกค้าได้ผลเดียวกัน()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine(Skip); return; }
        var s = await SeedAsync(db);
        var tiv = await TaxInvoiceAsync(db, s, Today.AddDays(-3));
        var rec = await PayWithReceiptAsync(s, tiv.Id, 748_970m, Today, fee: 30m);
        using var read = DbTestDatabase.TryCreateContext()!;
        var after = await read.Documents.AsNoTracking().Where(d => d.Id == tiv.Id).Select(d => new { d.Status, d.BalanceDue }).SingleAsync();
        Assert.Equal((DocumentStatus.Paid, 0m), (after.Status, after.BalanceDue));
        var html = await HtmlAsync(s.CompanyId, rec.Id);
        // รอบ 284 (คำตัดสิน 284-8 · T3 LOW-5): ใบเสร็จแสดงยอดที่ลูกค้าชำระเต็ม 749,000 (ค่าธรรมเนียมเป็นค่าใช้จ่ายผู้ขาย — ไม่ลดยอดบนใบ) · เดิม 748,970
        Assert.Contains("<span>ยอดรับชำระ</span><span>749,000.00</span>", html);
        Assert.Contains(System.Net.WebUtility.HtmlEncode("ตัดชำระครั้งนี้ 749,000.00: รับเงิน 748,970.00 · ค่าธรรมเนียมที่ถูกหัก 30.00"), html);
        Assert.DoesNotContain("รับชำระบางส่วน", html);
        // L3: หน้าเอกสารของลูกค้า — ตัวโหลด/ข้อความเดียวกับกระดาษ
        var dto = await SettlementReceiptTotalsLoader.DtoForAsync(read, s.CompanyId, rec.Id, english: false);
        Assert.NotNull(dto);
        Assert.Equal(("ยอดรับชำระ", 749_000m), (dto!.AmountLabel, dto.AmountReceived));
        Assert.Equal((await Docs(read).GetDocumentAsync(s.CompanyId, rec.Id)).SettlementTotals!.Lines, dto.Lines);
        // tenant: บริษัทอื่นอ่านไม่ได้
        Assert.Null(await SettlementReceiptTotalsLoader.DtoForAsync(read, Guid.NewGuid(), rec.Id, english: false));
    }


    [Fact]
    public async Task DraftReceipt_LinkThenApprove_SettlesInvoice()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน PostgreSQL (ACCOUNTING_TEST_PG) — ข้าม · หลักฐานอยู่ที่ job db-test"); return; }
        var s = await SeedAsync(db);
        var inv = await InvoiceAsync(db, s, s.CustomerId, 1_000m);
        var rc = await ReceiptAsync(db, s, s.CustomerId, 1_000m);

        // ผู้สมัครทั้งสองทิศเห็นกันและกัน (ใบเดียวกัน · เส้น SetDraftSource)
        using (var req = DbTestDatabase.TryCreateContext()!)
        {
            var fromInv = await Links(req).CandidatesAsync(s.CompanyId, inv.Id, User);
            Assert.Contains(fromInv.Items, x => x.ReceiptDocumentId == rc.Id && x.Allowed && x.Route == nameof(ReceiptLinkRoute.SetDraftSource));
            var fromRc = await Links(req).CandidatesAsync(s.CompanyId, rc.Id, User);
            Assert.Equal("receipt", fromRc.Side);
            Assert.Contains(fromRc.Items, x => x.InvoiceId == inv.Id && x.Allowed);
        }
        // พรีวิวไม่เขียนอะไร
        using (var req = DbTestDatabase.TryCreateContext()!)
            await Links(req).PreviewAsync(s.CompanyId, new ReceiptLinkRequest(inv.Id, rc.Id, null), User);
        using (var check = DbTestDatabase.TryCreateContext()!)
            Assert.Null((await check.Documents.AsNoTracking().SingleAsync(d => d.Id == rc.Id)).RelatedDocumentId);

        ReceiptLinkResult res;
        using (var req = DbTestDatabase.TryCreateContext()!)
            res = await PreviewThenLinkAsync(req, s.CompanyId, new ReceiptLinkRequest(inv.Id, rc.Id, null));
        Assert.Equal(nameof(ReceiptLinkRoute.SetDraftSource), res.Route);
        using (var check = DbTestDatabase.TryCreateContext()!)
        {
            Assert.Equal(inv.Id, (await check.Documents.AsNoTracking().SingleAsync(d => d.Id == rc.Id)).RelatedDocumentId);
            Assert.Equal(1_000m, (await check.Documents.AsNoTracking().SingleAsync(d => d.Id == inv.Id)).BalanceDue);   // ยังไม่ตัดจนกว่าจะอนุมัติ
            Assert.Equal(1, await LinkAuditCountAsync(check, s.CompanyId));
        }

        using (var req = DbTestDatabase.TryCreateContext()!)
            await Docs(req).ApproveDocumentAsync(s.CompanyId, rc.Id, "tester", acknowledgeWarnings: true);
        using var after = DbTestDatabase.TryCreateContext()!;
        var i2 = await after.Documents.AsNoTracking().SingleAsync(d => d.Id == inv.Id);
        Assert.Equal((0m, DocumentStatus.Paid), (i2.BalanceDue, i2.Status));
        // JE ของใบเสร็จตัดลูกหนี้ (ไม่ลงรายได้ซ้ำแบบขายสด)
        var rcJe = await after.JournalEntries.AsNoTracking().Include(j => j.Lines)
            .Where(j => j.CompanyId == s.CompanyId && j.SourceDocumentId == rc.Id && j.Status == JournalEntryStatus.Posted).ToListAsync();
        Assert.Contains(rcJe.SelectMany(j => j.Lines), l => l.AccountId == s.ArId && l.CreditAmount == 1_000m);
        Assert.DoesNotContain(rcJe.SelectMany(j => j.Lines), l => l.AccountId == s.RevenueId && l.CreditAmount > 0m);
    }

    [Fact]
    public async Task DraftReceipt_Unlink()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var s = await SeedAsync(db);
        var inv = await InvoiceAsync(db, s, s.CustomerId, 500m);
        var rc = await ReceiptAsync(db, s, s.CustomerId, 500m);
        using (var req = DbTestDatabase.TryCreateContext()!)
            await PreviewThenLinkAsync(req, s.CompanyId, new ReceiptLinkRequest(inv.Id, rc.Id, null));
        using (var req = DbTestDatabase.TryCreateContext()!)
            Assert.True((await Links(req).CandidatesAsync(s.CompanyId, rc.Id, User)).CanUndoDraftSource);
        using (var req = DbTestDatabase.TryCreateContext()!)
            await Links(req).UndoAsync(s.CompanyId, new ReceiptLinkUndoRequest(nameof(ReceiptLinkRoute.SetDraftSource), ReceiptDocumentId: rc.Id), User);
        using (var check = DbTestDatabase.TryCreateContext()!)
            Assert.Null((await check.Documents.AsNoTracking().SingleAsync(d => d.Id == rc.Id)).RelatedDocumentId);

        // ทิศตรงข้าม (266-1-2): ใบเสร็จที่ออกเลขแล้วถอด/เปลี่ยนใบต้นทางไม่ได้ — ทั้งปุ่มถอด และฟอร์มแก้ไข
        var issued = await ReceiptAsync(db, s, s.CustomerId, 500m, DocumentStatus.Approved, relatedTo: inv.Id);
        using (var req = DbTestDatabase.TryCreateContext()!)
        {
            var ex = await Assert.ThrowsAsync<BusinessRuleException>(() => Links(req).UndoAsync(s.CompanyId,
                new ReceiptLinkUndoRequest(nameof(ReceiptLinkRoute.SetDraftSource), ReceiptDocumentId: issued.Id), User));
            Assert.Equal(ReceiptLinkPolicy.SourceCode, ex.RuleCode);
        }
        using (var check = DbTestDatabase.TryCreateContext()!)
            Assert.Equal(inv.Id, (await check.Documents.AsNoTracking().SingleAsync(d => d.Id == issued.Id)).RelatedDocumentId);
    }


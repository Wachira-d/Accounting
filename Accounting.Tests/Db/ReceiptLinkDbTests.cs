    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var s = await SeedAsync(db);
        var open = await InvoiceAsync(db, s, s.CustomerId, 300m);
        var secret = await InvoiceAsync(db, s, s.CustomerId, 300m, sensitivity: SensitivityKind.Confidential);
        var rc = await ReceiptAsync(db, s, s.CustomerId, 300m);
        using var req = DbTestDatabase.TryCreateContext()!;
        var seen = await Links(req, new SeesNothingSensitive()).CandidatesAsync(s.CompanyId, rc.Id, User);
        Assert.Contains(seen.Items, x => x.InvoiceId == open.Id);
        Assert.DoesNotContain(seen.Items, x => x.InvoiceId == secret.Id);
        // ผู้ที่ไม่เห็นใบลับ เปิดผู้สมัครจากใบลับ/พรีวิวกับใบลับ = ไม่พบ (ไม่บอกว่ามีอยู่)
        await Assert.ThrowsAsync<KeyNotFoundException>(() => Links(req, new SeesNothingSensitive()).CandidatesAsync(s.CompanyId, secret.Id, User));
        await Assert.ThrowsAsync<KeyNotFoundException>(() => Links(req, new SeesNothingSensitive())
            .PreviewAsync(s.CompanyId, new ReceiptLinkRequest(secret.Id, rc.Id, null), User));
        // ทิศตรงข้าม: ผู้ที่ไม่มีตัวกรองชั้นความลับ (เจ้าของ) เห็นครบ
        var owner = await Links(req).CandidatesAsync(s.CompanyId, rc.Id, User);
        Assert.Contains(owner.Items, x => x.InvoiceId == secret.Id);
    }


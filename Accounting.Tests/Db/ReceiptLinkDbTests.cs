    [Fact]
    public async Task CreditRoute_SameResultAsAllocateAsync()
    {
        using var db = DbTestDatabase.TryCreateContext();
        if (db == null) { _out.WriteLine("ไม่มีฐาน — ข้าม"); return; }
        var s = await SeedAsync(db);
        var inv1 = await InvoiceAsync(db, s, s.CustomerId, 1_000m);
        PaymentResponse pay;
        using (var req = DbTestDatabase.TryCreateContext()!)
            pay = await Docs(req).CreateMultiDocPaymentAsync(s.CompanyId,
                new CreatePaymentRequest(inv1.Id, Today, 1_600m, PaymentMethod.Cash, "SLIP-RL", null, null,
                    Allocations: new List<PaymentAllocationRequest> { new(inv1.Id, 1_000m) },
                    ExcessReason: UnappliedReason.UninvoicedSupply, ExcessNote: "งานงวด 2 ยังไม่ออกใบ"), "tester");
        Assert.Equal(600m, pay.UnappliedCredit);
        var inv2 = await InvoiceAsync(db, s, s.CustomerId, 600m);

        using (var req = DbTestDatabase.TryCreateContext()!)
        {
            var c = await Links(req).CandidatesAsync(s.CompanyId, inv2.Id, User);
            var row = Assert.Single(c.Items, x => x.PaymentId == pay.Id);
            Assert.Equal((true, nameof(ReceiptLinkRoute.AllocateCredit), 600m), (row.Allowed, row.Route, row.Suggested));
        }
        ReceiptLinkResult res;
        using (var req = DbTestDatabase.TryCreateContext()!)
            res = await PreviewThenLinkAsync(req, s.CompanyId, new ReceiptLinkRequest(inv2.Id, null, pay.Id));
        Assert.Equal((0m, nameof(DocumentStatus.Paid)), (res.InvoiceBalanceDue, res.InvoiceStatus));
        Assert.NotNull(res.AllocationId);

        using (var check = DbTestDatabase.TryCreateContext()!)
        {
            // สภาพเดียวกับเส้น "ใช้เงินรอจัดสรร" เดิม: แถวจัดสรรทีหลัง · เงินรอจัดสรรเป็นศูนย์ · ใบปิด
            var alloc = await check.PaymentAllocations.AsNoTracking().SingleAsync(a => a.Id == res.AllocationId);
            Assert.Equal((inv2.Id, 600m, true), (alloc.DocumentId, alloc.AllocatedAmount, alloc.IsLateAllocation));
            Assert.Equal(0m, (await check.Payments.AsNoTracking().SingleAsync(p => p.Id == pay.Id)).UnappliedAmount);
            Assert.Equal(DocumentStatus.Paid, (await check.Documents.AsNoTracking().SingleAsync(d => d.Id == inv2.Id)).Status);
            Assert.Equal(1, await LinkAuditCountAsync(check, s.CompanyId));
        }
        // ถอดผ่านปุ่มเดียวกัน = เส้นเดิม UndoAllocationAsync (ยอดค้างกลับ · เงินรอจัดสรรกลับ)
        using (var req = DbTestDatabase.TryCreateContext()!)
            await Links(req).UndoAsync(s.CompanyId, new ReceiptLinkUndoRequest(nameof(ReceiptLinkRoute.AllocateCredit), PaymentId: pay.Id, AllocationId: res.AllocationId), User);
        using (var check = DbTestDatabase.TryCreateContext()!)
        {
            Assert.Equal(600m, (await check.Documents.AsNoTracking().SingleAsync(d => d.Id == inv2.Id)).BalanceDue);
            Assert.Equal(600m, (await check.Payments.AsNoTracking().SingleAsync(p => p.Id == pay.Id)).UnappliedAmount);
        }
        // ยืนยันด้วยกุญแจพรีวิวเก่า (ข้อเท็จจริงเปลี่ยนแล้ว) = 409 RL-STALE ไม่มีอะไรถูกเขียน
        using (var req = DbTestDatabase.TryCreateContext()!)
        {
            var ex = await Assert.ThrowsAsync<BusinessRuleException>(() => Links(req).LinkAsync(s.CompanyId,
                new ReceiptLinkRequest(inv2.Id, null, pay.Id, 600m, PreviewToken: "000000000000000000000000"), User));
            Assert.Equal(ReceiptLinkPolicy.StaleCode, ex.RuleCode);
        }
    }


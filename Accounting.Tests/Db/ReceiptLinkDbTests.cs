    /// <summary>ใบแจ้งหนี้ขายที่อนุมัติแล้ว (ไม่มี VAT) + JE ตั้งลูกหนี้</summary>
    private static async Task<Document> InvoiceAsync(Accounting.Data.AccountingDbContext db, Seed s, Guid contactId, decimal amount,
        DateTime? date = null, SensitivityKind sensitivity = SensitivityKind.None)
    {
        var no = "INV-RL-" + Guid.NewGuid().ToString("N")[..8];
        var d = new Document
        {
            CompanyId = s.CompanyId, ContactId = contactId, DocumentType = DocumentType.Invoice, DocumentNumber = no,
            Status = DocumentStatus.Approved, DocumentDate = date ?? Today, SubTotal = amount, TotalAmount = amount, BalanceDue = amount,
            Currency = "THB", ExchangeRate = 1m, WhtCertAutoIssue = false, Sensitivity = sensitivity,
        };
        d.Lines.Add(new DocumentLine { LineOrder = 1, Description = "ค่าบริการ", Quantity = 1, UnitPrice = amount, Amount = amount, AccountId = s.RevenueId });
        db.Documents.Add(d);
        await db.SaveChangesAsync();
        var je = new JournalEntry
        {
            CompanyId = s.CompanyId, EntryNumber = "SV-" + no, EntryDate = d.DocumentDate, Status = JournalEntryStatus.Posted,
            JournalType = JournalType.Sales, Description = "ออกใบ " + no, Reference = no, TotalDebit = amount, TotalCredit = amount,
            SourceDocumentId = d.Id, IsAutoGenerated = true, CreatedBy = "tester",
        };
        je.Lines.Add(new JournalEntryLine { AccountId = s.ArId, DebitAmount = amount, LineOrder = 1 });
        je.Lines.Add(new JournalEntryLine { AccountId = s.RevenueId, CreditAmount = amount, LineOrder = 2 });
        db.JournalEntries.Add(je);
        await db.SaveChangesAsync();
        return d;
    }

    /// <summary>ใบเสร็จที่สร้างเอง (ไม่ใช่ของการชำระ) — สถานะ/ใบต้นทางตามที่ระบุ</summary>
    private static async Task<Document> ReceiptAsync(Accounting.Data.AccountingDbContext db, Seed s, Guid contactId, decimal amount,
        DocumentStatus status = DocumentStatus.Draft, Guid? relatedTo = null, DateTime? date = null)
    {
        var d = new Document
        {
            CompanyId = s.CompanyId, ContactId = contactId, DocumentType = DocumentType.Receipt,
            DocumentNumber = status == DocumentStatus.Draft ? $"DRAFT-{Guid.NewGuid():N}"[..14] : "RC-RL-" + Guid.NewGuid().ToString("N")[..8],
            Status = status, DocumentDate = date ?? Today, SubTotal = amount, TotalAmount = amount, BalanceDue = 0m, PaidAmount = amount,
            Currency = "THB", ExchangeRate = 1m, RelatedDocumentId = relatedTo, WhtCertAutoIssue = false,
        };
        d.Lines.Add(new DocumentLine { LineOrder = 1, Description = "รับชำระค่าบริการ", Quantity = 1, UnitPrice = amount, Amount = amount, AccountId = s.RevenueId });
        db.Documents.Add(d);
        await db.SaveChangesAsync();
        return d;
    }


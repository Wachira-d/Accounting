    private static readonly Guid User = Guid.NewGuid();

    private static async Task<ReceiptLinkResult> PreviewThenLinkAsync(Accounting.Data.AccountingDbContext db, Guid companyId, ReceiptLinkRequest req)
    {
        var p = await Links(db).PreviewAsync(companyId, req, User);
        Assert.True(p.Allowed, p.Message);
        return await Links(db).LinkAsync(companyId, req with { Amount = p.Amount, PreviewToken = p.PreviewToken }, User);
    }

    private static Task<int> LinkAuditCountAsync(Accounting.Data.AccountingDbContext db, Guid companyId)
        => db.AuditLogs.AsNoTracking().CountAsync(a => a.CompanyId == companyId && a.NewValues != null && a.NewValues.Contains(ReceiptLinkPolicy.RuleCode));


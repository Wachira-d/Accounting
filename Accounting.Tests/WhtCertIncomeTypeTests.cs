using Accounting.Helpers;
using Xunit;

namespace Accounting.Tests;

/// <summary>
/// แบบ 50 ทวิ เป็น**ฟอร์มพิมพ์สำเร็จที่พิมพ์ทุกประเภทเงินได้เป็นรายการให้ติ๊ก**
/// ⇒ ตัวอ่านเดิมที่ยอมตอบเฉพาะเมื่อ "เจอกลุ่มเดียวทั้งใบ" คืน null ทุกใบ
/// ⇒ ด่านตรวจอัตราตาม ท.ป.4/2528 ไม่เคยมีข้อมูลให้ตรวจ (ผลตรวจ 2026-09-06 · T1-08)
/// </summary>
public class WhtCertIncomeTypeTests
{
    private static string Form(params string[] extraRows)
    {
        var rows = new List<string>
        {
            "หนังสือรับรองการหักภาษี ณ ที่จ่าย",
            "ตามมาตรา 50 ทวิ แห่งประมวลรัษฎากร",
            "ประเภทเงินได้พึงประเมินที่จ่าย        จำนวนเงินที่จ่าย   ภาษีที่หักและนำส่งไว้",
            "1. เงินเดือน ค่าจ้าง ฯลฯ ตามมาตรา 40(1)",
            "2. ค่าธรรมเนียม ค่านายหน้า ฯลฯ ตามมาตรา 40(2)",
            "3. ค่าแห่งลิขสิทธิ์ ฯลฯ ตามมาตรา 40(3)",
            "4. (ก) ดอกเบี้ย ฯลฯ ตามมาตรา 40(4)(ก)",
            "   (ข) เงินปันผล ฯลฯ ตามมาตรา 40(4)(ข)",
            "5. ค่าเช่า ฯลฯ ตามมาตรา 40(5)",
            "6. วิชาชีพอิสระ ตามมาตรา 40(6)",
            "7. ค่ารับเหมา ตามมาตรา 40(7)",
        };
        rows.AddRange(extraRows);
        return string.Join('\n', rows);
    }

    [Fact]
    public void ฟอร์มติ๊ก_แถวที่มีจำนวนเงินคือประเภทจริง()
    {
        var text = Form("8. อื่น ๆ ค่าบริการ ตามมาตรา 40(8)   50,000.00   1,500.00");
        Assert.Equal("40(8) ค่าบริการ", WhtCertIncomeType.Infer(text, 50000m));
    }

    [Fact]
    public void ฟอร์มติ๊ก_ค่าเช่า()
    {
        var text = Form("5. ค่าเช่า ฯลฯ ตามมาตรา 40(5)   30,000.00   1,500.00",
            "8. อื่น ๆ ตามมาตรา 40(8)");
        // แถว 5 ที่มีตัวเลขคือแถวจริง — แถวอื่นเป็นข้อความฟอร์มเปล่า
        Assert.Equal("40(5) ค่าเช่า", WhtCertIncomeType.Infer(text, 30000m));
    }

    [Fact]
    public void สองแถวมีตัวเลข_ยอดที่ตรงกับฐานเงินได้ชนะ()
    {
        var text = Form(
            "5. ค่าเช่า ฯลฯ ตามมาตรา 40(5)   30,000.00   1,500.00",
            "7. ค่ารับเหมา ตามมาตรา 40(7)   12,000.00   360.00");
        Assert.Equal("40(7) ค่ารับเหมา", WhtCertIncomeType.Infer(text, 12000m));
        Assert.Equal("40(5) ค่าเช่า", WhtCertIncomeType.Infer(text, 30000m));
    }

    [Fact]
    public void สองแถวมีตัวเลข_แต่ไม่รู้ฐานเงินได้_ต้องไม่เดา()
    {
        var text = Form(
            "5. ค่าเช่า ฯลฯ ตามมาตรา 40(5)   30,000.00   1,500.00",
            "7. ค่ารับเหมา ตามมาตรา 40(7)   12,000.00   360.00");
        Assert.Null(WhtCertIncomeType.Infer(text, null));
    }

    [Fact]
    public void ฟอร์มเปล่าที่ไม่มีแถวไหนมีตัวเลข_ต้องไม่เดา()
    {
        // ทุกกลุ่มปรากฏหมด (เป็นข้อความฟอร์ม) — ตอบไม่ได้ = ต้องบอกว่าไม่รู้
        Assert.Null(WhtCertIncomeType.Infer(Form("8. อื่น ๆ ตามมาตรา 40(8)"), 50000m));
    }

    [Fact]
    public void ใบที่ไม่ใช่ฟอร์มติ๊ก_พฤติกรรมเดิมต้องยังใช้ได้()
    {
        var text = "ใบแจ้งหนี้ค่าบริการ\nค่าบริการรายเดือน 10,000.00\nหัก ณ ที่จ่าย 3% 300.00";
        Assert.Equal("40(8) ค่าบริการ", WhtCertIncomeType.Infer(text, 10000m));
    }

    [Fact]
    public void ข้อความว่าง_ต้องคืน_null()
    {
        Assert.Null(WhtCertIncomeType.Infer(null));
        Assert.Null(WhtCertIncomeType.Infer("   "));
    }
}
